#!/usr/bin/env python3
"""Mirror decentralized docs/ folders into one Sphinx-buildable tree.

Problem this solves
--------------------
Pluss is organized as six root packages (PlussQit, PlussMic, PlussMa, PlussPl,
PlussAI, PlussTils), each of which has topic subfolders that carry their own
docs/ folder close to the code they document (for example
PlussMa/Math/Finance/docs, PlussMa/Stats/distributions/docs,
PlussAI/NodeB/docs). Nobody wants to hand-copy those into the package's own
Sphinx tree, and nobody wants to hand-copy each package's Sphinx tree into the
root docs/sphinx build either -- that manual-copy step is exactly what used to
make root docs/sphinx drift out of sync with the real source-of-truth files.

This script removes the manual step. It mirrors a set of *source* docs/
folders into one *target* directory's `_local/` subfolder. The target's
Sphinx `index.md` references `_local` once, via a `{toctree}` block with the
`:glob:` option (see the `install-glob-toctree` subcommand below), so newly
aggregated pages are picked up automatically on the next build -- nobody needs
to edit a toctree list by hand when a new local doc is added.

Two levels of aggregation exist in this repo, both driven by this one script:

1. Package level: each package's own docs/sphinx directory aggregates every
   docs/ folder nested under that package (excluding its own docs/sphinx
   tree). Example: `PlussMa/docs/sphinx/_local/` mirrors
   `PlussMa/Math/Finance/docs`, `PlussMa/Stats/distributions/docs`, etc.

2. Root level: the root docs/sphinx directory aggregates each package's own
   (already-aggregated) docs/sphinx tree. Example: root
   `docs/sphinx/_local/PlussMic/` mirrors `PlussMic/docs/sphinx/`.

Both levels use the same rule going forward: edit the *local* file, rebuild,
and the change appears in every level above it automatically -- there is
nothing else to keep in sync by hand.

`_local/` is always fully regenerated by this script. Never hand-edit a file
under `_local/`; edit the source docs/ folder it was mirrored from instead.

Usage
-----
Package-level aggregation (scan a package root for nested docs/ folders):

    python3 aggregate_docs.py \\
        --into PlussMa/docs/sphinx \\
        --scan PlussMa

Root-level aggregation (mirror specific already-built package hubs):

    python3 aggregate_docs.py \\
        --into docs/sphinx \\
        --package-hub PlussQit=PlussQit/docs \\
        --package-hub PlussMic=PlussMic/docs/sphinx \\
        --package-hub PlussMa=PlussMa/docs \\
        --package-hub PlussPl=PlussPl/docs/sphinx \\
        --package-hub PlussAI=PlussAI/docs/sphinx \\
        --package-hub PlussTils=PlussTils/docs/sphinx
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

IGNORED_PATH_PARTS = {
    "_build", "build", "__pycache__", ".git", "node_modules", "_local",
}
# Prefixes for any directory literally named "build*" (build, build-tests, ...)
IGNORED_DIR_PREFIXES = ("build",)
MIRRORED_DOC_SUFFIXES = {
    ".md",
    ".svg",
    ".png",
    ".jpg",
    ".jpeg",
    ".gif",
    ".webp",
    ".pdf",
}

# The canonical copy of the shared chrome (topbar, sidebars, prev/next nav,
# card-grid landing page CSS) lives at the repo root's docs/sphinx/_static/.
# Every other site's own _static/ is kept in sync with these two files on
# every build, so a fix made once at the root propagates everywhere instead
# of silently forking again (see docs-lint.yml / build_docs.sh call order).
REPO_ROOT = Path(__file__).resolve().parent.parent.parent
CANONICAL_STATIC_DIR = REPO_ROOT / "docs" / "sphinx" / "_static"
SYNCED_STATIC_FILES = ("api_ref.css", "layout.js")
# If a destination file already contains one of these markers, it has grown
# genuine site-specific functionality beyond the canonical template (for
# example PlussMic's per-page API method sidebar). Overwriting it would
# silently delete that functionality, so it is left alone and reported
# instead -- the fix in that case is to merge the addition back into the
# canonical file so every site can share it, not to keep forking.
CUSTOMIZATION_MARKERS = ("buildApiMethodSidebar",)


def _is_ignored(path: Path) -> bool:
    for part in path.parts:
        if part in IGNORED_PATH_PARTS:
            return True
        if "." not in part and any(part.startswith(prefix) and part != "docs" for prefix in IGNORED_DIR_PREFIXES):
            return True
    return False


def _is_ignored_in_docs_tree(rel_dir: Path) -> bool:
    """Ignore rule for a path *inside* a docs tree. A page group may legitimately be named `build` or `builder`
    (api/procedure/build/, api/lymph/models/builder/), so only build outputs count: `build`/`build-*`/`build_*` at the top of the tree and
    `_build`/caches/`_local` anywhere."""
    for i, part in enumerate(rel_dir.parts):
        if part in IGNORED_PATH_PARTS - {"build"}:
            return True
        if i == 0 and "." not in part and (part == "build" or part.startswith(("build-", "build_"))):
            return True
    return False


def _slugify(rel_parts: tuple[str, ...]) -> str:
    cleaned = [p for p in rel_parts if p not in (".", "")]
    return "__".join(cleaned) if cleaned else "root"


def find_local_doc_sources(scan_root: Path, into: Path) -> list[tuple[Path, str]]:
    """Find every directory literally named 'docs' under scan_root.

    Excludes the `into` target itself (and anything under it) so a package's
    own docs/sphinx tree never tries to aggregate itself, and excludes build
    directories, .git, node_modules, __pycache__, and any existing _local
    mirror.
    """
    scan_root = scan_root.resolve()
    into = into.resolve()
    sources: list[tuple[Path, str]] = []

    for candidate in sorted(scan_root.rglob("docs")):
        if not candidate.is_dir():
            continue
        if _is_ignored(candidate.relative_to(scan_root).parent if candidate.parent != scan_root else Path(".")):
            pass  # parent-level ignore handled below via full-path check
        if _is_ignored(candidate):
            continue
        resolved = candidate.resolve()
        if resolved == into or into in resolved.parents or resolved in into.parents:
            continue
        rel = candidate.relative_to(scan_root)
        # rel looks like Math/Finance/docs -- slug from everything before "docs"
        slug = _slugify(rel.parts[:-1]) if len(rel.parts) > 1 else scan_root.name
        sources.append((candidate, slug))
    return sources


def plan_docs_tree(source: Path, slug: str) -> list[tuple[Path, Path]]:
    """Return [(source_file, dest_relpath_under_local_dir), ...] for markdown
    plus doc assets that pages reference relative to themselves.

    The root/site `_local/` mirror must carry not only the `.md` sources but
    also nearby images/PDFs, otherwise the aggregated site renders the text of
    a page while silently breaking its figures.
    """
    plan = []
    for source_file in sorted(source.rglob("*")):
        if not source_file.is_file():
            continue
        rel = source_file.relative_to(source)
        if _is_ignored_in_docs_tree(rel.parent):
            continue
        if source_file.suffix.lower() not in MIRRORED_DOC_SUFFIXES:
            continue
        plan.append((source_file, Path(slug) / rel))
    # Each hub's index lists its own `_local/MANIFEST` in a toctree, so the one `_local` file the mirror keeps is that manifest.
    manifest = source / "_local" / "MANIFEST.md"
    if manifest.is_file():
        plan.append((manifest, Path(slug) / "_local" / "MANIFEST.md"))
    return plan


def sync_local_dir(local_dir: Path, plan: list[tuple[Path, Path]]) -> tuple[int, list[str]]:
    """Make local_dir's contents match `plan` exactly: copy/overwrite every
    planned file, then remove any existing file under local_dir that isn't
    part of the plan (a leftover from a source that was renamed or removed).

    This is deliberately surgical rather than "rmtree then recopy": it only
    ever touches files that actually need to change, so a filesystem that
    disallows deleting some (or all) files still ends up with every live
    source correctly mirrored -- orphan cleanup is best-effort and reported,
    never fatal.
    """
    expected = {local_dir / rel for _, rel in plan}

    removed_orphans = 0
    failed_removals: list[str] = []
    if local_dir.exists():
        for existing in local_dir.rglob("*"):
            if existing.is_dir():
                continue
            if existing.name == "MANIFEST.md":
                continue
            if existing not in expected:
                try:
                    existing.unlink()
                    removed_orphans += 1
                except OSError as exc:
                    failed_removals.append(f"{existing} ({exc})")

    for source_file, rel in plan:
        out_path = local_dir / rel
        out_path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source_file, out_path)

    # Best-effort: prune now-empty directories left behind by removed orphans.
    if local_dir.exists():
        for d in sorted(local_dir.rglob("*"), key=lambda p: len(p.parts), reverse=True):
            if d.is_dir():
                try:
                    d.rmdir()  # only succeeds if already empty
                except OSError:
                    pass

    if failed_removals:
        print(f"warning: could not remove {len(failed_removals)} orphaned file(s) under {local_dir} "
              f"(filesystem may disallow deletion here); leaving them in place:", file=sys.stderr)
        for f in failed_removals[:10]:
            print(f"  - {f}", file=sys.stderr)
        if len(failed_removals) > 10:
            print(f"  ... and {len(failed_removals) - 10} more", file=sys.stderr)

    return removed_orphans, failed_removals


def sync_static_assets(into: Path) -> list[str]:
    """Copy the canonical _static/{api_ref.css,layout.js} into `into/_static/`,
    creating the directory if needed. Skips (and reports) any destination file
    that already contains a CUSTOMIZATION_MARKERS hit rather than clobbering
    site-specific additions. Returns a list of human-readable status lines.
    """
    if into.resolve() == CANONICAL_STATIC_DIR.parent.resolve():
        return []  # the canonical site never needs to sync into itself

    notes: list[str] = []
    dest_static = into / "_static"

    for filename in SYNCED_STATIC_FILES:
        src = CANONICAL_STATIC_DIR / filename
        if not src.exists():
            continue
        dest = dest_static / filename
        if dest.exists():
            try:
                existing_text = dest.read_text(errors="ignore")
            except OSError:
                existing_text = ""
            if any(marker in existing_text for marker in CUSTOMIZATION_MARKERS):
                notes.append(
                    f"kept site-specific {dest} (contains custom functionality beyond "
                    f"the canonical template -- merge upstream instead of overwriting)"
                )
                continue
        dest_static.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest)
    return notes


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--into", required=True, type=Path,
                         help="Target Sphinx source directory (its _local/ subfolder is synced to match sources).")
    parser.add_argument("--scan", action="append", default=[], type=Path,
                         help="Package root to recursively scan for nested docs/ folders. Repeatable.")
    parser.add_argument("--package-hub", action="append", default=[],
                         help="NAME=PATH pair: mirror an already-aggregated docs directory wholesale "
                              "under the explicit slug NAME (used for root-level aggregation of each "
                              "package's docs/sphinx tree, where the slug must be the package name, "
                              "not inferred from a possibly-ambiguous 'docs' or 'sphinx' path segment). "
                              "Repeatable.")
    args = parser.parse_args()

    into = args.into.resolve()
    local_dir = into / "_local"
    local_dir.mkdir(parents=True, exist_ok=True)

    # --- Build the full sync plan first, guarding against slug collisions ---
    slug_sources: dict[str, Path] = {}   # slug -> first source dir claiming it
    full_plan: list[tuple[Path, Path]] = []
    manifest_lines = ["# Aggregated Local Documentation", "",
                      "Auto-generated by `docs/scripts/aggregate_docs.py`. Do not edit files under "
                      "`_local/` directly -- edit the source `docs/` folder listed below and rebuild.", ""]
    total_sources = 0

    def claim_slug(slug: str, source_dir: Path) -> bool:
        """Return False (and print an error) if `slug` is already claimed by
        a *different* source directory -- two unrelated doc trees silently
        overwriting each other under one slug is exactly the kind of bug this
        guard exists to catch loudly instead of shipping a half-merged site.
        """
        prior = slug_sources.get(slug)
        if prior is not None and prior != source_dir:
            print(f"error: slug collision -- both {prior} and {source_dir} "
                  f"want to aggregate under _local/{slug}/. Rename one of the "
                  f"source docs/ folders or pass an explicit --package-hub "
                  f"slug to disambiguate.", file=sys.stderr)
            return False
        slug_sources[slug] = source_dir
        return True

    collision = False
    for scan_root in args.scan:
        for source_dir, slug in find_local_doc_sources(scan_root, into):
            if not claim_slug(slug, source_dir):
                collision = True
                continue
            plan = plan_docs_tree(source_dir, slug)
            if not plan:
                continue
            full_plan.extend(plan)
            total_sources += 1
            manifest_lines.append(f"- `{slug}` <- `{source_dir}` ({len(plan)} file(s))")

    for entry in args.package_hub:
        if "=" not in entry:
            print(f"error: --package-hub must be NAME=PATH, got: {entry}", file=sys.stderr)
            return 1
        slug, hub_path = entry.split("=", 1)
        hub = Path(hub_path).resolve()
        if not hub.exists():
            print(f"warning: --package-hub {slug} not found, skipping: {hub}", file=sys.stderr)
            continue
        if not claim_slug(slug, hub):
            collision = True
            continue
        plan = plan_docs_tree(hub, slug)
        full_plan.extend(plan)
        total_sources += 1
        manifest_lines.append(f"- `{slug}` <- `{hub}` ({len(plan)} file(s))")

    if collision:
        return 1

    removed_orphans, failed_removals = sync_local_dir(local_dir, full_plan)
    (local_dir / "MANIFEST.md").write_text("---\norphan: true\n---\n\n" + "\n".join(manifest_lines) + "\n")

    static_notes = sync_static_assets(into)
    for note in static_notes:
        print(f"aggregate_docs: {note}", file=sys.stderr)

    print(f"aggregate_docs: mirrored {len(full_plan)} file(s) from {total_sources} source(s) into {local_dir} "
          f"({removed_orphans} orphan(s) removed"
          + (f", {len(failed_removals)} could not be removed)" if failed_removals else ")"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
