#!/usr/bin/env python3
"""Write the table of documentation pages that pluss::tils::doc searches.

    python3 gen_doc_index.py <source root> <output .inc>

Every public page becomes one row: its title, its address on the website and the path of its source
file (see public_docs.py for which pages are public). The output is only rewritten when it changes.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import public_docs as pd  # noqa: E402


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(source, output):
    source = Path(source).resolve()
    rows = []
    for space, folder, path in pd.public_pages(source):
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        rows.append((pd.title_of(text, path), pd.slug_for(path, space, folder), path.relative_to(source).as_posix()))
    rows.sort(key=lambda row: (row[1].lower(), row[0]))
    lines = ["// Generated by PlussTils/tools/gen_doc_index.py. Do not edit.", "// title, address on the website, source path"]
    lines += [f"{{{c_string(t)}, {c_string(s)}, {c_string(p)}}}," for t, s, p in rows]
    text = "\n".join(lines) + "\n"
    out = Path(output)
    if not out.exists() or out.read_text() != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
    print(f"doc index: {len(rows)} pages")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
