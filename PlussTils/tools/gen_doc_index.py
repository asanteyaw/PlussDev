#!/usr/bin/env python3
"""Write the table of documentation pages that pluss::tils::doc searches.

    python3 gen_doc_index.py <source root> <output .inc>

Every page the website publishes becomes one row: its title, its address on the website and the
path of its source file. The rules for which files count and what their address is mirror the
website's own page sync (scripts/sync-docs.py in the website repository), so a link printed by
doc() is the link the website serves. The output is only rewritten when it changes.
"""
import re
import sys
from pathlib import Path

BLOCKED = {"_build", "_local", ".doctrees", "node_modules"}
INTERNAL = {
    "README.md", "build_outputs.md", "plussmic_docs_hub.md", "Series_Doc_Authoring_Standard.md",
    "API_Doc_Authoring_Standard.md", "CodeM_MethodRoutingPlan.md", "derivative_coverage.md", "PATCHES.md",
    "USER_GUIDE_STANDARD.md", "dl_torch_maturity_blueprint.md", "autodiff_architecture.md",
    "optimization_diff_contract.md", "plusspl_blueprint.md", "dataframe_benchmarks.md",
}


def roots(source):
    yield "guide", source / "docs" / "sphinx"
    for name, folder in (("qit", "PlussQit"), ("mic", "PlussMic"), ("ma", "PlussMa"), ("pl", "PlussPl"), ("ai", "PlussAI"), ("tils", "PlussTils")):
        yield name, source / folder / "docs"


def slug_for(path, space, folder):
    relative = path.relative_to(folder)
    if space != "guide" and relative.parts[0] == "sphinx":
        relative = Path(*relative.parts[1:])
    return f"{space}/{relative.with_suffix('').as_posix()}"


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(source, output):
    source = Path(source).resolve()
    rows = []
    for space, folder in roots(source):
        if not folder.is_dir():
            continue
        for path in sorted(folder.rglob("*.md")):
            relative = path.relative_to(folder)
            if any(part in BLOCKED for part in relative.parts) or path.is_symlink():
                continue
            if path.name in INTERNAL or (path.name.startswith("optima_") and "parity" in path.stem.lower()) or path.name.endswith("_todo.md"):
                continue
            if space == "guide" and path.name == "series_api_reference.md":
                continue
            try:
                text = path.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            heading = re.search(r"^#\s+(.+?)\s*$", text, re.MULTILINE)
            title = re.sub(r"[`*]", "", heading.group(1)).strip() if heading else path.stem.replace("_", " ").replace("-", " ").title()
            rows.append((title, slug_for(path, space, folder), path.relative_to(source).as_posix()))
    rows.sort(key=lambda row: (row[1].lower(), row[0]))
    lines = ["// Generated by PlussTils/tools/gen_doc_index.py. Do not edit.", "// title, address on the website, source path"]
    lines += [f"{{{c_string(t)}, {c_string(s)}, {c_string(p)}}}," for t, s, p in rows]
    text = "\n".join(lines) + "\n"
    out = Path(output)
    if not out.exists() or out.read_text() != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
    print(f"doc index: {len(rows)} pages")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
