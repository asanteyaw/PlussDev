#!/usr/bin/env python3
"""Generate CodeN dispatch registry include.

This is intentionally small and explicit: it exists to keep the dispatcher
surface and its error messages in sync with the set of supported ops.

Usage:
  python3 tools/codegen/gen_coden_dispatch_registry.py \
    --spec tools/codegen/coden_ops.json \
    --out  src/CodeN/compat/DispatchRegistry.inc
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import List, Dict


ARGKIND = {
    "bool": "ArgKind::kBool",
    "int": "ArgKind::kInt64",
    "int64": "ArgKind::kInt64",
    "double": "ArgKind::kDouble",
    "string": "ArgKind::kString",
    "intlist": "ArgKind::kIntList",
}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    spec_path = Path(args.spec)
    out_path = Path(args.out)

    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    ops: List[Dict] = spec.get("ops", [])

    lines: List[str] = []
    lines.append("// This file is generated by tools/codegen/gen_coden_dispatch_registry.py")
    lines.append("// DO NOT EDIT BY HAND. Edit tools/codegen/coden_ops.json instead.")
    lines.append("\n#pragma once\n")
    lines.append("#include <cstdint>\n#include <string_view>\n")
    lines.append("namespace pluss::coden::_compat {\n")
    lines.append("enum class ArgKind : std::uint8_t {\n  kNone=0, kBool, kInt64, kDouble, kString, kIntList\n};\n")
    lines.append("struct OpSig {\n  std::string_view group;\n  std::string_view name;\n  std::string_view pretty;\n  std::uint8_t argc;\n  ArgKind a0{ArgKind::kNone};\n  ArgKind a1{ArgKind::kNone};\n  ArgKind a2{ArgKind::kNone};\n};\n")
    lines.append("inline constexpr OpSig kOpSigs[] = {")

    for op in ops:
        group = op["group"]
        name = op["name"]
        pretty = op.get("pretty", f"{name}(...)" )
        a = op.get("args", [])
        argc = len(a)
        kinds = [ARGKIND.get(x, "ArgKind::kNone") for x in a]
        while len(kinds) < 3:
            kinds.append("ArgKind::kNone")
        lines.append(
            f"  {{\"{group}\", \"{name}\", \"{pretty}\", {argc}, {kinds[0]}, {kinds[1]}, {kinds[2]}}},"
        )

    lines.append("};\n")
    lines.append("} // namespace pluss::coden::_compat\n")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"[codegen] wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
