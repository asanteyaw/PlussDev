#!/usr/bin/env python3
"""Generate primitive Series autograd helpers from derivatives.yaml.

This is intentionally a small, static code generator rather than a runtime
registry. The goal is the same shape used in the local PyTorch tree:
derivative formulas live in a spec file, then compile down into ordinary C++.
"""

from __future__ import annotations

import argparse
from pathlib import Path


def parse_entries(text: str) -> list[dict[str, str]]:
    entries: list[dict[str, str]] = []
    current: dict[str, str] | None = None
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("- name:"):
            if current is not None:
                entries.append(current)
            current = {"name": line.split(":", 1)[1].strip()}
            continue
        if current is None:
            continue
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        current[key.strip()] = value.strip()
    if current is not None:
        entries.append(current)
    return entries


def render_reverse_header(entries: list[dict[str, str]], spec_path: Path) -> str:
    entries = [entry for entry in entries if entry.get("arity", "unary") == "unary"]
    lines = [
        "// @generated by tools/codegen/generate_series_autograd_gen.py. Do not edit manually.",
        f"// Source: {spec_path.name}",
        "#pragma once",
        "",
        "namespace generated::autograd_unary {",
        "",
        "enum class Rule {",
    ]
    for entry in entries:
        lines.append(f"  {entry['rule']},")
    lines.extend(
        [
            "};",
            "",
            "inline Series apply(Rule rule, const Series& out_sens, const Series& input,",
            "                    const Series& output) {",
            "  (void)input;",
            "  (void)output;",
            "  switch (rule) {",
        ]
    )
    for entry in entries:
        lines.append(f"    case Rule::{entry['rule']}: return {entry['reverse']};")
    lines.extend(
        [
            '  }',
            '  PLUSS_FAIL("generated::autograd_unary::apply: unsupported unary rule");',
            "}",
            "",
            "} // namespace generated::autograd_unary",
            "",
        ]
    )
    return "\n".join(lines)


def render_binary_reverse_header(entries: list[dict[str, str]], spec_path: Path) -> str:
    entries = [entry for entry in entries if entry.get("arity") == "binary"]
    lines = [
        "// @generated by tools/codegen/generate_series_autograd_gen.py. Do not edit manually.",
        f"// Source: {spec_path.name}",
        "#pragma once",
        "",
        "namespace generated::autograd_binary {",
        "",
        "enum class Rule {",
    ]
    for entry in entries:
        lines.append(f"  {entry['rule']},")
    lines.extend(
        [
            "};",
            "",
            "inline Series apply_lhs(Rule rule, const Series& out_sens,",
            "                        const Series& lhs, const Series& rhs, const Series& output) {",
            "  (void)output;",
            "  switch (rule) {",
        ]
    )
    for entry in entries:
        lines.append(f"    case Rule::{entry['rule']}: return {entry['lhs_reverse']};")
    lines.extend(
        [
            "  }",
            '  PLUSS_FAIL("generated::autograd_binary::apply_lhs: unsupported binary rule");',
            "}",
            "",
            "inline Series apply_rhs(Rule rule, const Series& out_sens,",
            "                        const Series& lhs, const Series& rhs, const Series& output) {",
            "  switch (rule) {",
        ]
    )
    for entry in entries:
        lines.append(f"    case Rule::{entry['rule']}: return {entry['rhs_reverse']};")
    lines.extend(
        [
            "  }",
            '  PLUSS_FAIL("generated::autograd_binary::apply_rhs: unsupported binary rule");',
            "}",
            "",
            "} // namespace generated::autograd_binary",
            "",
        ]
    )
    return "\n".join(lines)


def render_diff_inc(entries: list[dict[str, str]], spec_path: Path) -> str:
    lines = [
        "// @generated by tools/codegen/generate_series_autograd_gen.py. Do not edit manually.",
        f"// Source: {spec_path.name}",
        "",
    ]
    for entry in entries:
        if entry.get("arity", "unary") != "unary":
            continue
        trace = entry.get("trace")
        dual_primal = entry.get("dual_primal")
        dual_tangent = entry.get("dual_tangent")
        if not trace or not dual_primal or not dual_tangent:
            continue
        name = entry["name"]
        lines.extend(
            [
                f"inline Trace {name}(const Trace& x) {{",
                f'  detail::require_defined_(x.value(), "{name}");',
                f"  return Trace({trace});",
                "}",
                "",
                f"inline DualTrace {name}(const DualTrace& x) {{",
                f"  const Series primal = {dual_primal};",
                f"  return DualTrace(primal, {dual_tangent});",
                "}",
                "",
            ]
        )
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", required=True, help="Path to derivative spec")
    ap.add_argument("--out-reverse", required=True, help="Generated reverse helper header")
    ap.add_argument("--out-binary-reverse", required=True, help="Generated binary reverse helper header")
    ap.add_argument("--out-diff", required=True, help="Generated diff helper include")
    args = ap.parse_args()

    spec_path = Path(args.spec)
    entries = parse_entries(spec_path.read_text(encoding="utf-8"))

    reverse_out = Path(args.out_reverse)
    reverse_out.parent.mkdir(parents=True, exist_ok=True)
    reverse_out.write_text(render_reverse_header(entries, spec_path), encoding="utf-8")

    binary_reverse_out = Path(args.out_binary_reverse)
    binary_reverse_out.parent.mkdir(parents=True, exist_ok=True)
    binary_reverse_out.write_text(
        render_binary_reverse_header(entries, spec_path), encoding="utf-8")

    diff_out = Path(args.out_diff)
    diff_out.parent.mkdir(parents=True, exist_ok=True)
    diff_out.write_text(render_diff_inc(entries, spec_path), encoding="utf-8")


if __name__ == "__main__":
    main()
