#!/usr/bin/env python3
"""Generate CodeH method-surface headers.

This emits:
  - TimelineMethodsGen.h
  - DurationMethodsGen.h
  - TimeIndexMethodsGen.h

The large, repetitive Timeline method families are driven by TSV specs.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


def read_tsv(path: Path) -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if "\t" not in line:
            raise ValueError(f"Bad TSV line (missing tab): {line}")
        name, value = line.split("\t", 1)
        rows.append((name.strip(), value.strip()))
    return rows


_INVOKE_ARGS_RE = re.compile(
    r'(::pluss::codeh::_compat::invoke<[^>]+>\("[^"]+",\s*[^,]+),\s*(.+)\);'
)


def normalize_codeh_invoke_lines(lines: list[str]) -> list[str]:
    out: list[str] = []
    for line in lines:
        m = _INVOKE_ARGS_RE.search(line)
        if not m:
            out.append(line)
            continue
        args = m.group(2).strip()
        if args.startswith("{"):
            out.append(line)
            continue
        out.append(
            line[: m.start()]
            + f"{m.group(1)}, {{{args}}});"
            + line[m.end() :]
        )
    return out


