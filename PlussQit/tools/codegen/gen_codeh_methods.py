def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--timeline-dt-fields", required=True, type=Path)
    ap.add_argument("--timeline-predicates", required=True, type=Path)
    ap.add_argument("--timeline-strftime", required=True, type=Path)
    ap.add_argument("--out-dir", required=True, type=Path)
    args = ap.parse_args()

    out_dir = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    dt_fields = read_tsv(args.timeline_dt_fields)
    predicates = read_tsv(args.timeline_predicates)
    strftime_methods = read_tsv(args.timeline_strftime)

    emit_timeline(out_dir, dt_fields, predicates, strftime_methods)
    emit_duration(out_dir)
    emit_timeindex(out_dir)


if __name__ == "__main__":
    main()
