#!/usr/bin/env python3
"""Generate CodeN dispatch fallback signatures from generated method declarations.

This keeps Dispatch.cpp synchronized with generated Note/Chord method surfaces:
any declared method that is not manually wired still routes to a clear
"declared but not implemented" dispatcher error rather than "No such op".
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


DECL_RE = re.compile(r"^\s*(.+?)\s+([A-Za-z_][A-Za-z0-9_]*)\((.*)\)\s+const;\s*$")


def split_top_level(args: str) -> list[str]:
    s = args.strip()
    if not s:
        return []
    out: list[str] = []
    cur: list[str] = []
    depth_angle = 0
    depth_paren = 0
    for ch in s:
        if ch == "<":
            depth_angle += 1
        elif ch == ">":
            depth_angle = max(0, depth_angle - 1)
        elif ch == "(":
            depth_paren += 1
        elif ch == ")":
            depth_paren = max(0, depth_paren - 1)

        if ch == "," and depth_angle == 0 and depth_paren == 0:
            frag = "".join(cur).strip()
            if frag:
                out.append(frag)
            cur = []
            continue
        cur.append(ch)

    frag = "".join(cur).strip()
    if frag:
        out.append(frag)
    return out


def parse_decls(path: Path) -> list[tuple[str, str, int]]:
    out: list[tuple[str, str, int]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        m = DECL_RE.match(line)
        if not m:
            continue
        ret = m.group(1).strip()
        name = m.group(2).strip()
        argc = len(split_top_level(m.group(3)))
        out.append((ret, name, argc))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--note-decls", required=True)
    ap.add_argument("--chord-decls", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    note_decls = parse_decls(Path(args.note_decls))
    chord_decls = parse_decls(Path(args.chord_decls))

    groups: dict[str, set[tuple[str, int]]] = {
        "Chord": set(),
        "ChordBool": set(),
        "ChordTokenBatch": set(),
        "Note": set(),
        "NoteChord": set(),
        "NoteU8List": set(),
        "NoteI64List": set(),
        "NoteTokenBatch": set(),
    }

    for ret, name, argc in chord_decls:
        if ret == "Chord":
            groups["Chord"].add((name, argc))
        elif ret == "bool":
            groups["ChordBool"].add((name, argc))
        elif ret == "TokenBatch":
            groups["ChordTokenBatch"].add((name, argc))

    for ret, name, argc in note_decls:
        if ret == "Note":
            groups["Note"].add((name, argc))
        elif ret == "Chord":
            groups["NoteChord"].add((name, argc))
        elif ret == "::std::vector<::std::uint8_t>":
            groups["NoteU8List"].add((name, argc))
        elif ret == "::std::vector<::std::int64_t>":
            groups["NoteI64List"].add((name, argc))
        elif ret == "TokenBatch":
            groups["NoteTokenBatch"].add((name, argc))

    def emit_group(lines: list[str], sym: str, items: set[tuple[str, int]]) -> None:
        lines.append(f"inline constexpr ::std::array<DeclDispatchSig, {len(items)}> {sym} = {{{{")
        for name, argc in sorted(items, key=lambda x: (x[0], x[1])):
            lines.append(f'  {{"{name}", {argc}}},')
        lines.append("}};")
        lines.append("")

    lines: list[str] = []
    lines.append("// AUTO-GENERATED by tools/codegen/gen_coden_decl_dispatch_fallbacks.py")
    lines.append("// DO NOT EDIT. Regenerate from generated Note/Chord declaration headers.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <array>")
    lines.append("#include <cstddef>")
    lines.append("#include <string_view>")
    lines.append("")
    lines.append("namespace pluss::coden::_compat {")
    lines.append("struct DeclDispatchSig {")
    lines.append("  ::std::string_view name;")
    lines.append("  ::std::size_t argc;")
    lines.append("};")
    lines.append("")
    emit_group(lines, "kDeclChordSigs", groups["Chord"])
    emit_group(lines, "kDeclChordBoolSigs", groups["ChordBool"])
    emit_group(lines, "kDeclChordTokenBatchSigs", groups["ChordTokenBatch"])
    emit_group(lines, "kDeclNoteSigs", groups["Note"])
    emit_group(lines, "kDeclNoteChordSigs", groups["NoteChord"])
    emit_group(lines, "kDeclNoteU8ListSigs", groups["NoteU8List"])
    emit_group(lines, "kDeclNoteI64ListSigs", groups["NoteI64List"])
    emit_group(lines, "kDeclNoteTokenBatchSigs", groups["NoteTokenBatch"])
    lines.append("} // namespace pluss::coden::_compat")
    lines.append("")

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"[codegen] wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
