#!/usr/bin/env python3
import argparse, pathlib, re, textwrap

def write(path: pathlib.Path, s: str):
  path.parent.mkdir(parents=True, exist_ok=True)
  path.write_text(textwrap.dedent(s).lstrip())

SIG_RE = re.compile(r"^\s*(Series|Series&)\s+([a-zA-Z_]\w*)\s*\((.*)\)\s*;\s*$")
SERIES_METHOD_RE = re.compile(r"^\s*(?:Series|Series&|bool|std::int64_t|void)\s+([a-zA-Z_]\w*)\s*\(", re.M)

def split_params(arglist: str):
  arglist = arglist.strip()
  if not arglist:
    return []
  parts = []
  depth = 0
  cur = []
  for ch in arglist:
    if ch == "," and depth == 0:
      parts.append("".join(cur).strip())
      cur = []
      continue
    if ch in "<({[":
      depth += 1
    elif ch in ">)}]":
      depth -= 1
    cur.append(ch)
  if cur:
    parts.append("".join(cur).strip())
  return parts

def parse_opsinternal(text: str):
  ops = []
  for ln in text.splitlines():
    m = SIG_RE.match(ln)
    if not m:
      continue
    ret, name, args = m.group(1), m.group(2), m.group(3)
    params = split_params(args)
    ops.append((ret, name, params))
  return ops

def param_name(p: str) -> str:
  p = p.split("=")[0].strip()
  return p.split()[-1]

def load_existing_method_names(series_h_text: str) -> set[str]:
  # Conservative: skip generating any method whose name already exists anywhere in Series.h.
  return set(SERIES_METHOD_RE.findall(series_h_text))

def render_method(ret, name, params):
  if not params:
    return None
  first = params[0]
  rest = params[1:]
  if "Series" not in first:
    return None

  is_inplace = (ret == "Series&")
  const = "" if is_inplace else " const"
  rest_sig = ", ".join(rest)
  fwd = ", ".join([param_name(p) for p in rest])
  if fwd:
    call = f"pluss::codem::ops_internal::{name}(*this, {fwd})"
  else:
    call = f"pluss::codem::ops_internal::{name}(*this)"

  if ret == "Series":
    decl = f"  Series {name}({rest_sig}){const};"
    defin = f"Series Series::{name}({rest_sig}){const} {{ return {call}; }}"
  else:
    decl = f"  Series& {name}({rest_sig});"
    defin = f"Series& Series::{name}({rest_sig}) {{ return {call}; }}"
  return decl, defin

def main():
  ap = argparse.ArgumentParser()
  ap.add_argument("--opsinternal", required=True)
  ap.add_argument("--series-header", required=True)
  ap.add_argument("--out-decls", required=True)
  ap.add_argument("--out-defs", required=True)
  args = ap.parse_args()

  ops_text = pathlib.Path(args.opsinternal).read_text()
  series_text = pathlib.Path(args.series_header).read_text()

  existing = load_existing_method_names(series_text)
  ops = parse_opsinternal(ops_text)

  decls = ["// @generated by generate_series_methods_from_opsinternal.py", ""]
  defs  = ["// @generated by generate_series_methods_from_opsinternal.py", ""]
  seen = set()

  for ret, name, params in ops:
    if name in existing:
      continue
    key = (name, tuple(params), ret)
    if key in seen:
      continue
    seen.add(key)
    out = render_method(ret, name, params)
    if not out:
      continue
    d, f = out
    decls.append(d)
    defs.append(f)

  write(pathlib.Path(args.out_decls), "\n".join(decls) + "\n")
  write(pathlib.Path(args.out_defs),  "\n".join(defs) + "\n")

if __name__ == "__main__":
  main()
