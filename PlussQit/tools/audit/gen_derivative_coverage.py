#!/usr/bin/env python3
"""Generate docs/derivative_coverage.md — an audit of where every differentiable
Series op gets its reverse (and forward-mode) rule.

Three tiers, mirroring the local PyTorch split (declarative `derivatives.yaml`
+ hand-written `FunctionsManual.cpp`):

  yaml        a declarative entry in src/CodeM/native/derivatives.yaml — the
              formula is codegen'd into the reverse/dual helpers
  hand-node   an explicit reverse node wired by a `maybe_link_*` / `bind_*`
              helper in the operator implementation (non-elementwise families:
              indexing, scatter, reductions, views, linalg)
  composite   no explicit node; the op decomposes into differentiable
              primitives and gets its gradient transitively (torch's
              CompositeImplicitAutograd model)

The report lists the yaml and hand-node ops explicitly; everything else on the
public surface is composite-or-nondifferentiable and is covered by the
finite-difference sweep + the libtorch oracle rather than a dedicated rule.

Run from the PlussQit source root:
    python3 tools/audit/gen_derivative_coverage.py
"""
from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(".")
YAML = ROOT / "src/CodeM/native/derivatives.yaml"
IMPL_FILES = [
    ROOT / "src/CodeM/core/OpsInternal.cpp",
    ROOT / "src/CodeM/compat/OpsInternal.cpp",
    ROOT / "src/CodeM/compat/Invoke.cpp",
    ROOT / "src/CodeM/compat/LinearAlgFunctional.cpp",
]
OUT = ROOT / "docs/derivative_coverage.md"

# op-name string literal in a `maybe_link_*(out, a, "NAME", ...)` /
# `bind_*_backward_(..., "NAME", ...)` call, and `link->op_name = "NAME"`.
HAND_CALL = re.compile(
    r"(maybe_link_[a-z_]+_|bind_[a-z_]+backward_)\([^;\"]*?\"([a-z0-9_:]+)\"", re.S)
OPNAME_ASSIGN = re.compile(r'->op_name\s*=\s*"([a-z0-9_:]+)"')

# Not real op names: the generic unary-fallback tag and dispatch-mode flags
# that happen to be the first string literal inside some call.
NOISE = {
    "unary", "true", "false", "yes", "no", "on", "off", "native", "metal",
    "auto", "cpu", "mps", "cuda",
}


def yaml_entries() -> list[tuple[str, str, bool]]:
    """(name, rule, has_forward_mode) for each derivatives.yaml entry."""
    text = YAML.read_text()
    blocks = re.split(r"\n(?=- name:)", text)
    out = []
    for b in blocks:
        m = re.search(r"- name:\s*([a-z0-9_]+)", b)
        if not m:
            continue
        name = m.group(1)
        rule = (re.search(r"\brule:\s*([A-Za-z0-9]+)", b) or [None, "-"])[1]
        has_fwd = bool(re.search(r"\bdual_tangent:", b))
        out.append((name, rule, has_fwd))
    return out


def hand_node_ops() -> dict[str, set[str]]:
    """op name -> set of helper families that wire its reverse node."""
    found: dict[str, set[str]] = {}
    for f in IMPL_FILES:
        if not f.exists():
            continue
        text = f.read_text()
        for helper, name in HAND_CALL.findall(text):
            if name in NOISE:
                continue
            found.setdefault(name, set()).add(helper.rstrip("_"))
        for name in OPNAME_ASSIGN.findall(text):
            if name in NOISE:
                continue
            found.setdefault(name, set()).add("SourceLink")
    return found


def main() -> int:
    if not YAML.exists():
        print("run from the PlussQit source root", file=sys.stderr)
        return 2

    ys = yaml_entries()
    yaml_names = {n for n, _, _ in ys}
    unary = [e for e in ys if e[1] not in {"Add", "Sub", "Mul", "Div", "Pow", "Maximum", "Minimum"}]
    binary = [e for e in ys if e[1] in {"Add", "Sub", "Mul", "Div", "Pow", "Maximum", "Minimum"}]

    hand = hand_node_ops()
    # drop names already covered declaratively (they route through the generated
    # rule via maybe_link_unary_rule_/binary; the grep also catches the wrapper)
    hand_only = {k: v for k, v in sorted(hand.items()) if k not in yaml_names}

    L: list[str] = []
    W = L.append
    W("# Series derivative coverage")
    W("")
    W("<!-- GENERATED by tools/audit/gen_derivative_coverage.py — do not edit. -->")
    W("")
    W("Where each differentiable `Series` op gets its reverse (and forward-mode)")
    W("rule. Same split as the local PyTorch tree: a declarative")
    W("`src/CodeM/native/derivatives.yaml` for elementwise primitives, hand-written")
    W("nodes for the structural / indexing / reduction / linalg families, and")
    W("transitive (composite) gradients for everything built out of those.")
    W("")
    W(f"- **{len(unary)}** declarative unary primitive rules")
    W(f"- **{len(binary)}** declarative binary primitive rules")
    W(f"- **{len(hand_only)}** ops with an explicit hand-written reverse node")
    W(f"- **{len(unary) + len(binary) + len(hand_only)}** ops total with a dedicated derivative")
    W("- everything else on the public surface is composite-transitive or")
    W("  non-differentiable; correctness is pinned by")
    W("  `tests/CodeM/test_autodiff_sweep.cpp` (finite-difference) and")
    W("  `tests/CodeM/test_patch177_cpu_torch_autograd_parity.cpp` (libtorch oracle)")
    W("")
    W("This table is a **static index** parsed from the sources. The runtime-")
    W("authoritative list of what actually forms a reverse node is the")
    W("`[autodiff-sweep]` classification report; per-op libtorch parity lives in")
    W("the oracle's `[generated]` / `[parity]` cases. Regenerate this file with")
    W("`python3 tools/audit/gen_derivative_coverage.py` after changing")
    W("`derivatives.yaml` or a `maybe_link_*` call site.")
    W("")
    W("## Declarative primitive rules (`derivatives.yaml`)")
    W("")
    W("| op | rule | reverse | forward-mode |")
    W("|----|------|---------|--------------|")
    for name, rule, fwd in unary + binary:
        W(f"| `{name}` | `{rule}` | yes | {'yes' if fwd else '—'} |")
    W("")
    W("## Explicit hand-written reverse nodes")
    W("")
    W("Non-elementwise ops whose backward is wired directly in the operator")
    W("implementation (indexing, scatter, gather, reductions that route through")
    W("selected indices, views / alias lineage, and the matmul / linalg family).")
    W("")
    W("| op | wired by |")
    W("|----|----------|")
    for name, helpers in hand_only.items():
        W(f"| `{name}` | {', '.join(f'`{h}`' for h in sorted(helpers))} |")
    W("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT}")
    print(f"  {len(unary)} unary + {len(binary)} binary declarative rules; "
          f"{len(hand_only)} hand-node ops")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
