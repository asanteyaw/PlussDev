#!/usr/bin/env python3
"""Generate tests/CodeM/test_series_routing_manifest.cpp.

Every generated `Series` wrapper in SeriesMethodsGen.h forwards to the string
dispatch in Invoke.cpp. A wrapper whose (name, arity, arg-types) has no branch
there falls to the generic backstop, which under strict-unrouted mode raises.

The emitted test calls every generated overload once with best-effort synthetic
arguments while strict mode is on, and classifies the outcome:

  ROUTED     the call returned, or raised something OTHER than the unrouted
             backstop error (a shape/dtype complaint still proves a real kernel
             was reached)
  UNROUTED   the call raised the strict-mode "Unrouted op" error -- the method
             is public but has no implementation for this signature

The test fails if any UNROUTED row is not on the explicit allowlist, and always
writes the full manifest to `series_routing_manifest.txt` in the run directory.

Run from the PlussQit source root:
    python3 tools/audit/gen_series_routing_manifest.py
"""
from __future__ import annotations

import pathlib
import re
import sys

SRC = pathlib.Path("src/CodeM/generated/SeriesMethodsGen.h")
OUT = pathlib.Path("tests/CodeM/test_series_routing_manifest.cpp")

# "name(sig)" entries the strict-mode backstop fires on: public wrappers with no
# real implementation for that signature. Keeps the gate meaningful for the rest
# while each is scheduled for implementation or a precise loud rejection.
# Populated from the first manifest run; the goal is to drive this list to empty.
KNOWN_UNROUTED: list[str] = [
]

# Wrapper definition:  <ret> name(<params>) const { return <invoke|invoke_>("op", *this[, {args}]); }
WRAPPER = re.compile(
    r'^\s*(Series&?|[\w:<>,\s]+?)\s+([a-z][A-Za-z0-9_]*)\s*\(([^)]*)\)\s*const\s*\{\s*'
    r'return\s+pluss::codem::_compat::(invoke_?)\(\s*"([a-z0-9_]+)"\s*(.*?)\);\s*\}',
    re.M,
)


def base_type(param: str) -> str:
    """'const Series& other = x' -> 'const Series&'."""
    t = re.sub(r'=.*$', '', param).strip()          # drop default value
    t = re.sub(r'\s+[A-Za-z_]\w*$', '', t).strip()  # drop parameter name
    return t


def synth_arg(ptype: str, idx: int) -> tuple[str, str | None]:
    """Return (expression, pre-statement-or-None) for a parameter type."""
    t = base_type(ptype)
    if t == "const Series&":
        return ("mate", None)
    if t == "std::int64_t":
        return ("INT64_C(0)", None)
    if t == "double":
        return ("0.5", None)
    if t == "bool":
        return ("false", None)
    if t == "const std::string&":
        return ('std::string("sum")', None)
    if t == "pluss::msharp::RangeView::Int":
        var = f"il{idx}"
        return (f"pluss::msharp::RangeView::Int({var})",
                f"std::vector<std::int64_t> {var}{{1, 1}};")
    # Unknown: bail so we notice and extend the table.
    return ("", None)


def main() -> int:
    if not SRC.exists():
        print(f"cannot find {SRC}; run from the PlussQit source root", file=sys.stderr)
        return 2
    text = SRC.read_text()

    probes: list[tuple[str, str, list[str], list[str]]] = []
    skipped: list[str] = []
    for m in WRAPPER.finditer(text):
        _ret, name, plist, _kind, op, _tail = m.groups()
        params = [p.strip() for p in plist.split(",") if p.strip()]
        pres: list[str] = []
        args: list[str] = []
        ok = True
        for i, p in enumerate(params):
            expr, pre = synth_arg(p, i)
            if not expr:
                ok = False
                break
            if pre:
                pres.append(pre)
            args.append(expr)
        sig = "(" + ", ".join(base_type(p) for p in params) + ")"
        if not ok:
            skipped.append(f"{name}{sig}")
            continue
        call = f"s.{name}(" + ", ".join(args) + ")"
        probes.append((op, sig, pres, [call]))

    lines: list[str] = []
    W = lines.append
    W("// GENERATED by tools/audit/gen_series_routing_manifest.py -- do not edit.")
    W("//")
    W("// Calls every generated Series wrapper once under strict-unrouted mode and")
    W("// classifies the outcome ROUTED / UNROUTED / CRASHED. A CRASHED row means the")
    W("// synthetic arguments were lethal to a real kernel (still routed); only")
    W("// UNROUTED rows -- the strict-mode backstop error -- fail the gate, and only")
    W("// when not on the known_unrouted() allowlist. Writes the full classification")
    W("// to series_routing_manifest.txt in the run directory.")
    W("")
    W("#include <catch2/catch_test_macros.hpp>")
    W("")
    W("#include <pluss/codem/codem.h>")
    W("#include <pluss/codem/series_factory.h>")
    W("")
    W('#include "CodeM/compat/Invoke.h"')
    W('#include "MSharp/RangeView.h"')
    W("")
    W("#include <sys/wait.h>")
    W("#include <unistd.h>")
    W("")
    W("#include <cstdio>")
    W("#include <cstdlib>")
    W("#include <fstream>")
    W("#include <set>")
    W("#include <string>")
    W("#include <vector>")
    W("")
    W("namespace {")
    W("")
    W("using pluss::ScalarType;")
    W("using pluss::Series;")
    W("using pluss::make_series;")
    W("")
    W("enum class R { ROUTED, UNROUTED, CRASHED };")
    W("")
    W("struct Row { std::string key; R r; };")
    W("std::vector<Row>& rows() { static std::vector<Row> v; return v; }")
    W("")
    W('const char* kManifestPath = "series_routing_manifest.txt";')
    W("std::ofstream& sink() {")
    W("  static std::ofstream s(kManifestPath, std::ios::trunc);")
    W("  return s;")
    W("}")
    W("")
    W("Series probe_input() {")
    W("  return make_series(std::vector<double>{0.3, -0.7, 1.1, 0.4, -0.2, 0.9}, {2, 3})")
    W("      .to(ScalarType::Float64);")
    W("}")
    W("")
    W("// Each probe runs in a forked child so a kernel that segfaults or aborts on")
    W("// the deliberately-wrong synthetic arguments is contained: the parent still")
    W("// records a verdict and moves on. The child reports its classification over a")
    W("// pipe; a child that dies by signal (or writes nothing) is CRASHED, which")
    W("// means \"reached a real kernel that did not like the args\" -- not a routing")
    W("// failure. Only the strict-mode backstop error is UNROUTED.")
    W("template <class F>")
    W("void probe(const std::string& name, const std::string& sig, F&& f) {")
    W("  const std::string key = name + sig;")
    W("  int fds[2];")
    W("  if (pipe(fds) != 0) { rows().push_back({key, R::CRASHED});")
    W('    sink() << "CRASHED\\t" << key << "\\tpipe() failed\\n"; sink().flush(); return; }')
    W("  const pid_t pid = fork();")
    W("  if (pid == 0) {")
    W("    ::close(fds[0]);")
    W('    std::freopen("/dev/null", "w", stderr);')
    W('    std::string verdict = "ROUTED";')
    W("    std::string detail;")
    W("    try {")
    W("      (void)f();")
    W("    } catch (const std::exception& e) {")
    W("      const std::string w = e.what();")
    W('      const bool unrouted = w.find("Unrouted") != std::string::npos &&')
    W('                            w.find("strict mode") != std::string::npos;')
    W('      verdict = unrouted ? "UNROUTED" : "ROUTED";')
    W("      detail = w.substr(0, 160);")
    W("    } catch (...) {")
    W('      detail = "non-std exception";')
    W("    }")
    W('    std::string line = verdict + "\\t" + key;')
    W('    if (!detail.empty()) line += "\\t" + detail;')
    W("    const ssize_t wr = ::write(fds[1], line.data(), line.size());")
    W("    (void)wr;")
    W("    ::close(fds[1]);")
    W("    _exit(0);")
    W("  }")
    W("  ::close(fds[1]);")
    W("  std::string got;")
    W("  char buf[512];")
    W("  ssize_t n;")
    W("  while ((n = ::read(fds[0], buf, sizeof buf)) > 0) got.append(buf, static_cast<std::size_t>(n));")
    W("  ::close(fds[0]);")
    W("  int status = 0;")
    W("  ::waitpid(pid, &status, 0);")
    W("  R r;")
    W("  std::string outline;")
    W("  if (!got.empty() && !WIFSIGNALED(status)) {")
    W("    outline = got;")
    W('    r = got.rfind("UNROUTED\\t", 0) == 0 ? R::UNROUTED : R::ROUTED;')
    W("  } else {")
    W("    r = R::CRASHED;")
    W('    outline = "CRASHED\\t" + key + "\\t" +')
    W("              (WIFSIGNALED(status)")
    W('                   ? std::string("fatal signal ") + std::to_string(WTERMSIG(status))')
    W('                   : std::string("child produced no verdict"));')
    W("  }")
    W("  rows().push_back({key, r});")
    W('  sink() << outline << "\\n";')
    W("  sink().flush();")
    W("}")
    W("")
    W("// Signatures known to be public-but-unimplemented today (the strict-mode")
    W("// backstop fires). Each must be either implemented or converted to a precise")
    W("// loud rejection; until then it is tracked here so the gate stays meaningful")
    W("// for everything else. Populated from the first manifest run.")
    W("const std::set<std::string>& known_unrouted() {")
    W("  static const std::set<std::string> s{")
    for entry in KNOWN_UNROUTED:
        W(f'      "{entry}",')
    W("  };")
    W("  return s;")
    W("}")
    W("")
    W("}  // namespace")
    W("")
    W('TEST_CASE("series routing manifest", "[routing-manifest][audit]") {')
    W("  const bool prev = pluss::codem::_compat::strict_unrouted();")
    W("  pluss::codem::_compat::set_strict_unrouted(true);")
    W("")
    for op, sig, pres, calls in probes:
        stmt = f'  probe("{op}", "{sig}", [&]{{ Series s = probe_input(); Series mate = probe_input(); '
        for pre in pres:
            stmt += pre + " "
        stmt += f'return {calls[0]}; }});'
        W(stmt)
    W("")
    W("  pluss::codem::_compat::set_strict_unrouted(prev);")
    W("")
    W("  int routed = 0, unrouted = 0, crashed = 0;")
    W("  for (const auto& row : rows()) {")
    W("    if (row.r == R::UNROUTED) ++unrouted;")
    W("    else if (row.r == R::CRASHED) ++crashed;")
    W("    else ++routed;")
    W("  }")
    W('  sink() << "# " << routed << " routed, " << unrouted << " unrouted, "')
    W('         << crashed << " crashed\\n";')
    W("  sink().flush();")
    W('  WARN("routing manifest: " << routed << " routed, " << unrouted')
    W('       << " unrouted, " << crashed << " crashed (see " << kManifestPath << ")");')
    W("")
    W("  std::vector<std::string> newly;")
    W("  for (const auto& row : rows()) {")
    W("    if (row.r == R::UNROUTED && !known_unrouted().count(row.key)) newly.push_back(row.key);")
    W("  }")
    W('  for (const auto& k : newly) UNSCOPED_INFO("newly unrouted: " << k);')
    W("  CHECK(newly.empty());")
    W("}")
    W("")

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} with {len(probes)} probes")
    if skipped:
        print(f"skipped {len(skipped)} wrappers with unmapped param types:")
        for s in skipped[:40]:
            print("  ", s)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
