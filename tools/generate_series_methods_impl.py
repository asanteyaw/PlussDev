#!/usr/bin/env python3
import re
from pathlib import Path

IN = Path('PlussQit/src/CodeM/core/SeriesMethods.cleaned.inc')
OUT = Path('PlussQit/src/CodeM/Series/SeriesMethods.cpp.inc')

lines = IN.read_text(encoding='utf-8').splitlines()
out_lines = []
out_lines.append('// @generated by tools/generate_series_methods_impl.py')
out_lines.append('')
out_lines.append('using namespace pluss::codem;')
out_lines.append('')

for raw in lines:
    line = raw.strip()
    if not line or line.startswith('//'):
        continue
    if not line.endswith(';'):
        continue
    sig = line[:-1].strip()  # remove trailing ;
    # split return type and rest
    parts = sig.split(None, 1)
    if len(parts) != 2:
        continue
    return_type, rest = parts
    # rest like: name(params) [qual]
    m = re.match(r"([^(\s]+)\s*(\(.*\))\s*(.*)", rest)
    if not m:
        continue
    name = m.group(1)
    params = m.group(2)  # includes parentheses
    qualifier = m.group(3).strip()

    # extract param names
    param_list = params[1:-1].strip()
    args = []
    if param_list:
        # split top-level commas (naive split ok here)
        parts = [p.strip() for p in param_list.split(',')]
        for p in parts:
            if not p:
                continue
            # parameter like: 'const Series& mask' or 'double nan=0.0' or 'std::span<const std::int64_t> dims'
            # take last token and strip default assignment
            last = p.split()[-1]
            name_only = last.split('=')[0]
            # remove trailing & or && or * from name (unlikely present but safe)
            name_only = name_only.rstrip('&*')
            args.append(name_only)
    args_str = ', '.join(args)
    call_args = ('*this' + (', ' + args_str if args_str else ''))

    # reconstruct signature (keep params and qualifier as-is)
    qual_str = (' ' + qualifier) if qualifier else ''
    signature = f"{return_type} Series::{name}{params}{qual_str} {{ return pluss::codem::ops_internal::{name}({call_args}); }}"
    out_lines.append(signature)

OUT.write_text('\n'.join(out_lines) + '\n', encoding='utf-8')
print('Wrote', OUT)
