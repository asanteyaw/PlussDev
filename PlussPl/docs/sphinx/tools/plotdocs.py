#!/usr/bin/env python3
"""Builds the PlussPl "Types and options" reference pages from specs, and is their permanent verifier.

Each spec in tools/specs/<slug>.py defines PAGE (a dict). Every example's code is wrapped in a standard harness, compiled,
run, its standard output captured and the figure it saves written to api/types/img/. The page is then assembled from the
spec with the captured output, so printed output and images can never be typed by hand or drift from the code.

Usage:
    python3 tools/plotdocs.py [slug ...]        # build the named pages (default: every spec)
    python3 tools/plotdocs.py --check [slug ...] # rebuild into a temp dir and fail if a page is stale

Environment: SDKROOT (defaults to xcrun), PLUSSDEV_BUILD (library build tree, default as PlussTils/tools/verify_example.sh).
"""
import argparse, concurrent.futures, hashlib, importlib.util, os, pathlib, shutil, subprocess, sys, tempfile

HERE = pathlib.Path(__file__).resolve().parent
SPHINX = HERE.parent
ROOT = SPHINX.parents[2]            # PlussDev
API = SPHINX / "api" / "types"
IMG = API / "img"
SPECS = HERE / "specs"
VERIFY = ROOT / "PlussTils" / "tools" / "verify_example.sh"
CACHE = pathlib.Path(os.environ.get("PLOTDOCS_CACHE", tempfile.gettempdir())) / "plotdocs_cache"

HARNESS = """#include <pluss/pl/plusspl.h>
#include <cmath>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <limits>
#include <string>
#include <vector>
using namespace pluss::pl;
int main() {
%s
}
"""
MARK = "<!-- generated by PlussPl/docs/sphinx/tools/plotdocs.py from tools/specs/%s.py; edit the spec -->"


def load_specs(slugs):
    out = []
    files = sorted(p for p in SPECS.glob("*.py") if not p.name.startswith("_")) if not slugs else [SPECS / f"{s}.py" for s in slugs]
    for f in files:
        spec = importlib.util.spec_from_file_location(f.stem, f)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        page = mod.PAGE
        page.setdefault("slug", f.stem)
        out.append(page)
    return out


def run_example(slug, idx, ex, outdir):
    """Compile and run one example; return (stdout, svg_name or None)."""
    body = ex["code"].rstrip("\n")
    svg_name = f"{slug}-{idx}-{ex['id']}.svg"
    svg_path = outdir / svg_name
    src_body = body.replace('"figure.svg"', '"%s"' % svg_path)
    text = HARNESS % src_body
    salt = "".join(hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest() for p in os.environ.get("PLUSSDEV_EXTRA_SRCS", "").split() if pathlib.Path(p).exists())
    key = hashlib.sha256((text.replace(str(outdir), "<out>") + salt).encode()).hexdigest()[:20]
    hit = CACHE / key
    work = pathlib.Path(tempfile.mkdtemp(prefix="plotdocs_"))
    try:
        if (hit / "stdout.txt").exists():
            stdout = (hit / "stdout.txt").read_text()
            if (hit / "figure.svg").exists():
                shutil.copy(hit / "figure.svg", svg_path)
        else:
            cpp, exe = work / "e.cpp", work / "e.exe"
            cpp.write_text(text)
            env = dict(os.environ)
            env.setdefault("SDKROOT", subprocess.run(["xcrun", "--show-sdk-path"], capture_output=True, text=True).stdout.strip())
            b = subprocess.run(["bash", str(VERIFY), str(cpp), str(exe)], capture_output=True, text=True, env=env)
            if b.returncode != 0:
                raise SystemExit(f"BUILD FAILED {slug} example {idx} ({ex['id']}):\n" + "\n".join(l for l in b.stderr.splitlines() if "error" in l)[:2000])
            r = subprocess.run([str(exe)], capture_output=True, text=True, timeout=120, env=env)
            if r.returncode != 0:
                raise SystemExit(f"RUN FAILED {slug} example {idx} ({ex['id']}): {r.stderr[:1000]}")
            stdout = r.stdout
            hit.mkdir(parents=True, exist_ok=True)
            (hit / "stdout.txt").write_text(stdout)
            if svg_path.exists():
                shutil.copy(svg_path, hit / "figure.svg")
        return stdout, (svg_name if svg_path.exists() else None)
    finally:
        shutil.rmtree(work, ignore_errors=True)


def render(page, results, prev, nxt):
    slug = page["slug"]
    L = [MARK % slug, "", f"# {page['title']}", "", "[Back to Types and Options Reference](../../types_api_reference)", ""]
    L += ["## What It Does", "", page["intro"].strip("\n"), ""]
    if page.get("table"):
        L += [page.get("table_title", "## Values"), "", page["table"].strip("\n"), ""]
    for title, body in page.get("sections", []):
        L += [f"## {title}", "", body.strip("\n"), ""]
    L += ["## Examples", ""]
    for i, ex in enumerate(page["examples"], 1):
        stdout, svg = results[(slug, i)]
        L += [f"Example {i}. {ex['text'].strip()}", "", "```cpp", ex["code"].strip("\n"), "```", ""]
        if stdout.strip():
            L += ["### Output", "", "```text", "\n".join(line.rstrip() for line in stdout.rstrip("\n").splitlines()), "```", ""]
        if svg:
            L += [f"![Output of Example {i}](img/{svg})", ""]
    if page.get("notes"):
        L += ["## Notes", "", page["notes"].strip("\n"), ""]
    if page.get("see"):
        L += ["## See Also", ""] + [f"- {s}" for s in page["see"]] + [""]
    nav = ['<div class="pluss-inline-prev-next">']
    if prev:
        nav += [f'  <a class="prev-link" href="{prev[0]}.html">', '    <span class="label">Previous</span>', f'    <span class="title">{prev[1]}</span>', "  </a>"]
    if nxt:
        nav += [f'  <a class="next-link" href="{nxt[0]}.html">', '    <span class="label">Next</span>', f'    <span class="title">{nxt[1]}</span>', "  </a>"]
    nav += ["</div>"]
    return "\n".join(L + nav) + "\n"


GROUPS = [
    ("Legends", ["KeyPlace", "KeyDock", "KeyFrame", "KeyShape"]),
    ("Axes, scales and grid", ["ScalePolicy", "LimitMethod", "TickFormat", "GridStyle"]),
    ("3D view and surface appearance", ["Lens", "LightRig", "ShadeMode", "LightingMode", "MaterialProfile"]),
    ("Colour and themes", ["Rgba", "PaletteRamp", "Theme"]),
    ("Annotations and geometry", ["Cues", "Geometry"]),
    ("Trace types and their options", ["TraceKind", "ViolinOptions"]),
    ("Layout and export", ["MosaicLayout", "PdfEngine"]),
]


def write_landing(allpages):
    titles = {p["slug"]: p for p in allpages}
    L = ["<!-- generated by PlussPl/docs/sphinx/tools/plotdocs.py; edit GROUPS there -->", "", "# Types and Options Reference", "",
         "Most of what PlussPl lets you change about a figure is a **value** you pass to a `Studio`, `Pane` or `Trace` method: where a legend goes, how an axis is scaled, which grid lines are drawn, how a surface is lit, which colours a theme holds. These value types are the *options* of the plotting API, and this reference documents each one in one place: a table of every value or field with its meaning and default, where it is used, and a rendered demonstration of every value, so you can choose by looking at the result.", "",
         "Each page explains what the option does, lists its values or fields in a table, then gives examples with their printed output and figures. Every example is compiled and run by `tools/plotdocs.py`, which writes the printed output and figures, so they cannot drift from the code. Examples are shown without the lines around them: each is the body of `main()` in a program that starts with `#include <pluss/pl/plusspl.h>` and `using namespace pluss::pl;`, and `fig.save_svg(\"figure.svg\")` writes the figure shown beneath it.", "",
         "The per-method pages are in the [Studio](studio_api_reference.md), [Pane](pane_api_reference.md), [Trace](trace_api_reference.md) and [flash](flash_api_reference.md) references; they link here for the meaning of each option value.", ""]
    listed = []
    for title, slugs in GROUPS:
        slugs = [s for s in slugs if s in titles]
        if not slugs:
            continue
        L += [f"## {title}", "", "| Type | What it chooses |", "|---|---|"]
        for s in slugs:
            L.append(f"| [`{titles[s]['title']}`](api/types/{s}.md) | {titles[s].get('summary', '')} |")
            listed.append(s)
        L.append("")
    rest = [p["slug"] for p in allpages if p["slug"] not in listed]
    if rest:
        L += ["## Other", "", "| Type | What it chooses |", "|---|---|"] + [f"| [`{titles[s]['title']}`](api/types/{s}.md) | {titles[s].get('summary', '')} |" for s in rest] + [""]
    order = sorted(p["slug"] for p in allpages)
    L += ["```{toctree}", ":hidden:", ":maxdepth: 1", ""] + [f"api/types/{s}" for s in order] + ["```", ""]
    (SPHINX / "types_api_reference.md").write_text("\n".join(L))
    print("wrote types_api_reference.md")


def render_method(page, results, prev, nxt, family):
    slug = page["slug"]
    L = ["<!-- pluss-hand-authored -->", "", f"# {page['title']}", "", f"[Back to {family.capitalize()} API Reference](../../{family}_api_reference)", "",
         "## Signature", "", "```cpp", page["signature"].strip("\n"), "```", "", "## What It Does", "", page["intro"].strip("\n"), "",
         "## Parameters", "", page.get("parameters", "*(none)*").strip("\n"), "", "## Returns", "", page["returns"].strip("\n"), "", "## Examples", ""]
    for i, ex in enumerate(page["examples"], 1):
        stdout, svg = results[(slug, i)]
        L += [f"Example {i}. {ex['text'].strip()}", "", "```cpp", ex["code"].strip("\n"), "```", ""]
        if stdout.strip():
            L += ["### Output", "", "```text", stdout.rstrip("\n"), "```", ""]
        if svg:
            L += [f"![Output of Example {i}](img/{svg})", ""]
    if page.get("notes"):
        L += ["## Notes", "", page["notes"].strip("\n"), ""]
    if page.get("see"):
        L += ["## See Also", ""] + [f"- {s}" for s in page["see"]] + [""]
    nav = ['<div class="pluss-inline-prev-next">']
    if prev:
        nav += [f'  <a class="prev-link" href="{prev}.html">', '    <span class="label">Previous</span>', f'    <span class="title">{prev}</span>', "  </a>"]
    if nxt:
        nav += [f'  <a class="next-link" href="{nxt}.html">', '    <span class="label">Next</span>', f'    <span class="title">{nxt}</span>', "  </a>"]
    nav += ["</div>"]
    return "\n".join(L + nav) + "\n"


def build_methods(family):
    """Method pages for one family (pane, studio, trace): specs in tools/method_specs/<family>/*.py."""
    specdir = HERE / "method_specs" / family
    pages = []
    for f in sorted(specdir.glob("*.py")):
        spec = importlib.util.spec_from_file_location(f"{family}_{f.stem}", f)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        pages.append(mod.PAGE)
    apidir = SPHINX / "api" / family
    img = apidir / "img"
    jobs = [(p["slug"], i, ex) for p in pages for i, ex in enumerate(p["examples"], 1)]
    results = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=int(os.environ.get("PLOTDOCS_JOBS", "3"))) as pool:
        futs = {pool.submit(run_example, s, i, ex, img): (s, i) for s, i, ex in jobs}
        for fut, key in futs.items():
            results[key] = fut.result()
    existing = sorted(p.stem for p in apidir.glob("*.md"))
    names = sorted(set(existing) | {p["slug"] for p in pages})
    for p in pages:
        k = names.index(p["slug"])
        prev = names[k - 1] if k > 0 else None
        nxt = names[k + 1] if k + 1 < len(names) else None
        (apidir / f"{p['slug']}.md").write_text(render_method(p, results, prev, nxt, family))
        print("wrote", (apidir / f"{p['slug']}.md").relative_to(SPHINX))
        # keep the neighbours' previous/next links pointing at the new page
        for neighbour, link_class, target in ((prev, "next-link", p["slug"]), (nxt, "prev-link", p["slug"])):
            if not neighbour or neighbour in {q["slug"] for q in pages}:
                continue
            path = apidir / f"{neighbour}.md"
            text = path.read_text()
            import re as _re
            pat = _re.compile(r'(<a class="%s" href=")[^"]*(\.html">\s*<span class="label">\w+</span>\s*<span class="title">)[^<]*(</span>)' % link_class)
            if pat.search(text):
                path.write_text(pat.sub(lambda m: m.group(1) + target + m.group(2) + target + m.group(3), text))
    print("add to", f"{family}_api_reference.md toctree:", [p["slug"] for p in pages])


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "--methods":
        build_methods(sys.argv[2])
        return
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("slugs", nargs="*")
    a = ap.parse_args()
    pages = load_specs(a.slugs)
    allpages = load_specs([])
    order = sorted(p["slug"] for p in allpages)
    outdir = pathlib.Path(tempfile.mkdtemp(prefix="plotdocs_out_")) if a.check else IMG
    outdir.mkdir(parents=True, exist_ok=True)
    API.mkdir(parents=True, exist_ok=True)
    jobs = [(p["slug"], i, ex) for p in pages for i, ex in enumerate(p["examples"], 1)]
    results = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=int(os.environ.get("PLOTDOCS_JOBS", "3"))) as pool:
        futs = {pool.submit(run_example, s, i, ex, outdir): (s, i) for s, i, ex in jobs}
        for f, key in futs.items():
            results[key] = f.result()
    stale = []
    for p in pages:
        s = p["slug"]
        k = order.index(s)
        prev = (order[k - 1], next(x["title"] for x in allpages if x["slug"] == order[k - 1])) if k > 0 else None
        nxt = (order[k + 1], next(x["title"] for x in allpages if x["slug"] == order[k + 1])) if k + 1 < len(order) else None
        text = render(p, results, prev, nxt)
        dest = API / f"{s}.md"
        if a.check:
            if not dest.exists() or dest.read_text() != text:
                stale.append(s)
        else:
            dest.write_text(text)
            print("wrote", dest.relative_to(SPHINX))
    if not a.check:
        write_landing(allpages)
    if a.check:
        if stale:
            sys.exit("stale: " + ", ".join(stale))
        print("types pages up to date")


if __name__ == "__main__":
    main()
