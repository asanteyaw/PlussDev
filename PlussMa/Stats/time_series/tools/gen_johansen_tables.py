#!/usr/bin/env python3
"""Simulates the asymptotic distributions of Johansen's trace and maximum-eigenvalue statistics and writes
ts/modules/vecm/johansen_tables.h (upper-tail quantiles on a fixed probability grid).

For m = n - r common trends the limit of the trace statistic is tr{ int dW F' (int F F')^-1 int F dW' } and that of the
maximum-eigenvalue statistic is the largest eigenvalue of the same matrix, where W is an m-dimensional Brownian motion and
  case 1 (no deterministic terms):          F = W
  case 3 (unrestricted constant):           F = (W_1..W_{m-1} demeaned, u - 1/2)
  case 5 (unrestricted constant and trend): F = (W_1..W_{m-1} detrended, u^2 detrended on 1, u)
The functional is evaluated on a grid of N steps with R replications; usage: gen_johansen_tables.py [R] [N] [output].
"""
import sys
import numpy as np

R = int(sys.argv[1]) if len(sys.argv) > 1 else 100000
N = int(sys.argv[2]) if len(sys.argv) > 2 else 1000
OUT = sys.argv[3] if len(sys.argv) > 3 else "johansen_tables.h"
PROBS = [0.999, 0.995, 0.99, 0.975, 0.95, 0.925, 0.9, 0.85, 0.8, 0.7, 0.6, 0.5, 0.4, 0.3, 0.2, 0.15, 0.1, 0.075, 0.05, 0.025, 0.01, 0.005, 0.001]
MAXM = 12
BATCH = 500

def basis(case):
    u = np.arange(N) / N
    if case == 1:
        return None
    if case == 3:
        return np.c_[np.ones(N)]
    return np.c_[np.ones(N), u]

def project_out(x, X):
    # x: (B, N, k); remove the least-squares fit on columns X (N, c)
    P = X @ np.linalg.solve(X.T @ X, X.T)
    return x - np.einsum("nj,bjk->bnk", P, x)

def simulate(case, m, reps, rng):
    u = np.arange(N) / N
    X = basis(case)
    tr = np.empty(reps); mx = np.empty(reps)
    done = 0
    while done < reps:
        B = min(BATCH, reps - done)
        dW = rng.standard_normal((B, N, m)) / np.sqrt(N)
        W = np.cumsum(dW, axis=1) - dW  # left endpoints W_{i-1}
        if case == 1:
            F = W
        else:
            k = m - 1
            F = np.empty((B, N, m))
            if k > 0:
                F[:, :, :k] = project_out(W[:, :, :k], X)
            last = (u - 0.5) if case == 3 else u * u
            last = last[None, :, None] * np.ones((B, 1, 1))
            if case == 5:
                last = project_out(last, X)
            F[:, :, k:] = last if case == 5 else (last - last.mean(axis=1, keepdims=True))
        A = np.einsum("bni,bnj->bij", dW, F)
        S = np.einsum("bni,bnj->bij", F, F) / N
        M = A @ np.linalg.solve(S, np.swapaxes(A, 1, 2))
        M = 0.5 * (M + np.swapaxes(M, 1, 2))
        ev = np.linalg.eigvalsh(M)
        tr[done:done + B] = ev.sum(axis=1)
        mx[done:done + B] = ev[:, -1]
        done += B
    return tr, mx

def task(args):
    case, m = args
    rng = np.random.default_rng([20261022, case, m])
    reps = R if m <= 6 else max(R // 2, 20000)
    tr, mx = simulate(case, m, reps, rng)
    qs = [1 - p for p in PROBS]
    return (case, m), (np.quantile(tr, qs), np.quantile(mx, qs))

def main():
    from multiprocessing import Pool
    jobs = sorted(((c, m) for c in (1, 3, 5) for m in range(1, MAXM + 1)), key=lambda j: -j[1])
    tables = {}
    with Pool() as pool:
        for key, val in pool.imap_unordered(task, jobs):
            tables[key] = val
            print(key, val[0][[18]], flush=True)
    with open(OUT, "w") as f:
        f.write("// Generated by Stats/time_series/tools/gen_johansen_tables.py (R=%d, N=%d); do not edit.\n" % (R, N))
        f.write("// Upper-tail quantiles of the asymptotic Johansen trace and maximum-eigenvalue statistics, by case and m = n - r.\n")
        f.write("#pragma once\n\nnamespace pluss::subsp::stats::ts::johansen_tables {\n\n")
        f.write("inline constexpr int kMaxM = %d;\ninline constexpr int kNumProbs = %d;\n" % (MAXM, len(PROBS)))
        f.write("inline constexpr double kProbs[kNumProbs] = {%s};\n\n" % ", ".join(repr(p) for p in PROBS))
        for name, idx in (("kTrace", 0), ("kMaxEigen", 1)):
            f.write("// [case index (1, 3, 5)][m - 1][probability index]\n")
            f.write("inline constexpr double %s[3][kMaxM][kNumProbs] = {\n" % name)
            for case in (1, 3, 5):
                f.write("  {\n")
                for m in range(1, MAXM + 1):
                    f.write("    {%s},\n" % ", ".join("%.4f" % v for v in tables[(case, m)][idx]))
                f.write("  },\n")
            f.write("};\n\n")
        f.write("}  // namespace pluss::subsp::stats::ts::johansen_tables\n")

if __name__ == "__main__":
    main()
