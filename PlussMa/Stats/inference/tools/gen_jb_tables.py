#!/usr/bin/env python3
"""Simulated null distribution of the Jarque-Bera statistic for small and moderate samples.

For each sample size n of the grid it draws `reps` standard-normal samples, computes JB = n/6 (S^2 + (K - 3)^2 / 4) with the
biased (population) moments, and records the upper-tail critical values c(n, q) with P(JB >= c) = q for the levels q below.
The output header is used by jbtest() to turn a statistic into a p-value; above the largest n the chi-squared(2) limit is used.

    python3 gen_jb_tables.py > ../hypothesis_testing/gof/jb_tables.h
"""
import sys
import numpy as np

NS = [4, 5, 6, 7, 8, 9, 10, 12, 14, 16, 20, 25, 30, 40, 50, 60, 80, 100, 150, 200, 300, 500, 1000]
QS = [0.99, 0.95, 0.9, 0.8, 0.7, 0.6, 0.5, 0.4, 0.3, 0.2, 0.1, 0.05, 0.025, 0.01, 0.005, 0.0025, 0.001, 0.0005]
SEED = 20261024


def jb_samples(rng, n, reps):
    out = np.empty(reps)
    batch = max(1, int(2e7 // n))
    done = 0
    while done < reps:
        m = min(batch, reps - done)
        x = rng.standard_normal((m, n))
        c = x - x.mean(axis=1, keepdims=True)
        m2 = (c ** 2).mean(axis=1)
        m3 = (c ** 3).mean(axis=1)
        m4 = (c ** 4).mean(axis=1)
        s = m3 / m2 ** 1.5
        k = m4 / m2 ** 2
        out[done:done + m] = n / 6.0 * (s ** 2 + 0.25 * (k - 3.0) ** 2)
        done += m
    return out


def main():
    rng = np.random.default_rng(SEED)
    rows = []
    for n in NS:
        reps = int(min(4_000_000, max(400_000, 8e8 / n)))
        jb = jb_samples(rng, n, reps)
        rows.append([float(np.quantile(jb, 1.0 - q)) for q in QS])
        print(f"n={n} reps={reps}", file=sys.stderr)
    w = sys.stdout.write
    w("// Generated by Stats/inference/tools/gen_jb_tables.py -- do not edit.\n")
    w("// Upper-tail critical values c(n, q) of the Jarque-Bera statistic under normality: P(JB >= c) = q.\n")
    w("#pragma once\n\nnamespace pluss::subsp::stats::inference::hypothesis::jb_tables {\n\n")
    w(f"inline constexpr int kSizes = {len(NS)};\n")
    w(f"inline constexpr int kLevels = {len(QS)};\n")
    w("inline constexpr int kN[kSizes] = {" + ", ".join(str(n) for n in NS) + "};\n")
    w("inline constexpr double kQ[kLevels] = {" + ", ".join(repr(q) for q in QS) + "};\n")
    w("inline constexpr double kCritical[kSizes][kLevels] = {\n")
    for r in rows:
        w("    {" + ", ".join(f"{v:.6g}" for v in r) + "},\n")
    w("};\n\n}  // namespace pluss::subsp::stats::inference::hypothesis::jb_tables\n")


if __name__ == "__main__":
    main()
