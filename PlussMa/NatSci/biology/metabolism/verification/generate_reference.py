#!/usr/bin/env python3
"""Generate test/metabolism_reference.h from COBRApy (independent LP stack: optlang/GLPK or HiGHS).
Model: e_coli_core, the BiGG 'textbook' core model shipped with COBRApy (cobra/data/textbook.xml.gz).
usage: generate_reference.py <out.h>      (needs cobra)
"""
import sys, numpy as np, cobra
from cobra.flux_analysis import flux_variability_analysis, loopless_solution
m = cobra.io.load_model('textbook')
# COBRApy's CycleFreeFlux sets bounds (flux, flux) on boundary reactions and raises if solver round-off puts a flux a hair
# outside its bound (e.g. ATPM 8.389999999999986 < 8.39). Snap fluxes into their bounds before delegating (oracle-side fix only).
import cobra.flux_analysis.loopless as _ll
_orig_add = _ll._add_cycle_free
def _snapped(model, fluxes):
    fluxes = {k: min(max(v, model.reactions.get_by_id(k).lower_bound), model.reactions.get_by_id(k).upper_bound) for k, v in dict(fluxes).items()}
    return _orig_add(model, fluxes)
_ll._add_cycle_free = _snapped
rxns = [r.id for r in m.reactions]; mets = [x.id for x in m.metabolites]
S = cobra.util.array.create_stoichiometric_matrix(m)
lb = np.array([r.lower_bound for r in m.reactions]); ub = np.array([r.upper_bound for r in m.reactions])
c = np.array([r.objective_coefficient for r in m.reactions])
def vec(a): return "{" + ",".join(repr(float(v)) for v in np.ravel(a)) + "}"
wt = m.optimize().objective_value
fva1 = flux_variability_analysis(m, fraction_of_optimum=1.0, loopless=False, processes=1)
fva9 = flux_variability_analysis(m, fraction_of_optimum=0.9, loopless=False, processes=1)
growth = []
for rx in m.reactions:      # single-process, one LP per knock-out (no multiprocessing)
    with m:
        rx.knock_out()
        sol = m.optimize(raise_error=False)
        growth.append(sol.objective_value if sol.status == 'optimal' else 0.0)
growth = np.nan_to_num(np.array(growth, float), nan=0.0)
genes = [g.id for g in m.genes]
rules = [r.gene_reaction_rule for r in m.reactions]
gko = []
for g in m.genes:           # single-process gene deletions (GPR evaluated by cobra)
    with m:
        g.knock_out()
        sol = m.optimize(raise_error=False)
        gko.append(sol.objective_value if sol.status == 'optimal' else 0.0)
rng = np.random.default_rng(7); pairs = [tuple(sorted(rng.choice(len(genes), 2, replace=False))) for _ in range(40)]
dko = []
for a, b in pairs:
    with m:
        m.genes[a].knock_out(); m.genes[b].knock_out()
        sol = m.optimize(raise_error=False)
        dko.append(sol.objective_value if sol.status == 'optimal' else 0.0)
llfva = flux_variability_analysis(m, fraction_of_optimum=1.0, loopless='cycleFreeFlux', processes=1)
sol0 = m.optimize()
start = np.clip(np.array([sol0.fluxes[r] for r in rxns]), lb, ub)   # snap round-off outside bounds (cobra rejects it)
lls = loopless_solution(m, dict(zip(rxns, start)))
ll_flux = np.array([lls.fluxes[r] for r in rxns])
boundary = np.array([1.0 if r.boundary else 0.0 for r in m.reactions])
# a flux with a genuine thermodynamic loop: the FVA maximum of FRD7 (fumarate reductase) runs through the SUCDi/FRD7 cycle
from cobra.core.solution import get_solution
frd7 = m.reactions.get_by_id('FRD7'); opt0 = m.slim_optimize()
with m:
    old = m.problem.Variable("fva_old_objective"); con = m.problem.Constraint(m.objective.expression - old, lb=0, ub=0, name="fva_old_objective_constraint")
    m.add_cons_vars([old, con]); old.lb = opt0
    m.objective = m.problem.Objective(frd7.flux_expression, direction='max'); m.slim_optimize()
    fl = get_solution(m).fluxes
    loopy_start = np.clip(np.array([fl[r] for r in rxns]), lb, ub)
    with m:
        _ll._add_cycle_free(m, dict(zip(rxns, loopy_start))); m.slim_optimize(); cl = get_solution(m).fluxes
    loopy_cleaned = np.array([cl[r] for r in rxns])
glc = rxns.index('EX_glc__D_e'); vals = np.array([-2., -5., -10., -15., -20.]); sweep = []
for v in vals:
    with m: 
        m.reactions[glc].lower_bound = v; m.reactions[glc].upper_bound = v
        s = m.optimize(); sweep.append(s.objective_value if s.status == 'optimal' else 0.0)
with open(sys.argv[1], 'w') as f:
    f.write("// Generated by verification/generate_reference.py (COBRApy %s, e_coli_core 'textbook'); do not edit.\n#pragma once\n#include <vector>\nnamespace metabolism_reference {\n" % cobra.__version__)
    f.write("inline const int m = %d, r = %d, glucose_exchange = %d;\n" % (len(mets), len(rxns), glc))
    f.write("inline const std::vector<double> S = %s, lower = %s, upper = %s, objective = %s;\n" % (vec(S), vec(lb), vec(ub), vec(c)))
    f.write("inline const double optimum = %r;\n" % wt)
    f.write("inline const std::vector<double> fva_min = %s, fva_max = %s, fva90_min = %s, fva90_max = %s;\n" % (vec(fva1['minimum']), vec(fva1['maximum']), vec(fva9['minimum']), vec(fva9['maximum'])))
    f.write("inline const std::vector<double> knockout_growth = %s, sweep_values = %s, sweep_growth = %s;\n" % (vec(growth), vec(vals), vec(sweep)))
    f.write("inline const std::vector<double> ll_fva_min = %s, ll_fva_max = %s, start_flux = %s, loopless_flux = %s, boundary = %s;\n" % (vec(llfva['minimum']), vec(llfva['maximum']), vec(start), vec(ll_flux), vec(boundary)))
    f.write("inline const std::vector<double> loopy_start = %s, loopy_cleaned = %s;\n" % (vec(loopy_start), vec(loopy_cleaned)))
    f.write("inline const std::vector<double> gene_knockout_growth = %s, double_knockout_growth = %s;\n" % (vec(gko), vec(dko)))
    f.write("inline const std::vector<int> double_pairs = {%s};\n" % ",".join("%d,%d" % p for p in pairs))
    f.write("inline const std::vector<const char *> gene_names = {%s};\n" % ",".join('"%s"' % g for g in genes))
    f.write("inline const std::vector<const char *> gene_rules = {%s};\n" % ",".join('"%s"' % x.replace('"', '') for x in rules))
    f.write("} // namespace metabolism_reference\n")
print("optimum", wt, "m,r", len(mets), len(rxns))
