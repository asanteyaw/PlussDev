#!/usr/bin/env python3
"""Generate test/ijo1366_reference.h: the genome-scale E. coli model iJO1366 (Orth et al. 2011; BiGG, shipped with COBRApy as
cobra/data/iJO1366.xml.gz) with COBRApy results for FBA, a sampled FVA and sampled single-gene deletions.
The stoichiometry is stored sparsely (row, col, value triplets). usage: generate_genome_scale_reference.py <out.h> [n_fva] [n_genes]
"""
import sys, numpy as np, cobra
nf = int(sys.argv[2]) if len(sys.argv) > 2 else 40
ng = int(sys.argv[3]) if len(sys.argv) > 3 else 60
m = cobra.io.load_model('iJO1366')
rxns = [r.id for r in m.reactions]
S = cobra.util.array.create_stoichiometric_matrix(m, array_type='dok')
lb = np.array([r.lower_bound for r in m.reactions]); ub = np.array([r.upper_bound for r in m.reactions])
c = np.array([r.objective_coefficient for r in m.reactions])
wt = m.optimize().objective_value
rng = np.random.default_rng(11)
active = [i for i, r in enumerate(m.reactions) if ub[i] > lb[i]]
fva_idx = sorted(rng.choice(active, nf, replace=False).tolist())
from cobra.flux_analysis import flux_variability_analysis
fva = flux_variability_analysis(m, reaction_list=[m.reactions[i] for i in fva_idx], fraction_of_optimum=1.0, processes=1)
gene_idx = sorted(rng.choice(len(m.genes), ng, replace=False).tolist())
gko = []
for gi in gene_idx:
    with m:
        m.genes[gi].knock_out(); s = m.optimize(raise_error=False)
        gko.append(s.objective_value if s.status == 'optimal' else 0.0)
vec = lambda a: "{" + ",".join(repr(float(v)) for v in np.ravel(a)) + "}"
ivec = lambda a: "{" + ",".join(str(int(v)) for v in a) + "}"
rows, cols, vals = [], [], []
for (i, j), v in S.items(): rows.append(i); cols.append(j); vals.append(v)
with open(sys.argv[1], 'w') as f:
    f.write("// Generated by verification/generate_genome_scale_reference.py (COBRApy %s, iJO1366); do not edit.\n#pragma once\n#include <vector>\nnamespace ijo1366_reference {\n" % cobra.__version__)
    f.write("inline const int m = %d, r = %d;\n" % (len(m.metabolites), len(rxns)))
    f.write("inline const std::vector<int> s_row = %s, s_col = %s;\ninline const std::vector<double> s_val = %s;\n" % (ivec(rows), ivec(cols), vec(vals)))
    f.write("inline const std::vector<double> lower = %s, upper = %s, objective = %s;\n" % (vec(lb), vec(ub), vec(c)))
    f.write("inline const double optimum = %r;\n" % wt)
    f.write("inline const std::vector<int> fva_index = %s;\ninline const std::vector<double> fva_min = %s, fva_max = %s;\n" % (ivec(fva_idx), vec(fva['minimum']), vec(fva['maximum'])))
    f.write("inline const std::vector<int> gene_index = %s;\ninline const std::vector<double> gene_growth = %s;\n" % (ivec(gene_idx), vec(gko)))
    f.write("inline const std::vector<const char *> gene_names = {%s};\n" % ",".join('"%s"' % g.id for g in m.genes))
    f.write("inline const std::vector<const char *> gene_rules = {%s};\n" % ",".join('"%s"' % r.gene_reaction_rule.replace('"', '') for r in m.reactions))
    f.write("} // namespace ijo1366_reference\n")
print("iJO1366 m,r", len(m.metabolites), len(rxns), "optimum", wt, "nnz", len(vals))
