"""Nearest-neighbour nucleic-acid thermodynamics: tables and reference Tm values from Biopython's MeltingTemp (the open implementation
read from GitHub: biopython/Bio/SeqUtils/MeltingTemp.py, SHA-256 4f3cbc58...). Writes
  include/pluss/subsp/natsci/biology/biophysics/nucleic_acid_tables.h   (the tables, generated from the Python dictionaries)
  NatSci/biology/biophysics/test/nucleic_reference.h                    (Tm values computed by Biopython for the test sequences)
Run with PYTHONPATH pointing at a biopython checkout.
"""
import sys, itertools, numpy as np
from Bio.SeqUtils import MeltingTemp as mt

tables = {name: getattr(mt, name) for name in ["DNA_NN1", "DNA_NN2", "DNA_NN3", "DNA_NN4", "RNA_NN1", "RNA_NN2", "RNA_NN3", "R_DNA_NN1"] if hasattr(mt, name)}
def cpp_table(name, t):
    rows = ",\n".join('    {"%s", {%r, %r}}' % (k, float(v[0]), float(v[1])) for k, v in t.items())
    return "inline const std::map<std::string, std::pair<double, double>> %s = {\n%s};\n" % (name, rows)
header = ("// Generated by NatSci/biology/verification/gen_nucleic_ref.py from Biopython's MeltingTemp.py tables; do not edit.\n"
          "// Values are (dH kcal/mol, dS cal/mol/K). Sources (as cited in that file): Breslauer et al. 1986 (DNA_NN1), Sugimoto et al. 1996 (DNA_NN2),\n"
          "// Allawi & SantaLucia 1997 (DNA_NN3), SantaLucia & Hicks 2004 (DNA_NN4), Freier et al. 1986 (RNA_NN1), Xia et al. 1998 (RNA_NN2),\n"
          "// Chen et al. 2012 (RNA_NN3), Sugimoto et al. 1995 (R_DNA_NN1).\n#pragma once\n#include <map>\n#include <string>\n#include <utility>\n\n"
          "namespace pluss::subsp::natsci::biology::biophysics::nucleic_acids::tables {\n" + "\n".join(cpp_table(n, t) for n, t in tables.items()) + "\n}\n")
open("../../include/pluss/subsp/natsci/biology/biophysics/nucleic_acid_tables.h", "w").write(header)

seqs = ["ATGCGTACGTTAGC", "GCGCGCGCGC", "AAAATTTTAAAATTTT", "CGATCGATCGAT", "GGGCCCAAATTTGGG", "ACGTACGTAC", "TTGACAATTAATCATCGGCTCGTATAATG", "CCGGAATTCCGG"]
rows = []
def add(kind, seq, **kw):
    kw0 = dict(kw)
    tm = mt.Tm_NN(seq, **kw0)
    rows.append((kind, seq, kw, tm))
for s in seqs:
    for tab in ["DNA_NN3", "DNA_NN4", "DNA_NN1", "DNA_NN2"]:
        add("dna", s, nn_table=getattr(mt, tab), dnac1=250, dnac2=250, Na=50, saltcorr=5)
    for sc in [1, 2, 3, 4, 5, 6, 7]:
        add("salt", s, nn_table=mt.DNA_NN4, dnac1=100, dnac2=100, Na=100 if sc != 7 else 50, K=0 if sc != 7 else 10, Mg=0 if sc not in (6, 7) else 1.5, dNTPs=0 if sc != 7 else 0.5, Tris=20 if sc == 2 else 0, saltcorr=sc)
    add("self", s if s == s.translate(str.maketrans("ACGT", "TGCA"))[::-1] else s, nn_table=mt.DNA_NN4, selfcomp=(s == s.translate(str.maketrans("ACGT", "TGCA"))[::-1]), dnac1=500, dnac2=500, Na=50, saltcorr=5)
for s in ["AUGCGUACGUUAGC", "GCGCGCGCGC", "AAAUUUAAAUUU"]:
    for tab in ["RNA_NN1", "RNA_NN2", "RNA_NN3"]:
        add("rna", s, nn_table=getattr(mt, tab), dnac1=250, dnac2=250, Na=50, saltcorr=5)
def cstr(v): return '"%s"' % v
tab_names = {id(getattr(mt, n)): n for n in tables}
lines = ["// Generated by NatSci/biology/verification/gen_nucleic_ref.py (Biopython MeltingTemp.Tm_NN); do not edit.", "#pragma once", "#include <string>", "#include <vector>", "namespace nucleic_reference {",
         "struct Case { const char *kind; const char *seq; const char *table; double dnac1, dnac2, na, k, tris, mg, dntps; int saltcorr; bool selfcomp; double tm; };",
         "inline const std::vector<Case> cases = {"]
for kind, seq, kw, tm in rows:
    lines.append('  {"%s", "%s", "%s", %r, %r, %r, %r, %r, %r, %r, %d, %s, %r},' % (kind, seq, tab_names[id(kw["nn_table"])], float(kw.get("dnac1", 25)), float(kw.get("dnac2", 25)), float(kw.get("Na", 50)), float(kw.get("K", 0)), float(kw.get("Tris", 0)), float(kw.get("Mg", 0)), float(kw.get("dNTPs", 0)), kw.get("saltcorr", 5), "true" if kw.get("selfcomp") else "false", float(tm)))
lines += ["};", "}"]
open("biophysics/test/nucleic_reference.h", "w").write("\n".join(lines) + "\n")
print("ok", len(rows), "cases")
