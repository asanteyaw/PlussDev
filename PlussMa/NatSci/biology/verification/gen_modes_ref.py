# Elementary-flux-mode oracle: brute-force enumeration of minimal supports (a support S' is an EFM iff the nullspace of S restricted to S' is
# one-dimensional, its vector is nowhere zero on S' and respects the irreversibility signs). Run from NatSci/biology:
#   python verification/gen_modes_ref.py
import itertools, numpy as np
rng = np.random.default_rng(12)
def efms(S, rev):
    m, r = S.shape; rank = np.linalg.matrix_rank(S); out = []
    for k in range(1, rank + 2):
        for sup in itertools.combinations(range(r), k):
            sub = S[:, sup]
            u, s, vt = np.linalg.svd(sub)
            nul = [vt[i] for i in range(len(sup)) if i >= len(s) or s[i] < 1e-9]
            if len(nul) != 1: continue
            v = nul[0]
            if np.min(np.abs(v)) < 1e-9: continue
            full = np.zeros(r); full[list(sup)] = v / np.max(np.abs(v))
            irr = [j for j in sup if not rev[j]]
            if irr:
                if all(full[j] >= -1e-9 for j in irr): pass
                elif all(full[j] <= 1e-9 for j in irr): full = -full
                else: continue
            else:
                first = next(j for j in sup); 
                if full[first] < 0: full = -full
            out.append(full)
    return np.array(out)
nets = []
while len(nets) < 8:
    m, r = 4, 9
    S = rng.choice([-1, 0, 0, 1], size=(m, r)).astype(float)
    S[rng.random((m, r)) < 0.1] *= 2
    if np.linalg.matrix_rank(S) >= m or np.any(np.all(S == 0, axis=0)): 
        pass
    rev = rng.random(r) < 0.4
    if np.linalg.matrix_rank(S) < 3 or r - np.linalg.matrix_rank(S) < 3: continue
    nets.append((S, rev))
blocks = []
for S, rev in nets:
    E = efms(S, rev)
    lo = np.where(rev, -1000.0, 0.0); hi = np.full(S.shape[1], 1000.0)
    blocks.append((S, lo, hi, E))
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(t)) for t in np.asarray(a, float).ravel()))
lines = ["inline const int n_networks = %d;" % len(blocks)]
for i, (S, lo, hi, E) in enumerate(blocks):
    lines += [arr("s%d" % i, S), arr("lo%d" % i, lo), arr("hi%d" % i, hi), arr("modes%d" % i, E), "inline const int m%d = %d, r%d = %d, count%d = %d;" % (i, S.shape[0], i, S.shape[1], i, E.shape[0])]
with open("metabolism/test/modes_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_modes_ref.py; do not edit.\n#pragma once\n#include <vector>\nnamespace modes_reference {\n" + "\n".join(lines) + "\n}\n")
print([b[3].shape[0] for b in blocks])
