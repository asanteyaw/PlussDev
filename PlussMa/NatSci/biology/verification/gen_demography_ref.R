# Matrix-population oracle: the R package popbio (CRAN mirror github.com/cran/popbio) sourced file by file, so the reference numbers are
# produced by popbio's own functions. Run from NatSci/biology:  Rscript verification/gen_demography_ref.R <popbio R dir>
args <- commandArgs(TRUE); d <- args[1]
for (f in c("splitA","lambda","sensitivity","elasticity","damping.ratio","fundamental.matrix","net.reproductive.rate","generation.time","LTRE","stoch.growth.rate","eigen.analysis","reproductive.value","stable.stage")) source(file.path(d, paste0(f, ".R")))
mk <- function(v, k) matrix(v, k, k, byrow = TRUE)
mats <- list(
  mk(c(0.2,0,4.0, 0.5,0.3,0, 0,0.45,0.85), 3),
  mk(c(0,0,3,6, 0.4,0.1,0,0, 0,0.5,0.2,0, 0,0,0.6,0.9), 4),
  mk(c(0.1,0,1.2,2.5,0, 0.35,0.3,0,0,0, 0,0.4,0.4,0,0, 0,0.1,0.3,0.5,0.1, 0,0,0.05,0.35,0.75), 5))
ref <- mats[[1]] * 0.85; trt <- mats[[1]] * 1.0; trt[1,3] <- 5.2; trt[3,3] <- 0.9; trt[2,1] <- 0.4
envs <- list(mk(c(0.2,0,3.0, 0.5,0.3,0, 0,0.45,0.85), 3), mk(c(0.3,0,5.5, 0.6,0.25,0, 0,0.5,0.9), 3), mk(c(0.1,0,0.8, 0.35,0.35,0, 0,0.3,0.7), 3), mk(c(0.25,0,6.5, 0.55,0.2,0, 0,0.55,0.8), 3))
probs <- c(0.1, 0.2, 0.3, 0.4)
out <- list()
fmt <- function(name, x) sprintf("inline const std::vector<double> %s = {%s};", name, paste(sprintf("%.17g", as.numeric(x)), collapse = ","))
rowmajor <- function(m) as.numeric(t(m))
for (i in seq_along(mats)) {
  A <- mats[[i]]; k <- nrow(A); n <- paste0("m", i, "_")
  ea <- eigen.analysis(A)
  fm <- fundamental.matrix(A)
  out[[length(out)+1]] <- fmt(paste0(n, "A"), rowmajor(A))
  out[[length(out)+1]] <- fmt(paste0(n, "lambda"), ea$lambda1)
  out[[length(out)+1]] <- fmt(paste0(n, "stable"), ea$stable.stage)
  out[[length(out)+1]] <- fmt(paste0(n, "repro"), ea$repro.value)
  out[[length(out)+1]] <- fmt(paste0(n, "sens"), rowmajor(ea$sensitivities))
  out[[length(out)+1]] <- fmt(paste0(n, "elas"), rowmajor(ea$elasticities))
  out[[length(out)+1]] <- fmt(paste0(n, "damping"), damping.ratio(A))
  mm <- Mod(eigen(A)$values)
  out[[length(out)+1]] <- fmt(paste0(n, "damping_exact"), mm[1] / mm[2])  # popbio's damping.ratio rounds the moduli to 5 decimals
  out[[length(out)+1]] <- fmt(paste0(n, "R0"), net.reproductive.rate(A))
  out[[length(out)+1]] <- fmt(paste0(n, "gen"), generation.time(A))
  out[[length(out)+1]] <- fmt(paste0(n, "N"), rowmajor(fm$N))
  out[[length(out)+1]] <- fmt(paste0(n, "Nvar"), rowmajor(fm$var))
  out[[length(out)+1]] <- fmt(paste0(n, "eta"), fm$meaneta)
  out[[length(out)+1]] <- fmt(paste0(n, "etavar"), fm$vareta)
}
cm <- LTRE(trt, ref)
out[[length(out)+1]] <- fmt("ltre_ref", rowmajor(ref)); out[[length(out)+1]] <- fmt("ltre_trt", rowmajor(trt))
out[[length(out)+1]] <- fmt("ltre_contrib", rowmajor(cm))
out[[length(out)+1]] <- fmt("ltre_lambda_ref", lambda(ref)); out[[length(out)+1]] <- fmt("ltre_lambda_trt", lambda(trt))
out[[length(out)+1]] <- fmt("env_A", unlist(lapply(envs, rowmajor))); out[[length(out)+1]] <- fmt("env_p", probs)
set.seed(11)
sg <- stoch.growth.rate(envs, prob = probs, maxt = 200000, verbose = FALSE)
out[[length(out)+1]] <- fmt("env_approx_popbio", sg$approx); out[[length(out)+1]] <- fmt("env_sim_popbio", c(sg$sim, sg$sim.CI))
writeLines(c("// Generated by NatSci/biology/verification/gen_demography_ref.R (popbio functions); do not edit.", "#pragma once", "#include <vector>", "namespace demography_reference {", unlist(out), "}"), "population/test/demography_reference.h")
cat("ok", length(out), "arrays; stochastic approx", sg$approx, "sim", sg$sim, sg$sim.CI, "\n")
