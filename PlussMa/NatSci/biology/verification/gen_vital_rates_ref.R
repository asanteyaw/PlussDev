# Vital-rate regression oracle: R's glm / lm on a simulated individual-based data set, and the IPM built from the fits with an eigen decomposition in base R.
# Run from NatSci/biology:  Rscript verification/gen_vital_rates_ref.R
set.seed(2026)
n <- 1800
z <- pmin(pmax(rnorm(n, 4.2, 1.5), 0.3), 9.5)
s_true <- plogis(-2 + 0.9 * z)
surv <- rbinom(n, 1, s_true)
z1 <- 0.6 + 0.85 * z + rnorm(n, 0, 0.7)
off <- rpois(n, exp(-2.2 + 0.35 * z))
rec <- rnorm(500, 1.2, 0.5)
fs <- glm(surv ~ z, family = binomial)
fg <- lm(z1[surv == 1] ~ z[surv == 1])
ff <- glm(off ~ z, family = poisson)
gsd <- summary(fg)$sigma
rmean <- mean(rec); rsd <- sd(rec)
# IPM on a 120-point midpoint mesh over [0, 10]
lo <- 0; hi <- 10; m <- 120; h <- (hi - lo) / m; zz <- lo + h * (seq_len(m) - 0.5)
surv_z <- plogis(coef(fs)[1] + coef(fs)[2] * zz)
mean_next <- coef(fg)[1] + coef(fg)[2] * zz
fec_z <- exp(coef(ff)[1] + coef(ff)[2] * zz)
G <- outer(zz, seq_len(m), function(a, j) dnorm(a, mean_next[j], gsd))
P <- h * sweep(G, 2, surv_z, "*")
Fk <- h * outer(dnorm(zz, rmean, rsd), fec_z)
A <- P + Fk
ev <- eigen(A); lam <- Re(ev$values[1])
fmt <- function(name, x) sprintf("inline const std::vector<double> %s = {%s};", name, paste(sprintf("%.17g", as.numeric(x)), collapse = ","))
out <- c(fmt("size", z), fmt("next_size", z1), fmt("survived", surv), fmt("offspring", off), fmt("recruit_size", rec),
         fmt("surv_coef", coef(fs)), fmt("surv_se", summary(fs)$coefficients[, 2]), fmt("growth_coef", coef(fg)), fmt("growth_sd", gsd), fmt("fec_coef", coef(ff)),
         fmt("recruit_stats", c(rmean, rsd)), fmt("lambda", lam), fmt("survival_curve", surv_z[c(5, 30, 60, 90, 115)]))
# case-resampling bootstrap (100 replicates): index matrices exported so the C++ result is reproducible to the last digit
B <- 100
ind <- matrix(sample.int(n, n * B, replace = TRUE), B, n); rcr <- matrix(sample.int(length(rec), length(rec) * B, replace = TRUE), B, length(rec))
lam_b <- numeric(B)
for (b in 1:B) {
  i <- ind[b, ]; zb <- z[i]; sb <- surv[i]; z1b <- z1[i]; ob <- off[i]; rb <- rec[rcr[b, ]]
  fs_b <- glm(sb ~ zb, family = binomial); fg_b <- lm(z1b[sb == 1] ~ zb[sb == 1]); ff_b <- glm(ob ~ zb, family = poisson)
  sd_b <- summary(fg_b)$sigma
  sv <- plogis(coef(fs_b)[1] + coef(fs_b)[2] * zz); mn <- coef(fg_b)[1] + coef(fg_b)[2] * zz; fc <- exp(coef(ff_b)[1] + coef(ff_b)[2] * zz)
  Gb <- outer(zz, seq_len(m), function(a, j) dnorm(a, mn[j], sd_b)); Ab <- h * sweep(Gb, 2, sv, "*") + h * outer(dnorm(zz, mean(rb), sd(rb)), fc)
  lam_b[b] <- Re(eigen(Ab)$values[1])
}
out <- c(out, fmt("boot_rows", t(ind - 1)), fmt("boot_rec_rows", t(rcr - 1)), fmt("boot_lambda", lam_b), fmt("boot_ci", quantile(lam_b, c(0.025, 0.975), type = 7)), fmt("boot_se", sd(lam_b)))
writeLines(c("// Generated by NatSci/biology/verification/gen_vital_rates_ref.R (R glm / lm / eigen); do not edit.", "#pragma once", "#include <vector>", "namespace vital_rates_reference {", out, "}"), "population/test/vital_rates_reference.h")
cat("lambda", lam, "surv", coef(fs), "growth", coef(fg), gsd, "fec", coef(ff), "\n")
