# IPM oracle: midpoint-rule kernel built and analysed with numpy (full eig), plus scipy minimization of the spreading-speed functional.
# Run from NatSci/biology:  python verification/gen_ipm_ref.py
import numpy as np
from scipy.optimize import minimize_scalar
def npdf(x, m, s): return np.exp(-0.5 * ((x - m) / s) ** 2) / (s * np.sqrt(2 * np.pi))
lo, hi, n = 0.0, 10.0, 200
h = (hi - lo) / n; z = lo + h * (np.arange(n) + 0.5)
surv = 1 / (1 + np.exp(-(-1 + 0.8 * z)))
G = npdf(z[:, None], 0.5 + 0.85 * z[None, :], 0.8)          # G(z'|z)
P = h * G * surv[None, :]
fec = 0.15 * z * surv
F = h * npdf(z[:, None], 1.0, 0.6) * fec[None, :]
A = P + F
w_, V = np.linalg.eig(A); i = np.argmax(w_.real); lam = w_[i].real
w = np.abs(V[:, i].real); w = w / (w.sum() * h)
wl, Vl = np.linalg.eig(A.T); j = np.argmax(wl.real); v = np.abs(Vl[:, j].real); v = v / (h * (v * w).sum())
sens = np.outer(v, w); K = A / h; elas = K * sens / lam
Nn = np.linalg.inv(np.eye(n) - P); eta = Nn.sum(axis=0); R0 = np.max(np.linalg.eigvals(F @ Nn).real)
out = {"lam": [lam], "w": w, "v": v, "eta": eta, "R0": [R0], "sens_diag": np.diag(sens), "elas_sum": [h * h * elas.sum()]}
# spreading speed of the Laplace kernel k(x) = exp(-|x|/a) / (2a): M(s) = 1/(1 - a^2 s^2)
a = 0.8; speeds = []
for lnr in (0.3, 0.7, 1.4):
    r = minimize_scalar(lambda s: (lnr - np.log(1 - a * a * s * s)) / s, bounds=(1e-6, 1 / a - 1e-9), method="bounded", options={"xatol": 1e-14})
    speeds.append(r.fun)
out["laplace_speed"] = speeds
def arr(name, x): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(t)) for t in np.asarray(x, float).ravel()))
with open("population/test/ipm_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_ipm_ref.py; do not edit.\n#pragma once\n#include <vector>\nnamespace ipm_reference {\n" + "\n".join(arr(k, v) for k, v in out.items()) + "\n}\n")
print("lambda", lam, "R0", R0, "speeds", speeds)
