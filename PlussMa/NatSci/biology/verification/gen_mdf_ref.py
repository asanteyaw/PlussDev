"""MDF and thermodynamics-based FBA references.
MDF: scipy.optimize.linprog (HiGHS) on the problem written in Noor et al. 2014 (PLoS Comput Biol 10:e1003483): max B s.t. -(G0 + RT S^T x) >= B,
ln Cmin <= x <= ln Cmax, ratio equalities.
TFA: exhaustive enumeration of every direction pattern z in {0,1}^R, an LP per pattern with scipy (independent of the branch-and-cut)."""
import itertools, numpy as np
from scipy.optimize import linprog
RT = 8.314462618e-3 * 298.15
out = []
def arr(name, v): out.append("inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(x)) for x in np.ravel(v))))

rng = np.random.default_rng(5)
cases = []
for t in range(12):
    C = int(rng.integers(3, 6)); R = int(rng.integers(2, 6))
    S = np.zeros((C, R))
    for j in range(R):  # each reaction: one or two substrates -> one or two products
        idx = rng.choice(C, size=int(rng.integers(2, 4)), replace=False)
        S[idx[0], j] = -1; S[idx[1], j] = 1
        if len(idx) > 2: S[idx[2], j] = rng.choice([-1, 1]) * 1
    g0 = rng.uniform(-30, 25, R)
    lo = np.log(rng.choice([1e-6, 1e-5], C)); hi = np.log(rng.choice([1e-3, 1e-2], C))
    ratio = None
    if t % 3 == 0 and C >= 2: ratio = (0, 1, float(rng.choice([0.1, 1.0, 10.0])))
    # LP: variables x (C), B ; minimise -B
    c_obj = np.zeros(C + 1); c_obj[-1] = -1
    A_ub = np.hstack([RT * S.T, np.ones((R, 1))]); b_ub = -g0
    A_eq = None; b_eq = None
    if ratio:
        A_eq = np.zeros((1, C + 1)); A_eq[0, ratio[0]] = 1; A_eq[0, ratio[1]] = -1; b_eq = [np.log(ratio[2])]
        # the ratio must be reachable inside the bounds, otherwise the problem is infeasible
    bounds = [(lo[i], hi[i]) for i in range(C)] + [(-1e4, 1e4)]
    res = linprog(c_obj, A_ub=A_ub, b_ub=b_ub, A_eq=A_eq, b_eq=b_eq, bounds=bounds, method="highs")
    cases.append((C, R, S, g0, lo, hi, ratio, res.status, -res.fun if res.status == 0 else float("nan")))
arr("mdf_n", [[c[0], c[1]] for c in cases])
arr("mdf_S", np.concatenate([c[2].ravel() for c in cases])); arr("mdf_g0", np.concatenate([c[3] for c in cases]))
arr("mdf_lo", np.concatenate([c[4] for c in cases])); arr("mdf_hi", np.concatenate([c[5] for c in cases]))
arr("mdf_ratio", [[1.0, c[6][0], c[6][1], c[6][2]] if c[6] else [0.0, 0, 0, 1.0] for c in cases])
arr("mdf_status", [c[7] for c in cases]); arr("mdf_value", [c[8] for c in cases])

# TFA toy networks: enumerate z
def tfa_enumerate(S, g0, lb, ub, constrained, lo_c, hi_c, obj, eps=1e-6):
    C, R = S.shape; best = None
    for z in itertools.product([0, 1], repeat=R):
        # variables: v (net flux, R), x (C); direction pattern z: forward (z=1) means v >= 0 & dG <= -eps ; reverse (z=0): v <= 0 & dG >= eps (only for constrained)
        c_obj = np.concatenate([-np.array(obj), np.zeros(C)])
        A_eq = np.hstack([S, np.zeros((C, C))]); b_eq = np.zeros(C)
        A_ub = []; b_ub = []; bounds = []
        for j in range(R):
            l, u = lb[j], ub[j]
            if constrained[j]:
                if z[j] == 1: l = max(l, 0.0)
                else: u = min(u, 0.0)
                row = np.concatenate([np.zeros(R), RT * S[:, j]])
                if z[j] == 1: A_ub.append(row); b_ub.append(-g0[j] - eps)
                else: A_ub.append(-row); b_ub.append(g0[j] - eps)
            bounds.append((l, u))
        bounds += [(lo_c[i], hi_c[i]) for i in range(C)]
        res = linprog(c_obj, A_ub=np.array(A_ub) if A_ub else None, b_ub=b_ub if b_ub else None, A_eq=A_eq, b_eq=b_eq, bounds=bounds, method="highs")
        if res.status == 0 and (best is None or -res.fun > best): best = -res.fun
    return best
tfa = []
# network 1: uptake -> A -> B -> secretion;  reactions: EX_A (A source, unconstrained), R1: A -> B, R2: B -> (sink, unconstrained)
def toy(dg_r1, lo_c, hi_c, rev_r1=False):
    S = np.array([[1, -1, 0], [0, 1, -1]], float)   # compounds A, B ; reactions: uptake, R1, sink
    g0 = np.array([0.0, dg_r1, 0.0]); lb = [0, -50 if rev_r1 else 0, 0]; ub = [10, 50, 50]
    constrained = [0, 1, 0]
    obj = [0, 0, 1]
    return S, g0, lb, ub, constrained, lo_c, hi_c, obj
toys = [(-10.0, 1e-6, 1e-2, False), (+10.0, 1e-6, 1e-2, False), (+60.0, 1e-6, 1e-2, False), (+12.0, 1e-3, 1e-2, False), (+5.0, 1e-6, 1e-2, True), (-20.0, 1e-6, 1e-2, True)]
for dg, lo, hi, rev in toys:
    S, g0, lb, ub, cons, loc, hic, obj = toy(dg, np.log([lo, lo]), np.log([hi, hi]), rev)
    tfa.append((dg, lo, hi, 1.0 if rev else 0.0, tfa_enumerate(S, g0, lb, ub, cons, loc, hic, obj) if True else None))
arr("tfa_cases", [[t[0], t[1], t[2], t[3]] for t in tfa]); arr("tfa_value", [t[4] if t[4] is not None else float("nan") for t in tfa])
with open("metabolism/test/mdf_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_mdf_ref.py; do not edit.\n#pragma once\n#include <vector>\nnamespace mdf_reference {\n" + "\n".join(out) + "\n}\n")
print("ok", len(out), "arrays;", sum(1 for c in cases if c[7] == 0), "feasible of", len(cases))
