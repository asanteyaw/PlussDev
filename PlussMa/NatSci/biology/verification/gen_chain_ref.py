# Planar chain oracle: symbolic Lagrangian derivation (sympy) of M(q), h(q, qd) and the end-point generalised force for a 3-link chain, evaluated at
# random states, plus an independent DOP853 trajectory with PD feedback. Run from NatSci/biology:  python verification/gen_chain_ref.py
import numpy as np, sympy as sp
from scipy.integrate import solve_ivp
n = 3
q = sp.symbols("q1:%d" % (n + 1)); qd = sp.symbols("d1:%d" % (n + 1)); qdd = sp.symbols("dd1:%d" % (n + 1))
m = sp.symbols("m1:%d" % (n + 1), positive=True); l = sp.symbols("l1:%d" % (n + 1), positive=True); c = sp.symbols("c1:%d" % (n + 1), positive=True); I = sp.symbols("I1:%d" % (n + 1), positive=True)
g = sp.Symbol("g", positive=True); fx, fy = sp.symbols("fx fy")
th = [sum(q[: i + 1]) for i in range(n)]
thd = [sum(qd[: i + 1]) for i in range(n)]
jx = [0]; jy = [0]; cx = []; cy = []
for i in range(n):
    cx.append(jx[-1] + c[i] * sp.cos(th[i])); cy.append(jy[-1] + c[i] * sp.sin(th[i]))
    jx.append(jx[-1] + l[i] * sp.cos(th[i])); jy.append(jy[-1] + l[i] * sp.sin(th[i]))
def tdot(e): return sum(sp.diff(e, q[k]) * qd[k] for k in range(n))
T = sum(sp.Rational(1, 2) * m[i] * (tdot(cx[i]) ** 2 + tdot(cy[i]) ** 2) + sp.Rational(1, 2) * I[i] * thd[i] ** 2 for i in range(n))
V = sum(m[i] * g * cy[i] for i in range(n))
L = T - V
M = sp.hessian(T, qd)
# h = M-free part: tau_free = d/dt(dL/dqd) - dL/dq with qdd = 0
tau = []
for k in range(n):
    p = sp.diff(L, qd[k])
    ddt = sum(sp.diff(p, q[j]) * qd[j] + sp.diff(p, qd[j]) * qdd[j] for j in range(n))
    tau.append(ddt - sp.diff(L, q[k]))
tau = sp.Matrix(tau)
h = tau.subs({s: 0 for s in qdd})
# end-point generalised force J^T F
Jt = sp.Matrix([[sp.diff(jx[-1], q[k]), sp.diff(jy[-1], q[k])] for k in range(n)])
JF = Jt * sp.Matrix([fx, fy])
args = list(q) + list(qd) + list(qdd) + list(m) + list(l) + list(c) + list(I) + [g, fx, fy]
f_tau = sp.lambdify(args, tau - JF, "numpy"); f_M = sp.lambdify(list(q) + list(m) + list(l) + list(c) + list(I), M, "numpy"); f_h = sp.lambdify(list(q) + list(qd) + list(m) + list(l) + list(c) + list(I) + [g], h, "numpy")
f_E = sp.lambdify(list(q) + list(qd) + list(m) + list(l) + list(c) + list(I) + [g], [T, V], "numpy")
rng = np.random.default_rng(21)
P = dict(m=[2.1, 1.3, 0.6], l=[0.42, 0.38, 0.2], c=[0.18, 0.15, 0.09], I=[0.031, 0.017, 0.004], g=9.80665)
cases = []; taus = []; Ms = []; hs = []; Es = []
for _ in range(8):
    qq = rng.uniform(-1.2, 1.2, n); dq = rng.uniform(-3, 3, n); ddq = rng.uniform(-8, 8, n); F = rng.uniform(-30, 30, 2)
    cases += list(qq) + list(dq) + list(ddq) + list(F)
    a = list(qq) + list(dq) + list(ddq) + P["m"] + P["l"] + P["c"] + P["I"] + [P["g"], F[0], F[1]]
    taus += list(np.array(f_tau(*a), float).ravel())
    Ms += list(np.array(f_M(*(list(qq) + P["m"] + P["l"] + P["c"] + P["I"])), float).ravel())
    hs += list(np.array(f_h(*(list(qq) + list(dq) + P["m"] + P["l"] + P["c"] + P["I"] + [P["g"]])), float).ravel())
    Es += [float(v) for v in f_E(*(list(qq) + list(dq) + P["m"] + P["l"] + P["c"] + P["I"] + [P["g"]]))]
# trajectory with PD feedback: tau = -kp (q - q_ref) - kd qd
kp, kd = 25.0, 4.0; qref = np.array([0.4, -0.3, 0.2])
def rhs(t, y):
    qq = y[:n]; dq = y[n:]
    Mn = np.array(f_M(*(list(qq) + P["m"] + P["l"] + P["c"] + P["I"])), float); hn = np.array(f_h(*(list(qq) + list(dq) + P["m"] + P["l"] + P["c"] + P["I"] + [P["g"]])), float).ravel()
    tq = -kp * (qq - qref) - kd * dq
    return np.r_[dq, np.linalg.solve(Mn, tq - hn)]
y0 = np.r_[[0.9, 0.1, -0.5], [0.0, 0.0, 0.0]]
sol = solve_ivp(rhs, (0, 2.0), y0, method="DOP853", rtol=1e-12, atol=1e-13, dense_output=True)
ts = [0.25, 0.5, 1.0, 1.5, 2.0]
traj = [v for t in ts for v in sol.sol(t)]
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(t)) for t in np.asarray(a, float).ravel()))
with open("biomechanics/test/chain_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_chain_ref.py (sympy Lagrangian); do not edit.\n#pragma once\n#include <vector>\nnamespace chain_reference {\n" + "\n".join([arr("m", P["m"]), arr("l", P["l"]), arr("c", P["c"]), arr("I", P["I"]), arr("cases", cases), arr("tau", taus), arr("mass_matrix", Ms), arr("bias", hs), arr("energy", Es), arr("traj", traj), arr("traj_t", ts), "inline const double kp = %r, kd = %r;" % (kp, kd), arr("qref", qref), arr("y0", y0)]) + "\n}\n")
print("ok")
