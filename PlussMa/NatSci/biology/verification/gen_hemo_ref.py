# Haemodynamics oracle: mpmath complex Bessel functions and the Womersley formulas evaluated with them, and an ODE integration of the 3-element
# Windkessel (scipy DOP853) under a periodic flow compared later with the impedance harmonic sum. Run from NatSci/biology:  python verification/gen_hemo_ref.py
import numpy as np, mpmath as mp
from scipy.integrate import solve_ivp
mp.mp.dps = 40
zs = [0.3 + 0.2j, 2.0 - 1.5j, -3.0 + 3.0j, 8.0 + 8.0j, -14.0 + 14.0j, 20.0 * np.exp(0.75j * np.pi), 30.0 * np.exp(0.75j * np.pi), 1e-3 + 0j, 6.0 + 0j]
bes = []
for z in zs:
    z = mp.mpc(z); bes += [float(mp.besselj(0, z).real), float(mp.besselj(0, z).imag), float(mp.besselj(1, z).real), float(mp.besselj(1, z).imag)]
rho, mu, R, A = 1060.0, 0.0035, 0.012, 80.0  # blood-like fluid in a 12 mm radius tube, gradient amplitude 80 Pa/m
ws = [0.5, 2 * np.pi * 1.0, 2 * np.pi * 5.0, 2 * np.pi * 15.0]
w_out = []
for w in ws:
    alpha = R * mp.sqrt(w * rho / mu); lam = mp.mpf(alpha) * mp.exp(1j * 3 * mp.pi / 4)
    J0, J1 = mp.besselj(0, lam), mp.besselj(1, lam)
    Q = mp.pi * R ** 2 * A / (1j * rho * w) * (1 - 2 * J1 / (lam * J0))
    tau = 1j * mu * A / (rho * w) * lam / R * J1 / J0
    u_half = A / (1j * rho * w) * (1 - mp.besselj(0, lam * 0.5) / J0)
    w_out += [w, float(alpha), float(Q.real), float(Q.imag), float(tau.real), float(tau.imag), float(u_half.real), float(u_half.imag)]
# Windkessel: periodic flow, 3 harmonics
Rp, C, Zc = 1.1e8, 1.4e-8, 7.0e6
T = 0.8; w0 = 2 * np.pi / T
harm = [(1.0e-4, 0.0), (2.5e-5, 0.4), (1.2e-5, -0.9)]  # amplitude [m^3/s], phase for harmonics 1..3
Q0 = 8.0e-5
def Qt(t): return Q0 + sum(a * np.cos((k + 1) * w0 * t + ph) for k, (a, ph) in enumerate(harm))
sol = solve_ivp(lambda t, y: [(Qt(t) - y[0] / Rp) / C], (0, 40 * T), [0.0], method="DOP853", rtol=1e-11, atol=1e-6, dense_output=True)
ts = 39 * T + np.linspace(0, T, 9)[:-1]
pc = [sol.sol(t)[0] for t in ts]; p = [pc[i] + Zc * Qt(t) for i, t in enumerate(ts)]
wk = [Rp, C, Zc, T, Q0] + [v for h in harm for v in h] + list(ts) + p
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(t)) for t in np.asarray(a, float).ravel()))
with open("biomechanics/test/hemo_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_hemo_ref.py (mpmath, scipy); do not edit.\n#pragma once\n#include <vector>\nnamespace hemo_reference {\n" + "\n".join([arr("zs_re", [z.real for z in zs]), arr("zs_im", [z.imag for z in zs]), arr("bessel", bes), "inline const double rho = %r, mu = %r, radius = %r, gradient = %r;" % (rho, mu, R, A), arr("womersley", w_out), arr("windkessel", wk)]) + "\n}\n")
print("ok", "alpha values", [round(w_out[8 * i + 1], 2) for i in range(len(ws))])
