"""Protein-folding references. Equilibrium / chevron models are evaluated with the OPEN PyFolding package (models.py read from GitHub,
quantumjot/PyFolding, SHA-256 8b277549...), imported from a local checkout. Thermal unfolding is checked against numerical integration of
the thermodynamic identities dH/dT = dCp, dS/dT = dCp/T (scipy solve_ivp) and brentq root finding, independent of the closed form."""
import sys, numpy as np
sys.path.insert(0, sys.argv[1])
from pyfolding import models, core, constants as pc
from scipy import integrate, optimize
out = []
def arr(name, v):
    out.append("inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(x)) for x in np.ravel(v))))
RT = pc.RT
arr("pf_rt", [RT])
x = np.linspace(0.0, 9.0, 19); arr("pf_x", x)
two = models.TwoStateEquilibrium(); arr("pf_two_F", two.fit_func(x, 1.9, 4.2)); arr("pf_two_p", [1.9, 4.2])
sl = models.TwoStateEquilibriumSloping(); arr("pf_sloping", sl.fit_func(x, 1.1, -0.03, 0.2, 0.012, 1.9, 4.2)); arr("pf_sloping_p", [1.1, -0.03, 0.2, 0.012, 1.9, 4.2])
th = models.ThreeStateEquilibrium(); arr("pf_three_signal", th.fit_func(x, 1.0, 0.45, 0.05, 4.0, 1.6, 3.0, 1.1)); arr("pf_three_p", [1.0, 0.45, 0.05, 4.0, 1.6, 3.0, 1.1])
# populations of the three-state model from its definition (Y = 1, 0, 0 etc. extracts each population)
arr("pf_three_FN", th.fit_func(x, 1, 0, 0, 4.0, 1.6, 3.0, 1.1)); arr("pf_three_FI", th.fit_func(x, 0, 1, 0, 4.0, 1.6, 3.0, 1.1)); arr("pf_three_FD", th.fit_func(x, 0, 0, 1, 4.0, 1.6, 3.0, 1.1))
dm = models.TwoStateDimerEquilibrium(); arr("pf_dimer_FD", [dm.fit_func(xx, 0, 0, 1, 0, 1.8, 3.5, 2e-6) for xx in x]); arr("pf_dimer_p", [1.8, 3.5, 2e-6])
import mpmath as mp
mp.mp.dps = 60
def dimer_exact(xx, m=1.8, d50=3.5, Pt=2e-6):
    K = mp.mpf(Pt) * mp.e ** (mp.mpf(m) * (mp.mpf(xx) - mp.mpf(d50)) / mp.mpf(RT)); P = mp.mpf(Pt)
    return float((mp.sqrt(K**2 + 8 * K * P) - K) / (4 * P))
arr("pf_dimer_exact", [dimer_exact(xx) for xx in x])
ch = models.TwoStateChevron(); arr("pf_chev_two", ch.fit_func(x, 150.0, 1.7, 3e-4, 0.95)); arr("pf_chev_two_p", [150.0, 1.7, 3e-4, 0.95])
c3 = models.ThreeStateChevron(); arr("pf_chev_three", c3.fit_func(x, 4.5e-4, -0.95, 1.3e9, -6.9, 1.4e-8, -1.6)); arr("pf_chev_three_p", [4.5e-4, -0.95, 1.3e9, -6.9, 1.4e-8, -1.6])
# thermal: dHm = 80 kcal/mol, Tm = 340 K, dCp = 1.5 kcal/mol/K ; integrate dG/dT numerically from Tm
dHm, Tm, dCp = 80.0, 340.0, 1.5
Rg = 1.987204258e-3
def dHdT(T): return dCp
def ds_dT(T): return dCp / T
Ts = np.array([250.0, 270.0, 290.0, 310.0, 330.0, 340.0, 350.0, 365.0, 380.0])
def G_numeric(T):
    # G(T) = H(T) - T S(T) with H, S obtained by integrating dH/dT = dCp and dS/dT = dCp/T from T_m (S(Tm) = dHm/Tm)
    sol = integrate.solve_ivp(lambda t, y: [dCp, dCp / t], [Tm, T], [dHm, dHm / Tm], rtol=1e-13, atol=1e-13)
    H, S = sol.y[0, -1], sol.y[1, -1]
    return H - T * S
arr("th_T", Ts); arr("th_G", [G_numeric(T) for T in Ts]); arr("th_p", [dHm, Tm, dCp])
Gf = lambda T: G_numeric(T)
arr("th_roots", [optimize.brentq(Gf, 200.0, Tm - 1e-6, xtol=1e-12), optimize.brentq(Gf, Tm + 1e-6, 600.0, xtol=1e-12) if Gf(600.0) * Gf(Tm + 1e-6) < 0 else Tm])
Ts_stab = Tm * np.exp(-dHm / (dCp * Tm)); arr("th_Tstab_numeric", [optimize.minimize_scalar(lambda T: -G_numeric(T), bracket=(250.0, 280.0, 310.0), tol=1e-12).x])
arr("th_frac", [(lambda G: np.exp(-G / (Rg * T)) / (1 + np.exp(-G / (Rg * T))))(G_numeric(T)) for T in Ts])
with open("biophysics/test/folding_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_folding_ref.py; do not edit.\n#pragma once\n#include <vector>\nnamespace folding_reference {\n" + "\n".join(out) + "\n}\n")
print("ok", len(out), "arrays")
