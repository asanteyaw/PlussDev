# Count-based PVA with observation error: independent scalar Kalman filter / RTS smoother in numpy, scipy L-BFGS-B + Nelder-Mead maximum likelihood, finite-difference
# Hessian, and scipy quad for the extinction risk (Dennis et al. 2006). Run from NatSci/biology:  python verification/gen_count_pva_ref.py
import numpy as np
from scipy.optimize import minimize
from scipy.integrate import quad
from scipy.stats import norm
rng = np.random.default_rng(20261024)
T, mu_t, s2_t, e2_t = 36, 0.012, 0.018, 0.035
x = np.empty(T); x[0] = np.log(420.0)
for t in range(1, T): x[t] = x[t - 1] + mu_t + np.sqrt(s2_t) * rng.standard_normal()
y = x + np.sqrt(e2_t) * rng.standard_normal(T)
y[[5, 6, 17, 24]] = np.nan                     # missing census years
counts = np.exp(y)
def kalman(y, mu, s2, e2, smooth=False):
    k = 0; m0, P0 = y[0], e2                   # first census initialises the state
    obs = y[1:]; n = len(obs)
    mp = np.zeros(n); Pp = np.zeros(n); mf = np.zeros(n); Pf = np.zeros(n); ll = 0.0; m, P = m0, P0
    for i in range(n):
        m, P = m + mu, P + s2; mp[i], Pp[i] = m, P
        if np.isfinite(obs[i]):
            S = P + e2; v = obs[i] - m; ll += -0.5 * (np.log(2 * np.pi * S) + v * v / S); K = P / S; m, P = m + K * v, (1 - K) * P
        mf[i], Pf[i] = m, P
    if not smooth: return ll
    ms = mf.copy(); Ps = Pf.copy()
    for i in range(n - 2, -1, -1):
        J = Pf[i] / Pp[i + 1]; ms[i] = mf[i] + J * (ms[i + 1] - mp[i + 1]); Ps[i] = Pf[i] + J * J * (Ps[i + 1] - Pp[i + 1])
    return ll, mf, Pf, ms, Ps
fixed = [(0.01, 0.02, 0.03), (-0.03, 0.05, 0.001), (0.1, 0.004, 0.2)]
lls = [kalman(y, *p) for p in fixed]
nll = lambda th: -kalman(y, th[0], np.exp(th[1]), np.exp(th[2]))
th0 = np.array([0.0, np.log(0.02), np.log(0.02)])
r = minimize(nll, th0, method="L-BFGS-B"); r = minimize(nll, r.x, method="Nelder-Mead", options={"xatol": 1e-12, "fatol": 1e-14, "maxiter": 20000, "maxfev": 40000})
th = r.x; mu, s2, e2 = th[0], np.exp(th[1]), np.exp(th[2])
def hess(f, x0, h):
    n = len(x0); H = np.zeros((n, n))
    for i in range(n):
        for j in range(n):
            ei = np.eye(n)[i] * h[i]; ej = np.eye(n)[j] * h[j]
            H[i, j] = (f(x0 + ei + ej) - f(x0 + ei - ej) - f(x0 - ei + ej) + f(x0 - ei - ej)) / (4 * h[i] * h[j])
    return H
C = np.linalg.inv(hess(nll, th, [2e-4, 2e-3, 2e-3]))
se = [np.sqrt(C[0, 0]), s2 * np.sqrt(C[1, 1]), e2 * np.sqrt(C[2, 2])]
ll, mf, Pf, ms, Ps = kalman(y, mu, s2, e2, True)
m, P = mf[-1], Pf[-1]
Nc = 50.0; H = [10.0, 25.0, 50.0, 100.0]
def cdf(xd, t):
    s = np.sqrt(s2 * t); return norm.cdf((-xd - mu * t) / s) + np.exp(-2 * mu * xd / s2) * norm.cdf((-xd + mu * t) / s)
risk = []
for t in H:
    dens = lambda xd: norm.pdf(xd, m - np.log(Nc), np.sqrt(P))
    risk.append(norm.cdf(0, m - np.log(Nc), np.sqrt(P)) + quad(lambda xd: cdf(xd, t) * dens(xd), 0, m - np.log(Nc) + 12 * np.sqrt(P), epsabs=1e-13, epsrel=1e-12, limit=200)[0])
ult = norm.cdf(0, m - np.log(Nc), np.sqrt(P)) + quad(lambda xd: np.exp(-2 * mu * xd / s2) * norm.pdf(xd, m - np.log(Nc), np.sqrt(P)), 0, m - np.log(Nc) + 12 * np.sqrt(P), epsabs=1e-13, epsrel=1e-12)[0] if mu > 0 else 1.0
out = dict(counts=counts, fixed=np.array(fixed).ravel(), fixed_ll=lls, mle=[mu, s2, e2], mle_ll=ll, se=se, smoothed_mean=ms, smoothed_sd=np.sqrt(Ps), filt=[m, P],
           horizons=H, risk=risk, ultimate=[ult], threshold=[Nc], truth=[mu_t, s2_t, e2_t])
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(("NAN" if np.isnan(t) else repr(float(t))) for t in np.asarray(a, float).ravel()))
