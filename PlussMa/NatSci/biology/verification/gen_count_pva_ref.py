    fh.write("// Generated by NatSci/biology/verification/gen_count_pva_ref.py; do not edit.\n#pragma once\n#include <cmath>\n#include <vector>\nnamespace count_pva_reference {\n" + "\n".join(arr(k_, v_) for k_, v_ in out.items()) + "\n}\n")
