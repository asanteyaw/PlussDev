# Proton-linkage oracle: brute-force enumeration of all 2^n protonation microstates (mpmath), and the closed-form bell-shaped enzyme profile.
# Run from NatSci/biology:  python verification/gen_linkage_ref.py
import itertools, numpy as np, mpmath as mp
mp.mp.dps = 40
def enum_Z(pks, pH):
    # microstates: each site protonated (weight 10^(pK - pH) relative to deprotonated) or not
    Z = mp.mpf(0); H = mp.mpf(0)
    for bits in itertools.product([0, 1], repeat=len(pks)):
        w = mp.mpf(1)
        for b, pk in zip(bits, pks):
            if b: w *= mp.mpf(10) ** (pk - pH)
        Z += w; H += sum(bits) * w
    return Z, H / Z
free = [4.1, 4.1, 6.3, 9.8, 10.4]          # sites of the free receptor (two equivalent carboxyl, His, Tyr/Lys-like)
bound = [4.1, 5.2, 6.9, 9.8, 10.4]         # shifted pK in the complex
phs = [3.0, 4.5, 5.5, 6.5, 7.4, 8.5, 10.0, 11.5]
out = {"free_pk": free, "bound_pk": bound, "ph": phs}
lz_f, lz_b, h_f, h_b = [], [], [], []
for ph in phs:
    zf, hf = enum_Z(free, ph); zb, hb = enum_Z(bound, ph)
    lz_f.append(float(mp.log(zf))); lz_b.append(float(mp.log(zb))); h_f.append(float(hf)); h_b.append(float(hb))
out.update(lnz_free=lz_f, lnz_bound=lz_b, h_free=h_f, h_bound=h_b)
# polyprotic (diprotic enzyme): log10 beta1 = pK2, log10 beta2 = pK1 + pK2 (pK1 < pK2 are the macroscopic pKs of EH2 -> EH -> E).
pk1, pk2 = 5.6, 8.1
out["poly_logbeta"] = [pk2, pk1 + pk2]
# active EH: fraction = 1 / (1 + 10^(pK1 - pH) + 10^(pH - pK2))   (the textbook bell-shaped pH profile)
out["bell"] = [1 / (1 + 10 ** (pk1 - ph) + 10 ** (ph - pk2)) for ph in phs]
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(t)) for t in np.asarray(a, float).ravel()))
with open("biophysics/test/linkage_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_linkage_ref.py; do not edit.\n#pragma once\n#include <vector>\nnamespace linkage_reference {\n" + "\n".join(arr(k, v) for k, v in out.items()) + "\n}\n")
