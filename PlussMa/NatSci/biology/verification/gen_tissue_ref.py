import numpy as np, sympy as sp
F = sp.Matrix(3, 3, sp.symbols("f11 f12 f13 f21 f22 f23 f31 f32 f33"))
C = F.T * F
I1 = C.trace(); I2 = sp.Rational(1, 2) * (I1 ** 2 - (C * C).trace())
mu, c10, c01, c20, c30, jm, cf, bf, k1, k2, kap, gam = sp.symbols("mu c10 c01 c20 c30 jm cf bf k1 k2 kap gam", positive=True)
models = {
    "neo": (mu / 2 * (I1 - 3), {mu: 1.7}),
    "mr": (c10 * (I1 - 3) + c01 * (I2 - 3), {c10: 0.9, c01: 0.35}),
    "yeoh": (c10 * (I1 - 3) + c20 * (I1 - 3) ** 2 + c30 * (I1 - 3) ** 3, {c10: 0.8, c20: 0.05, c30: 0.004}),
    "gent": (-mu * jm / 2 * sp.log(1 - (I1 - 3) / jm), {mu: 1.2, jm: 9.0}),
    "fung": (cf / 2 * (sp.exp(bf * (I1 - 3)) - 1), {cf: 0.6, bf: 0.8}),
}
def cauchy(W, sub, Fnum):
    P = W.diff(F)  # elementwise dW/dF (sympy Matrix.diff on a matrix argument returns the elementwise derivative)
    Pn = sp.Matrix(3, 3, lambda i, j: sp.diff(W, F[i, j]))
    return np.array((Pn * F.T).subs(sub).subs(dict(zip(F, Fnum.flatten()))).evalf(), float)
lam_uni = [1.05, 1.2, 1.6, 2.1]; lam_bi = [1.04, 1.15, 1.4]; lam_pl = [1.1, 1.5]; gam_sh = [0.2, 0.7]
out = {}
for name, (W, sub) in models.items():
    uni, bi, pl, sh = [], [], [], []
    for l in lam_uni:
        S = cauchy(W, sub, np.diag([l, l ** -0.5, l ** -0.5])); uni.append(S[0, 0] - S[1, 1])
    for l in lam_bi:
        S = cauchy(W, sub, np.diag([l, l, l ** -2])); bi.append(S[0, 0] - S[2, 2])
    for l in lam_pl:
        S = cauchy(W, sub, np.diag([l, 1.0, 1 / l])); pl.append(S[0, 0] - S[2, 2])
    for g in gam_sh:
        S = cauchy(W, sub, np.array([[1, g, 0], [0, 1, 0], [0, 0, 1.0]])); sh += [S[0, 1], S[0, 0] - S[1, 1]]
    out[name] = (uni, bi, pl, sh, [float(v) for v in sub.values()])
# Ogden (3 terms): reduced-energy derivatives
al = [1.3, 5.0, -2.0]; mus = [0.63, 0.0012, -0.01]
l1, l2, l3 = sp.symbols("l1 l2 l3", positive=True)
Wo = sum(m / a * (l1 ** a + l2 ** a + l3 ** a - 3) for m, a in zip(mus, al))
lam = sp.Symbol("lam", positive=True)
uo = (lam * sp.diff(Wo.subs({l1: lam, l2: lam ** sp.Rational(-1, 2), l3: lam ** sp.Rational(-1, 2)}), lam))
bo = (lam / 2 * sp.diff(Wo.subs({l1: lam, l2: lam, l3: lam ** -2}), lam))
po = (lam * sp.diff(Wo.subs({l1: lam, l2: 1, l3: 1 / lam}), lam))
ogden = dict(uni=[float(uo.subs(lam, x)) for x in lam_uni], bi=[float(bo.subs(lam, x)) for x in lam_bi], pl=[float(po.subs(lam, x)) for x in lam_pl])
# HGO artery: full F-based W including the Macaulay bracket, biaxial (lt, lz) with lr = 1/(lt lz), sigma_rr eliminated
a = sp.Matrix([sp.cos(gam), sp.sin(gam), 0]); b = sp.Matrix([sp.cos(gam), -sp.sin(gam), 0])
def fib(avec):
    I4 = (avec.T * C * avec)[0]; E = kap * (I1 - 3) + (1 - 3 * kap) * (I4 - 1)
    return k1 / (2 * k2) * (sp.exp(k2 * sp.Piecewise((E, E > 0), (0, True)) ** 2) - 1)
Wh = c10 * (I1 - 3) + fib(a) + fib(b)
cases = [(1.15, 1.10, dict(c10=0.9, k1=2.4, k2=3.1, kap=0.1, gam=0.7)), (1.05, 1.35, dict(c10=0.9, k1=2.4, k2=3.1, kap=0.0, gam=0.9)), (1.2, 1.2, dict(c10=0.5, k1=5.0, k2=1.2, kap=0.226, gam=0.87)), (0.9, 0.95, dict(c10=0.9, k1=2.4, k2=3.1, kap=0.1, gam=0.7))]
hg = []
for lt, lz, pr in cases:
    sub = {c10: pr["c10"], k1: pr["k1"], k2: pr["k2"], kap: pr["kap"], gam: pr["gam"]}
    S = cauchy(Wh, sub, np.diag([lt, lz, 1 / (lt * lz)]))
    hg += [lt, lz, pr["c10"], pr["k1"], pr["k2"], pr["kap"], pr["gam"], S[0, 0] - S[2, 2], S[1, 1] - S[2, 2]]
def arr(name, v): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(t)) for t in np.asarray(v, float).ravel()))
lines = [arr("lam_uni", lam_uni), arr("lam_bi", lam_bi), arr("lam_pl", lam_pl), arr("gam_sh", gam_sh)]
