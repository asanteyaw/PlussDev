# Soft-tissue oracle: sympy differentiation of the strain-energy functions with respect to the deformation gradient F (first Piola P = dW/dF,
# Cauchy stress sigma = P F^T - p I for incompressible J = 1, pressure p fixed by the boundary condition of each test).
