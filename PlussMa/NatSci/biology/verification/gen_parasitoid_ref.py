# Host-parasitoid oracle: numpy eigenvalues of numerically differentiated Jacobians at the fsolve equilibria, and a coupled-map-lattice run in numpy.
# Run from NatSci/biology:  python verification/gen_parasitoid_ref.py
import numpy as np
from scipy.optimize import fsolve
def nb(s, lam, a, c): h, p = s; e = np.exp(-a * p); return np.array([lam * h * e, c * h * (1 - e)])
def nbin(s, lam, a, c, k): h, p = s; e = (1 + a * p / k) ** (-k); return np.array([lam * h * e, c * h * (1 - e)])
def bed(s, r, K, a, c): h, p = s; e = np.exp(-a * p); return np.array([h * np.exp(r * (1 - h / K) - a * p), c * h * (1 - e)])
def jac(f, s, h=1e-6):
    J = np.zeros((2, 2))
    for j in range(2):
        d = np.zeros(2); d[j] = h * abs(s[j]); J[:, j] = (f(s + d) - f(s - d)) / (2 * h * abs(s[j]))
    return J
out = []
cases = [("nb", (2.0, 0.05, 1.0)), ("nb", (1.5, 0.1, 0.8)), ("nbin", (2.0, 0.05, 1.0, 0.6)), ("nbin", (2.0, 0.05, 1.0, 1.5)), ("nbin", (3.0, 0.1, 1.0, 0.3)), ("bed", (0.8, 40.0, 0.05, 1.0)), ("bed", (1.6, 40.0, 0.05, 1.0))]
for kind, pr in cases:
    f = {"nb": nb, "nbin": nbin, "bed": bed}[kind]
    g = lambda s: f(s, *pr)
    if kind == "nb": lam, a, c = pr; P = np.log(lam) / a; guess = np.array([P * lam / (c * (lam - 1)), P])
    elif kind == "nbin": lam, a, c, k = pr; P = (lam ** (1 / k) - 1) * k / a; guess = np.array([P * lam / (c * (lam - 1)), P])
    else: guess = np.array([15.0, 8.0])
    eq, info, ier, msg = fsolve(lambda s: g(s) - s, guess, xtol=1e-14, full_output=True)
    assert np.abs(g(eq) - eq).max() < 1e-9, (kind, pr, eq, ier, msg)
    J = jac(g, eq); ev = np.linalg.eigvals(J)
    out.append((kind, pr, eq, J, np.abs(ev).max()))
kinds = {"nb": 0, "nbin": 1, "bed": 2}
flat = []
for kind, pr, eq, J, rho in out:
    flat += [kinds[kind]] + list(pr) + [0.0] * (4 - len(pr)) + list(eq) + list(J.ravel()) + [rho]
# coupled-map lattice: Ricker local dynamics on a ring of 12 patches, 40 steps
rng = np.random.default_rng(4)
n0 = rng.uniform(0.2, 1.6, 12); r = 2.7; D = 0.25
n = n0.copy()
for _ in range(40):
    f = n * np.exp(r * (1 - n)); n = (1 - D) * f + 0.5 * D * (np.roll(f, 1) + np.roll(f, -1))
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(t)) for t in np.asarray(a, float).ravel()))
with open("population/test/parasitoid_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_parasitoid_ref.py; do not edit.\n#pragma once\n#include <vector>\nnamespace parasitoid_reference {\n" + "\n".join([arr("cases", flat), arr("cml_n0", n0), arr("cml_n40", n), "inline const double cml_r = %r, cml_d = %r;" % (r, D)]) + "\n}\n")
print([(k, round(float(rho), 4)) for k, pr, eq, J, rho in out])
