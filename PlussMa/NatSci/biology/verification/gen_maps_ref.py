# Discrete-map oracle: numpy orbit/Lyapunov scans for logistic, Ricker and Hassell maps, and high-precision superstable parameters of the
# logistic map by mpmath (the Feigenbaum cascade). Run from NatSci/biology:  python verification/gen_maps_ref.py
import numpy as np, mpmath as mp
mp.mp.dps = 50
def lyap(f, df, x0, burn, n):
    x = x0
    for _ in range(burn): x = f(x)
    s = 0.0
    for _ in range(n):
        s += np.log(abs(df(x))); x = f(x)
    return s / n
out = {}
rs = np.array([2.8, 3.2, 3.5, 3.55, 3.83, 3.9, 4.0 - 1e-9])
out["logistic_r"] = rs
out["logistic_lyap"] = [lyap(lambda x, r=r: r * x * (1 - x), lambda x, r=r: r * (1 - 2 * x), 0.3, 2000, 200000) for r in rs]
rk = np.array([1.5, 2.2, 2.55, 2.7, 3.0, 3.5])
out["ricker_r"] = rk
out["ricker_lyap"] = [lyap(lambda x, r=r: x * np.exp(r * (1 - x)), lambda x, r=r: np.exp(r * (1 - x)) * (1 - r * x), 0.4, 2000, 200000) for r in rk]
hs = np.array([2.0, 5.0, 10.0, 15.0, 30.0])
out["hassell_lambda"] = hs
out["hassell_lyap"] = [lyap(lambda x, l=l: l * x * (1 + 0.5 * x) ** -3.0, lambda x, l=l: l * (1 + 0.5 * x) ** -4.0 * (1 + 0.5 * x - 1.5 * x), 0.5, 2000, 200000) for l in hs]
# superstable parameters R_n: f_R^(2^n)(1/2) = 1/2
R = []
guess = 2.0
for n in range(0, 8):
    p = 2 ** n
    g = lambda r: (lambda x: [x := r * x * (1 - x) for _ in range(p)][-1] - mp.mpf(1) / 2)(mp.mpf(1) / 2)
    r0 = mp.findroot(g, mp.mpf(guess)) if n == 0 else mp.findroot(g, mp.mpf(guess))
    R.append(float(r0))
    if n == 0: guess = 3.2
    elif n == 1: guess = 3.4985
    else: guess = float(r0) + (R[-1] - R[-2]) / 4.6692
    if n >= 1: guess = float(r0) + (float(r0) - R[-2]) / 4.6692
out["superstable"] = R
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(t)) for t in np.asarray(a, float).ravel()))
with open("population/test/maps_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_maps_ref.py; do not edit.\n#pragma once\n#include <vector>\nnamespace maps_reference {\n" + "\n".join(arr(k, v) for k, v in out.items()) + "\n}\n")
print(R)
