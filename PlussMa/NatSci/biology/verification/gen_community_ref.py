# Community / adaptive-dynamics oracle: numpy eigenvalues of random matrices, sympy second derivatives of the Gaussian competition fitness,
# scipy fsolve for chemostat and Lotka-Volterra equilibria. Run from NatSci/biology:  python verification/gen_community_ref.py
import numpy as np, sympy as sp
from scipy.optimize import fsolve
rng = np.random.default_rng(3)
out = {}
mats = []; abscissa = []
for _ in range(30):
    S = 9; M = rng.normal(0, 0.5, (S, S)) - 0.2 * np.eye(S); M *= rng.random((S, S)) < 0.8
    mats.append(M); abscissa.append(np.linalg.eigvals(M).real.max())
out["rand_mats"] = np.array(mats); out["rand_abscissa"] = abscissa
# GLV: 6 species, resident subset {0,1,3,4}
S = 6; A = -np.eye(S) + rng.normal(0, 0.08, (S, S)); r = rng.uniform(0.3, 1.0, S)
res = [0, 1, 3, 4]
Arr = A[np.ix_(res, res)]; nr = np.linalg.solve(Arr, -r[res]); n = np.zeros(S); n[res] = nr
out["glv_r"] = r; out["glv_A"] = A; out["glv_invasion"] = r + A @ n
# chemostat, three species on one resource: R* ordering and equilibrium of the lowest-R* species
D, S0 = 0.5, 10.0; mu = np.array([1.2, 1.0, 1.5]); Kh = np.array([2.0, 1.0, 4.0]); m = np.array([0.5, 0.5, 0.5]); q = np.array([1.0, 0.8, 1.2])
rs = m * Kh / (mu - m); w = np.argmin(rs)
Nstar = D * (S0 - rs[w]) * q[w] / m[w]
def f(y):
    R, N = y; g = mu[w] * R / (Kh[w] + R)
    return [D * (S0 - R) - g * N / q[w], (g - m[w]) * N]
sol = fsolve(f, [rs[w] * 1.1, Nstar * 0.9], xtol=1e-14)
out["chem"] = np.r_[D, S0, mu, Kh, m, q]; out["chem_rstar"] = rs; out["chem_eq"] = sol
# Gaussian logistic competition: sympy second derivatives at the singular point x* = 0
x, y, sa, sk = sp.symbols("x y sa sk", positive=True)
fexpr = 1 - sp.exp(-(y - x) ** 2 / (2 * sa ** 2)) * sp.exp(-x ** 2 / (2 * sk ** 2)) / sp.exp(-y ** 2 / (2 * sk ** 2))
fyy = sp.diff(fexpr, y, 2).subs({x: 0, y: 0}); fxy = sp.diff(fexpr, x, y).subs({x: 0, y: 0}); gx = sp.diff(fexpr, y)
cases = [(0.5, 1.0), (1.0, 0.5), (0.8, 0.8001), (2.0, 1.0)]
vals = []
for a, k in cases:
    vals += [a, k, float(fyy.subs({sa: a, sk: k})), float(fxy.subs({sa: a, sk: k})), float(gx.subs({sa: a, sk: k, x: 0.7, y: 0.7}))]
out["ad"] = vals
print(sp.simplify(fyy), sp.simplify(fxy))
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(t)) for t in np.asarray(a, float).ravel()))
with open("population/test/community_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_community_ref.py; do not edit.\n#pragma once\n#include <vector>\nnamespace community_reference {\n" + "\n".join(arr(k, v) for k, v in out.items()) + "\n}\n")
