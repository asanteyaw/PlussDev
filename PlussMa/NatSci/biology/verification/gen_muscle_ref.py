# Hill-type muscle oracle. Curve constants are PARSED from OpenSim's DeGrooteFregly2016Muscle.h (not retyped); the model is re-implemented in numpy and the
# dynamics are integrated with scipy DOP853 (independent of the Series RK4). Run from NatSci/biology:
#   python verification/gen_muscle_ref.py <path to DeGrooteFregly2016Muscle.h>
import re, sys, numpy as np
from scipy.integrate import solve_ivp
from scipy.optimize import brentq
src = open(sys.argv[1]).read()
def const(name): return float(re.search(r"constexpr static double %s\s*=\s*([-0-9.eE+]+)" % name, src).group(1))
b = {k: const(k) for k in ["b11", "b21", "b31", "b41", "b12", "b22", "b32", "b42", "b13", "b23", "b33", "b43"]}
d = {k: const(k) for k in ["d1", "d2", "d3", "d4"]}
c1, c2, c3, kPE = const("c1"), const("c2"), const("c3"), const("kPE")
LMIN = const("m_minNormFiberLength")
def gauss(x, b1, b2, b3, b4): return b1 * np.exp(-0.5 * (x - b2) ** 2 / (b3 + b4 * x) ** 2)
def fal(l, ws=1.0):
    x = (l - 1) / ws + 1
    return sum(gauss(x, b["b1%d" % k], b["b2%d" % k], b["b3%d" % k], b["b4%d" % k]) for k in (1, 2, 3))
def fpe(l, e0=0.6):
    off = np.exp(kPE * (LMIN - 1) / e0); return (np.exp(kPE * (l - 1) / e0) - off) / (np.exp(kPE) - off)
def fv(v): t = d["d2"] * v + d["d3"]; return d["d1"] * np.log(t + np.sqrt(t * t + 1)) + d["d4"]
def fvinv(f): return (np.sinh((f - d["d4"]) / d["d1"]) - d["d3"]) / d["d2"]
def kT(s1): return np.log((1 + c3) / c1) / (1 + s1 - c2)
def ft(lt, s1=0.049): return c1 * np.exp(kT(s1) * (lt - c2)) - c3
def ltinv(f, s1=0.049): return np.log((f + c3) / c1) / kT(s1) + c2
def dft(lt, s1=0.049): return c1 * kT(s1) * np.exp(kT(s1) * (lt - c2))
P = dict(F=800.0, lopt=0.09, lts=0.24, alpha=0.35, vmax=10.0, ta=0.015, td=0.060, s1=0.049, e0=0.6, damp=0.0, ws=1.0, smooth=0.1)
width = P["lopt"] * np.sin(P["alpha"])
def geom(L, f):
    lt = ltinv(f, P["s1"]) * P["lts"]; along = L - lt; lf = np.sqrt(along ** 2 + width ** 2); return lt, lf, lf / P["lopt"], along / lf
def arate(a, e):
    z = 0.5 + 1.5 * a; f = 0.5 * np.tanh(P["smooth"] * (e - a)); return ((f + 0.5) / (P["ta"] * z) + (-f + 0.5) * z / P["td"]) * (e - a)
def exc(t): return 0.05 + 0.375 * (1 + np.tanh((t - 0.15) / 0.02)) - 0.25 * (1 + np.tanh((t - 0.40) / 0.03))  # smooth pulse: a step would be integrated differently by adaptive and fixed-step schemes
def mtu(t): return 0.31 + 0.012 * np.sin(2 * np.pi * 2.0 * t)
def mtuv(t): return 0.012 * 2 * np.pi * 2.0 * np.cos(2 * np.pi * 2.0 * t)
def rhs(t, y):
    a, f = y; lt, lf, ln, cosa = geom(mtu(t), f)
    fvm = (f / cosa - fpe(ln, P["e0"])) / (a * fal(ln, P["ws"]))
    vn = fvinv(fvm); vf = vn * P["vmax"] * P["lopt"]
    vt = mtuv(t) - vf / cosa
    return [arate(a, exc(t)), vt / P["lts"] * dft(ltinv(f, P["s1"]), P["s1"])]
# isometric equilibrium for a grid of (activation, length)
acts = [0.1, 0.4, 0.8, 1.0]; lens = [0.29, 0.31, 0.33, 0.345]
eq = []
for a in acts:
    for L in lens:
        g = lambda f: f - geom(L, f)[3] * (a * fal(geom(L, f)[2], P["ws"]) * 1.0 + fpe(geom(L, f)[2], P["e0"]))
        f = brentq(g, 0.0, 5.0, xtol=1e-14, rtol=1e-14); lt, lf, ln, cosa = geom(L, f); eq += [a, L, f, ln, lt]
# dynamics
sol = solve_ivp(rhs, (0.0, 0.6), [0.05, 0.12], method="DOP853", rtol=1e-12, atol=1e-13, dense_output=True)
# initial tendon force: isometric equilibrium at t = 0 (a = 0.05, L = mtu(0)) keeps the start well-posed
a0 = 0.05; L0 = mtu(0.0)
g0 = lambda f: f - geom(L0, f)[3] * (a0 * fal(geom(L0, f)[2]) + fpe(geom(L0, f)[2], P["e0"]))
f0 = brentq(g0, 0.0, 5.0, xtol=1e-14)
sol = solve_ivp(rhs, (0.0, 0.6), [a0, f0], method="DOP853", rtol=1e-12, atol=1e-13, dense_output=True)
ts = np.linspace(0.05, 0.6, 12)
traj = [v for t in ts for v in (t, *sol.sol(t))]
# curves on grids
lgrid = np.linspace(0.3, 1.7, 15); vgrid = np.linspace(-1, 1, 11); tgrid = np.linspace(0.9, 1.06, 9)
out = dict(params=[P[k] for k in ["F", "lopt", "lts", "alpha", "vmax", "ta", "td", "s1", "e0", "damp", "ws", "smooth"]],
           lgrid=lgrid, fal=fal(lgrid), fpe=fpe(lgrid), vgrid=vgrid, fv=fv(vgrid), tgrid=tgrid, ft=ft(tgrid), dft=dft(tgrid), eq=eq, a0f0=[a0, f0], traj=traj)
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(t)) for t in np.asarray(a, float).ravel()))
with open("biomechanics/test/muscle_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_muscle_ref.py (curve constants parsed from OpenSim DeGrooteFregly2016Muscle.h); do not edit.\n#pragma once\n#include <vector>\nnamespace muscle_reference {\n" + "\n".join(arr(k, v) for k, v in out.items()) + "\n}\n")
print("fal(1)", fal(1.0), "fv(0)", fv(0.0), "fv(-1)", fv(-1.0), "ft(1.049)", ft(1.049), "fpe(1.6)", fpe(1.6), "f0", f0, "final", sol.y[:, -1])
