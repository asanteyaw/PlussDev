# Enzyme progress-curve fitting oracle: noisy synthetic curves from known parameters (lambertw closed form; ODE with product inhibition), fitted with scipy
# least_squares (MINPACK 'lm', analytic-quality finite differences) and nlparci-style intervals from the Jacobian. Run from NatSci/biology:
#   python verification/gen_enzyme_fit_ref.py
import numpy as np
from scipy.special import lambertw
from scipy.integrate import solve_ivp
from scipy.optimize import least_squares
from scipy import stats
rng = np.random.default_rng(17)
t = np.array([0.5, 1.0, 1.5, 2.0, 3.0, 4.0, 5.0, 6.5, 8.0, 10.0]); s0 = np.array([0.4, 1.0, 2.5, 6.0]); M, K = len(t), len(s0)
def integrated(beta, t=t, s0=s0):
    v, km = np.abs(beta)
    return np.array([km * lambertw((s / km) * np.exp((s - v * t) / km)).real for s in s0])
truth = np.array([0.9, 1.4]); y = integrated(truth) + 0.01 * rng.standard_normal((K, M))
fit = least_squares(lambda b: (integrated(b) - y).ravel(), [1.2, 2.0], method="lm", xtol=1e-14, ftol=1e-14, gtol=1e-14)
def ci(fit, n):
    J = fit.jac; p = len(fit.x); nu = n - p; sse = (fit.fun ** 2).sum(); se = np.sqrt(np.diag(np.linalg.inv(J.T @ J)) * sse / nu); tq = stats.t.ppf(0.975, nu); return fit.x - tq * se, fit.x + tq * se, se
lo, hi, se = ci(fit, y.size)
out = {"times": t, "s0": s0, "y1": y, "fit1": np.abs(fit.x), "sse1": [(fit.fun ** 2).sum()], "se1": se, "lo1": lo, "hi1": hi}
# competitive product inhibition by ODE
def ode(beta, t=t, s0=s0):
    v, km, kp = np.abs(beta); res = []
    for s in s0:
        sol = solve_ivp(lambda tt, S: [-v * S[0] / (km * (1 + (s - S[0]) / kp) + S[0])], (0, t[-1]), [s], t_eval=t, method="DOP853", rtol=1e-12, atol=1e-14); res.append(sol.y[0])
    return np.array(res)
truth2 = np.array([1.1, 1.8, 0.6]); y2 = ode(truth2) + 0.008 * rng.standard_normal((K, M))
fit2 = least_squares(lambda b: (ode(b) - y2).ravel(), [1.4, 2.5, 1.0], method="lm", xtol=1e-12, ftol=1e-12, gtol=1e-12)
lo2, hi2, se2 = ci(fit2, y2.size)
out.update({"y2": y2, "fit2": np.abs(fit2.x), "sse2": [(fit2.fun ** 2).sum()], "se2": se2})
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(x)) for x in np.asarray(a, float).ravel()))
with open("systems/test/enzyme_fit_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_enzyme_fit_ref.py (scipy least_squares); do not edit.\n#pragma once\n#include <vector>\nnamespace enzyme_fit_reference {\n" + "\n".join(arr(k, v) for k, v in out.items()) + "\n}\n")
print("fit1", fit.x, "se", se, "fit2", fit2.x, se2)
