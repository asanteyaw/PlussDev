# Birth-death / branching / diffusion-viability oracle with scipy and a Monte Carlo of Brownian first passage.
# Run from NatSci/biology:  python verification/gen_birth_death_ref.py
import numpy as np
from scipy.linalg import expm, solve, eig
from scipy.optimize import brentq
from scipy.stats import norm
rng = np.random.default_rng(5)
out = {}
def gen(b, d):
    m = len(b); Q = np.zeros((m, m))
    for n in range(m):
        if n + 1 < m: Q[n, n + 1] = b[n]
        if n > 0: Q[n, n - 1] = d[n]
        Q[n, n] = -(Q[n].sum())
    return Q
N = 40
n = np.arange(N + 1)
# stochastic logistic (SIS-type): b_n = r n (1 - n/K'), d_n = n   (K' chosen so b_N = 0)
b = 2.0 * n * (1 - n / N); d = 1.0 * n
Q = gen(b, d)
p0 = np.zeros(N + 1); p0[12] = 1
out["bd_birth"] = b; out["bd_death"] = d
out["bd_transient"] = p0 @ expm(Q * 1.7)
QT = Q[1:, 1:]
out["bd_mtte"] = solve(-QT, np.ones(N))
w, vl = eig(QT.T)
i = np.argmax(w.real); qsd = np.abs(vl[:, i].real); qsd /= qsd.sum()
out["bd_qsd"] = qsd; out["bd_decay"] = [-w[i].real]
# linear birth-death transient vs closed form is checked in C++; truncated chain here for extinction by t
bl = 1.1 * n; dl = 0.9 * n; bl = bl.copy(); bl[N] = 0.0
Ql = gen(bl, dl); pl = np.zeros(N + 1); pl[3] = 1
out["lin_p0_t"] = [(pl @ expm(Ql * t))[0] for t in (0.5, 1.5, 3.0)]
# Galton-Watson offspring distributions: ultimate extinction as the smallest root in [0, 1]
gw = [[0.2, 0.3, 0.5], [0.4, 0.1, 0.1, 0.4], [0.1, 0.2, 0.3, 0.2, 0.2], [0.5, 0.2, 0.3]]
out["gw_p"] = [x + [0.0] * (5 - len(x)) for x in gw]
ult = []
for p in gw:
    f = lambda s, p=p: sum(pk * s ** k for k, pk in enumerate(p)) - s
    m = sum(k * pk for k, pk in enumerate(p))
    ult.append(1.0 if m <= 1 else brentq(f, 0, 1 - 1e-9))
out["gw_ult"] = ult
byg = []
for p in gw:
    q = 0.0; row = [0.0]
    for _ in range(12):
        q = sum(pk * q ** k for k, pk in enumerate(p)); row.append(q)
    byg.append(row)
out["gw_by_gen"] = byg
# Brownian first passage: Monte Carlo with Brownian-bridge crossing correction between grid points
def mc(mu, s2, xd, ts, paths=400000, dt=2e-3):
    T = max(ts); steps = int(T / dt); x = np.zeros(paths); hit = np.full(paths, np.inf); sig = np.sqrt(s2)
    for k in range(steps):
        xn = x + mu * dt + sig * np.sqrt(dt) * rng.standard_normal(paths)
        a = x + xd; b2 = xn + xd  # distance above barrier (barrier at -xd)
        crossed = (b2 <= 0)
        pb = np.where((a > 0) & (b2 > 0), np.exp(-2 * a * b2 / (s2 * dt)), 0.0)
        bridge = rng.random(paths) < pb
        newly = (crossed | bridge) & np.isinf(hit)
        hit[newly] = (k + 1) * dt
        x = xn
    return [np.mean(hit <= t) for t in ts]
cases = [(0.05, 0.04, 1.2), (-0.02, 0.05, 1.0), (0.12, 0.09, 0.8)]
ts = [2.0, 5.0, 10.0]
out["pva_cases"] = [c for cs in cases for c in cs]
out["pva_ts"] = ts
out["pva_mc"] = [v for cs in cases for v in mc(*cs, ts)]
# Dennis estimator on a synthetic series with unequal intervals (numpy lstsq through the origin)
times = np.array([0, 1, 2, 4, 5, 8, 9, 12, 13, 15.0])
mu, s2 = 0.03, 0.02
lnN = np.log(500.0); ln = [lnN]
for i in range(1, len(times)):
    tau = times[i] - times[i - 1]; ln.append(ln[-1] + mu * tau + np.sqrt(s2 * tau) * rng.standard_normal())
counts = np.exp(ln); tau = np.diff(times); x = np.sqrt(tau); y = np.diff(np.log(counts)) / x
mh = (x @ y) / (x @ x); res = y - mh * x
out["den_counts"] = counts; out["den_times"] = times; out["den_est"] = [mh, (res @ res) / (len(y) - 1)]
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(t)) for t in np.asarray(a, float).ravel()))
