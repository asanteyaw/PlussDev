# Locomotion oracle: SLIP apex-to-apex map integrated with scipy DOP853 with event detection (touchdown, liftoff, apex), and the LIPM closed forms by
# numerical ODE integration. Run from NatSci/biology:  python verification/gen_locomotion_ref.py
import numpy as np
from scipy.integrate import solve_ivp
g = 9.80665
def slip(ya, vx, m, k, L0, alpha):
    # flight from apex (x = 0) to touchdown
    ytd = L0 * np.sin(alpha)
    if ya <= ytd: return [np.nan] * 4
    def flight(t, s): return [s[2], s[3], 0.0, -g]
    td = lambda t, s: s[1] - ytd; td.terminal = True; td.direction = -1
    f = solve_ivp(flight, (0, 5), [0.0, ya, vx, 0.0], events=td, rtol=1e-13, atol=1e-14, method="DOP853")
    s0 = f.y_events[0][0]; xf = s0[0] + L0 * np.cos(alpha)
    force = []
    def stance(t, s):
        dx = s[0] - xf; L = np.hypot(dx, s[1]); F = k * (L0 - L)
        return [s[2], s[3], F * dx / L / m, F * s[1] / L / m - g]
    lo = lambda t, s: np.hypot(s[0] - xf, s[1]) - L0; lo.terminal = True; lo.direction = 1
    st = solve_ivp(stance, (1e-9, 3), s0, events=lo, rtol=1e-13, atol=1e-14, method="DOP853", dense_output=True)
    if len(st.t_events[0]) == 0: return [np.nan] * 4
    tl = st.t_events[0][0]; sl = st.y_events[0][0]
    ts = np.linspace(1e-9, tl, 4001); ss = st.sol(ts)
    Fp = max(k * (L0 - np.hypot(ss[0] - xf, ss[1])))
    if sl[3] <= 0: return [np.nan] * 4
    return [sl[1] + sl[3] ** 2 / (2 * g), sl[2], tl, Fp]
cases = [(1.0, 5.0, 80.0, 20000.0, 1.0, 1.20), (1.02, 4.0, 80.0, 18000.0, 1.0, 1.15), (0.98, 6.5, 70.0, 25000.0, 0.95, 1.25), (1.05, 3.0, 60.0, 14000.0, 1.0, 1.1), (0.96, 5.5, 80.0, 16000.0, 1.0, 1.3)]
out = []
for c in cases:
    out += list(c) + slip(*c)
# LIPM: ODE integration of x'' = (g/z0) x
z0 = 0.95; Tc = np.sqrt(z0 / g)
lip = []
for x0, v0, t in [(-0.2, 1.1, 0.3), (0.05, 0.9, 0.4), (-0.35, 1.4, 0.25), (0.1, -0.2, 0.2)]:
    s = solve_ivp(lambda tt, y: [y[1], g / z0 * y[0]], (0, t), [x0, v0], rtol=1e-13, atol=1e-14, method="DOP853")
    lip += [x0, v0, t, s.y[0, -1], s.y[1, -1]]
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join("NAN" if np.isnan(t) else repr(float(t)) for t in np.asarray(a, float).ravel()))
with open("biomechanics/test/locomotion_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_locomotion_ref.py (scipy DOP853 with events); do not edit.\n#pragma once\n#include <cmath>\n#include <vector>\nnamespace locomotion_reference {\n" + "\n".join([arr("slip", out), "inline const double lipm_height = %r;" % z0, arr("lipm", lip)]) + "\n}\n")
print([round(v, 5) for v in out[:10]])
