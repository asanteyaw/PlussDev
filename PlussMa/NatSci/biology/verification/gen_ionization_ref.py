# Charge and isoelectric point oracle: Biopython's Bio/SeqUtils/IsoelectricPoint.py loaded from a local GitHub checkout (no Bio package needed,
# the aa_content dict is passed in). Run from NatSci/biology:  python verification/gen_ionization_ref.py <path to IsoelectricPoint.py>
import importlib.util, random, sys
spec = importlib.util.spec_from_file_location("iep", sys.argv[1]); iep = importlib.util.module_from_spec(spec); spec.loader.exec_module(iep)
random.seed(7)
aas = "ACDEFGHIKLMNPQRSTVWY"
seqs = ["INGAR", "PETER", "DDDDD", "KKKKK", "MA", "SEEEK", "PRRRH"]
for _ in range(193):
    n = random.choice([3, 5, 12, 40, 150, 400])
    w = [random.random() ** 2 + 0.05 for _ in aas]
    seqs.append("".join(random.choices(aas, weights=w, k=n)))
phs = [2.0, 4.0, 6.5, 7.4, 9.0, 11.5]
charge, pis = [], []
for s in seqs:
    ip = iep.IsoelectricPoint(s, {a: s.count(a) for a in aas})
    charge += [ip.charge_at_pH(p) for p in phs]
    pis.append(ip.pi())
with open("biophysics/test/ionization_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/verification/gen_ionization_ref.py; do not edit.\n#pragma once\n#include <string>\n#include <vector>\nnamespace ionization_reference {\n")
    fh.write("inline const std::vector<std::string> sequences = {%s};\n" % ",".join('"%s"' % s for s in seqs))
    fh.write("inline const std::vector<double> ph = {%s};\n" % ",".join(repr(p) for p in phs))
    fh.write("inline const std::vector<double> charge = {%s};\n" % ",".join(repr(c) for c in charge))
    fh.write("inline const std::vector<double> pi = {%s};\n}\n" % ",".join(repr(c) for c in pis))
print("ok", len(seqs), "sequences; pI range", min(pis), max(pis))
