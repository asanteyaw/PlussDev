# Independent Hodgkin-Huxley reference written directly in the ORIGINAL PAPER's sign convention
# (J. Physiol. 117:500, eqs. 26, 7, 15, 16, 12, 13, 20, 21, 23, 24; Table 3): depolarisation negative.
import numpy as np
from scipy.integrate import solve_ivp
def vtrap(x,y): return y if abs(x)<1e-9 else x/np.expm1(x/y)
gNa,gK,gl=120.0,36.0,0.3
VNa,VK,Vl=-115.0,12.0,-10.613
C=1.0
def rates(V):
    an=0.01*(V+10)/np.expm1((V+10)/10) if abs(V+10)>1e-9 else 0.1
    bn=0.125*np.exp(V/80)
    am=0.1*(V+25)/np.expm1((V+25)/10) if abs(V+25)>1e-9 else 1.0
    bm=4*np.exp(V/18)
    ah=0.07*np.exp(V/20)
    bh=1/(np.exp((V+30)/10)+1)
    return an,bn,am,bm,ah,bh
def rhs(t,y,Ip):
    V,n,m,h=y
    an,bn,am,bm,ah,bh=rates(V)
    I_ion=gK*n**4*(V-VK)+gNa*m**3*h*(V-VNa)+gl*(V-Vl)
    return [(Ip-I_ion)/C, an*(1-n)-bn*n, am*(1-m)-bm*m, ah*(1-h)-bh*h]
an,bn,am,bm,ah,bh=rates(0.0)
rest=[0.0,an/(an+bn),am/(am+bm),ah/(ah+bh)]
print("rest gates n,m,h",rest[1:])
def run(V0p,Ip,times):
    y0=[V0p]+rest[1:]
    sol=solve_ivp(rhs,[0,max(times)],y0,args=(Ip,),method='DOP853',rtol=1e-12,atol=1e-12,dense_output=True)
    Y=sol.sol(np.array(times)); return Y
times=[0.5,1.0,2.0,3.0,5.0,8.0]
out={}
for name,V0,Ip in (("v0_15",-15.0,0.0),("v0_6",-6.0,0.0),("i10",0.0,-10.0)):
    Y=run(V0,Ip,times)
    out[name]=Y
    print(name,"V_dep(t)=",["%.10f"%(-v) for v in Y[0]])
# threshold search on the initial depolarisation (paper Fig. 12: 7 mV subthreshold, 15 mV fires)
from scipy.optimize import brentq
def peak(V0d):
    y0=[-V0d]+rest[1:]
    sol=solve_ivp(rhs,[0,12],y0,args=(0.0,),method='DOP853',rtol=1e-11,atol=1e-11,dense_output=True)
    t=np.linspace(0,12,2401); return (-sol.sol(t)[0]).max()
for v0 in (5,6,7,8,9,10,12,15,20): print("V0",v0,"peak %.3f"%peak(v0))
f=lambda v:peak(v)-40.0
th=brentq(f,6.0,7.0,xtol=1e-9)
print("threshold (peak crosses 40 mV) V0 = %.6f"%th)
def arr(name,a):
    a=np.ravel(a); return "inline const double %s[%d] = {%s};\n"%(name,a.size,",".join("%.17e"%v for v in a))
txt="// Generated by scratchpad hh_paper_ref.py (independent implementation in the paper's own sign\n// convention); V values are depolarisation-positive. Do not edit.\n#pragma once\nnamespace hh_reference {\n"
txt+=arr("times",times)
for name,Y in out.items(): txt+=arr(name,np.vstack([-Y[0],Y[1],Y[2],Y[3]]).T)   # [time][V_dep,n,m,h]
txt+=arr("threshold_v0",[th])+arr("rest_gates",rest[1:])
txt+="}\n"
open("hh_reference.h","w").write(txt)
