% MATLAB pdepe reference (R2025b PDE solver) for the 1-D Gray-Scott system with no-flux boundaries; writes ../test/spatial_pdepe_reference.h
% run: matlab -batch "run('gen_spatial_ref.m')"
function main()
  Du = 0.16; Dv = 0.08; F = 0.035; k = 0.065; L = 2.5;
  x = linspace(0, L, 801); t = [0 10 30 60];
  sol = pdepe(0, @pdefun, @icfun, @bcfun, x, t, odeset('RelTol',1e-9,'AbsTol',1e-11));
  probes = [0.0 0.3 0.8 1.1 1.25 1.6 2.2 2.5];
  fid = fopen('../test/spatial_pdepe_reference.h','w');
  fprintf(fid,'// Generated by gen_spatial_ref.m (MATLAB pdepe); do not edit.\n#pragma once\n#include <vector>\nnamespace spatial_pdepe_reference {\n');
  wr(fid,'times',t); wr(fid,'probes',probes);
  for q = 1:numel(t)
    u = interp1(x, squeeze(sol(q,:,1)), probes, 'spline'); v = interp1(x, squeeze(sol(q,:,2)), probes, 'spline');
    wr(fid,sprintf('u_t%d',q),u); wr(fid,sprintf('v_t%d',q),v);
  end
  fprintf(fid,'}\n'); fclose(fid); disp('done');
  function [c,f,s] = pdefun(x,t,u,dudx)
    c = [1;1]; f = [Du;Dv].*dudx; s = [-u(1)*u(2)^2 + F*(1-u(1)); u(1)*u(2)^2 - (F+k)*u(2)];
  end
  function u0 = icfun(x)
    bump = exp(-((x-1.25)/0.1)^2);
    u0 = [1 - 0.5*bump; 0.25*bump];
  end
  function [pl,ql,pr,qr] = bcfun(xl,ul,xr,ur,t)
    pl = [0;0]; ql = [1;1]; pr = [0;0]; qr = [1;1];
  end
end
function wr(fid,name,v)
  fprintf(fid,'inline const std::vector<double> %s = {',name); fprintf(fid,'%.17g,',v(:)); fprintf(fid,'};\n');
end
