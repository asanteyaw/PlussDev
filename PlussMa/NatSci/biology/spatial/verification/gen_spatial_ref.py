"""Spatial references: random Turing cases against numpy eigenvalues (brute-force scan of max Re lambda over k^2), steady states of the
standard kinetics against scipy fsolve. MATLAB pdepe references are produced by gen_spatial_ref.m."""
import numpy as np
from scipy import optimize
rng = np.random.default_rng(11)
out = []
def arr(name, v): out.append("inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(x)) for x in np.ravel(v))))
cases = []
for t in range(600):
    if t % 3 == 0:  # unconstrained
        J = rng.normal(size=(2, 2)) * 2.0
    else:           # activator-inhibitor structure: fu > 0, gv < 0, fv gu < 0 (the classical Turing class)
        J = np.array([[rng.uniform(0.1, 3), rng.uniform(0.1, 3)], [-rng.uniform(0.1, 3), -rng.uniform(0.1, 3)]])
    da = 10 ** rng.uniform(-2, 0); db = da * 10 ** rng.uniform(0, 2.2)
    cases.append((J, da, db))
rows = []
k2grid = np.concatenate([[0.0], np.logspace(-6, 4, 20001)])
for J, da, db in cases:
    D = np.diag([da, db])
    ev = np.array([np.linalg.eigvals(J - k2 * D) for k2 in k2grid])
    growth = ev.real.max(axis=1)
    stable0 = growth[0] < 0
    max_growth = growth[1:].max()
    turing = stable0 and max_growth > 0
    # band edges: sign changes of growth on the grid
    sgn = growth > 0
    edges = [k2grid[i] for i in range(1, len(k2grid)) if sgn[i] != sgn[i - 1]]
    rows.append((J.ravel(), da, db, growth[[0, 100, 5000, 12000]], stable0, turing, max_growth, edges[:2] if len(edges) >= 2 else [np.nan, np.nan]))
arr("tu_J", [r[0] for r in rows]); arr("tu_da", [r[1] for r in rows]); arr("tu_db", [r[2] for r in rows])
arr("tu_growth_samples", [r[3] for r in rows]); arr("tu_k2_samples", k2grid[[0, 100, 5000, 12000]])
arr("tu_stable0", [float(r[4]) for r in rows]); arr("tu_turing", [float(r[5]) for r in rows]); arr("tu_maxgrowth", [r[6] for r in rows]); arr("tu_edges", [r[7] for r in rows])
# steady states
def gs_nontrivial(F, k):
    f = lambda v: [v[0] * v[1] ** 2 - F * (1 - v[0]) * -1 * -1 - 0 * v[1]]  # placeholder not used
    return None
gs_cases = [(0.09, 0.04), (0.1, 0.05), (0.08, 0.03), (0.12, 0.04)]
vals = []
for F, k in gs_cases:
    disc = 1 - 4 * (F + k) ** 2 / F
    if disc < 0: vals.append([np.nan] * 4); continue
    res = []
    for sign in (+1, -1):
        u0 = 0.5 * (1 + sign * np.sqrt(disc)); v0 = F * (1 - u0) / (F + k)
        # polish with fsolve of the full steady-state equations
        sol = optimize.fsolve(lambda w: [-w[0] * w[1] ** 2 + F * (1 - w[0]), w[0] * w[1] ** 2 - (F + k) * w[1]], [u0, v0], xtol=1e-14)
        res += list(sol)
    vals.append(res)
arr("gs_cases", gs_cases); arr("gs_states", vals)
with open("spatial/test/spatial_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/biology/spatial/verification/gen_spatial_ref.py; do not edit.\n#pragma once\n#include <cmath>\n#include <vector>\nnamespace spatial_reference {\n" + "\n".join(out).replace("nan", "NAN") + "\n}\n")
print("ok", len(out), "arrays; Turing cases:", sum(1 for r in rows if r[5]), "of", len(rows))
