# Surface-chemistry oracle: direct summation of the BET multilayer model, numpy regression for the BET plot, grid search of the Langmuir-Hinshelwood
# optimum, and a CO-oxidation microkinetic ODE integrated to steady state (scipy DOP853) plus an fsolve steady state.
# Run from NatSci/chemistry:  python verification/gen_surface_ref.py
import numpy as np
from scipy.integrate import solve_ivp
from scipy.optimize import fsolve
out = {}
# BET: q/qm = sum_{i<=n} i c x^i / (1 + sum_{i<=n} c x^i)
xs = np.array([0.02, 0.1, 0.25, 0.5, 0.8, 0.95])
rows = []
for c, n in [(20.0, 3), (100.0, 6), (5.0, 12), (60.0, 40)]:
    for x in xs:
        i = np.arange(1, n + 1); num = np.sum(i * c * x ** i); den = 1 + np.sum(c * x ** i); rows += [c, n, x, num / den]
out["bet_direct"] = rows
# BET plot regression on synthetic noisy data from the infinite-layer model
rng = np.random.default_rng(8)
x = np.linspace(0.06, 0.32, 9); c_true, qm_true = 55.0, 2.4
q = qm_true * c_true * x / ((1 - x) * (1 - x + c_true * x)) * (1 + 0.01 * rng.standard_normal(len(x)))
y = x / (q * (1 - x)); sl, ic = np.polyfit(x, y, 1)
r2 = 1 - np.sum((y - (sl * x + ic)) ** 2) / np.sum((y - y.mean()) ** 2)
out["bet_data_x"] = x; out["bet_data_q"] = q; out["bet_fit"] = [1 / (sl + ic), sl / ic + 1, r2]
# Langmuir-Hinshelwood optimum over P_A at fixed P_B
KA, KB, PB = 0.8, 0.3, 2.5
pa = np.linspace(0.01, 30, 300001); r = (KA * pa) * (KB * PB) / (1 + KA * pa + KB * PB) ** 2
out["lh"] = [KA, KB, PB, pa[np.argmax(r)], r.max()]
# CO oxidation microkinetics on sites: species CO*, O*, free *; constant pressures folded into rate constants
kaC, kdC, kaO, kdO, kr = 2.0, 0.5, 1.2, 0.05, 3.0
def rhs(t, y):
    co, o = y; s = 1 - co - o
    r1 = kaC * s - kdC * co; r3 = kaO * s * s - kdO * o * o; r5 = kr * co * o
    return [r1 - r5, 2 * r3 - r5]
sol = solve_ivp(rhs, (0, 400), [0.0, 0.0], method="DOP853", rtol=1e-12, atol=1e-14)
co_ss, o_ss = sol.y[:, -1]
fs = fsolve(lambda y: rhs(0, y), [co_ss, o_ss], xtol=1e-14)
out["mk_params"] = [kaC, kdC, kaO, kdO, kr]; out["mk_ss"] = [fs[0], fs[1], 1 - fs[0] - fs[1], kr * fs[0] * fs[1]]
traj_t = [0.5, 1.0, 2.0, 5.0]
s2 = solve_ivp(rhs, (0, 5), [0.0, 0.0], method="DOP853", rtol=1e-12, atol=1e-14, dense_output=True)
out["mk_traj"] = [v for t in traj_t for v in (t, *s2.sol(t))]
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(t)) for t in np.asarray(a, float).ravel()))
with open("surface/test/surface_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/chemistry/verification/gen_surface_ref.py; do not edit.\n#pragma once\n#include <vector>\nnamespace surface_reference {\n" + "\n".join(arr(k, v) for k, v in out.items()) + "\n}\n")
print("fit", out["bet_fit"], "lh", out["lh"], "ss", out["mk_ss"])
