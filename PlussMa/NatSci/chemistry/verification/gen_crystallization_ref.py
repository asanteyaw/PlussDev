# Crystallization oracle: MSMPR moment ODEs (scipy DOP853) to steady state and fsolve, CNT closed forms by direct arithmetic, and a Monte Carlo of homogeneous
# nucleation and interface-controlled growth in a periodic box (JMAK/Avrami check). Run from NatSci/chemistry:  python verification/gen_crystallization_ref.py
import numpy as np
from scipy.integrate import solve_ivp
from scipy.optimize import fsolve
out = {}
# MSMPR (units: L in micrometres, time in minutes)
tau, cin, csat, kg, g, kb, b, rho, kv = 6.0, 40.0, 10.0, 0.05, 1.3, 2.0e-3, 1.7, 2.0, 0.5
def rhs(t, y):
    c, m0, m1, m2, m3 = y; d = max(c - csat, 0.0); G = kg * d ** g; B = kb * d ** b * max(m3, 0.0)
    return [(cin - c) / tau - 3 * rho * kv * G * m2, B - m0 / tau, G * m0 - m1 / tau, 2 * G * m1 - m2 / tau, 3 * G * m2 - m3 / tau]
sol = solve_ivp(rhs, (0, 400 * tau), [cin - 1.0, 1.0, 5.0, 100.0, 4000.0], method="DOP853", rtol=1e-12, atol=1e-14)
yss = fsolve(lambda y: rhs(0, y), sol.y[:, -1], xtol=1e-14)
Gss = kg * (yss[0] - csat) ** g; Bss = kb * (yss[0] - csat) ** b * yss[4]
out["msmpr"] = [tau, cin, csat, kg, g, kb, b, rho, kv] + list(yss) + [Gss, Bss]
traj_t = [3.0, 12.0, 30.0, 60.0]
s2 = solve_ivp(rhs, (0, 60), [cin - 1.0, 1.0, 5.0, 100.0, 4000.0], method="DOP853", rtol=1e-12, atol=1e-14, dense_output=True)
out["msmpr_traj"] = [v for t in traj_t for v in (t, *s2.sol(t))]
# CNT: gamma = 0.03 J/m^2, v_m = 3.0e-29 m^3, T = 300 K, S in {1.5, 2, 3, 5}
kB = 1.380649e-23; gam, vm, T = 0.03, 3.0e-29, 300.0
Ss = np.array([1.5, 2.0, 3.0, 5.0]); kT = kB * T
out["cnt"] = [gam, vm, T] + list(Ss) + list(2 * gam * vm / (kT * np.log(Ss))) + list(16 * np.pi * gam ** 3 * vm ** 2 / (3 * (kT * np.log(Ss)) ** 2))
# JMAK Monte Carlo: periodic unit cube, nucleation rate I per unit volume and time during [0, T], growth speed G, X(t) = fraction covered by union of spheres
rng = np.random.default_rng(3)
I, G, Tend = 600.0, 0.18, 1.2
N = rng.poisson(I * Tend); tn = rng.uniform(0, Tend, N); cen = rng.random((N, 3))
pts = rng.random((60000, 3))
ts = np.array([0.3, 0.5, 0.7, 0.9, 1.1])
frac = []
for t in ts:
    covered = np.zeros(len(pts), bool)
    for i in range(N):
        if tn[i] >= t: continue
        r = G * (t - tn[i]); d = np.abs(pts - cen[i]); d = np.minimum(d, 1 - d); covered |= (d ** 2).sum(1) <= r * r
    frac.append(covered.mean())
out["jmak_mc"] = [I, G] + list(ts) + frac
def arr(name, a): return "inline const std::vector<double> %s = {%s};" % (name, ",".join(repr(float(t)) for t in np.asarray(a, float).ravel()))
with open("crystallization/test/crystallization_reference.h", "w") as fh:
    fh.write("// Generated by NatSci/chemistry/verification/gen_crystallization_ref.py; do not edit.\n#pragma once\n#include <vector>\nnamespace crystallization_reference {\n" + "\n".join(arr(k, v) for k, v in out.items()) + "\n}\n")
print("ss", yss, "G", Gss, "B", Bss, "jmak", frac, "kappa*t^4 pred", 1 - np.exp(-np.pi * I * G ** 3 * ts ** 4 / 3))
