# ---- Eckart tunnelling: exact transmission through V(x) = A y/(1+y) + B y/(1+y)^2, y = exp(2 pi x / L), by direct integration of the 1-D Schroedinger equation
# (independent of the closed-form cosh expression); L is fixed numerically from the barrier-top curvature |V''| = m (2 pi c nu*)^2, mass 1 amu (T(E) must not depend on it).
from scipy.integrate import solve_ivp, quad
from scipy.optimize import minimize_scalar
hbar = h / (2 * np.pi); amu = 1.66053906660e-27
def eckart_oracle(V1, V2, nu, mass=amu):          # V1, V2 in kJ/mol, nu in cm^-1
    A = V1 - V2; B = (np.sqrt(V1) + np.sqrt(V2)) ** 2
    Vf = lambda x, L: A * (y := np.exp(2 * np.pi * x / L)) / (1 + y) + B * y / (1 + y) ** 2
    xm = minimize_scalar(lambda x: -Vf(x, 1.0), bounds=(-3, 3), method="bounded", options={"xatol": 1e-13}).x
    d = 1e-3; d2 = lambda s: (-Vf(xm + 2 * s, 1.0) + 16 * Vf(xm + s, 1.0) - 30 * Vf(xm, 1.0) + 16 * Vf(xm - s, 1.0) - Vf(xm - 2 * s, 1.0)) / (12 * s * s)
    vpp = -d2(d)                                                  # kJ/mol per (L=1)^2, positive
    assert abs(Vf(xm, 1.0) - V1) < 1e-9 * V1, (Vf(xm, 1.0), V1)
    curv = mass * (2 * np.pi * c_cm * nu) ** 2 * NA / 1e3 * 1e-20  # kJ/mol per Angstrom^2
    L = np.sqrt(vpp / curv)                                       # Angstrom
    eps = hbar ** 2 / (2 * mass) * NA * 1e20 / 1e3                # kJ/mol Angstrom^2
    def T(E):
        if E <= max(A, 0.0): return 0.0
        k1 = np.sqrt(E / eps); k2 = np.sqrt((E - A) / eps); xR, xL = 14 * L, -14 * L
        sol = solve_ivp(lambda x, s: [s[1], (Vf(x, L) - E) / eps * s[0]], (xR, xL), np.array([np.exp(1j * k2 * xR), 1j * k2 * np.exp(1j * k2 * xR)]), method="DOP853", rtol=1e-12, atol=1e-14)
        psi, dpsi = sol.y[0, -1], sol.y[1, -1]
        a = 0.5 * (psi + dpsi / (1j * k1)) * np.exp(-1j * k1 * xL)  # incident amplitude
        return float((k2 / k1) / abs(a) ** 2)
    return T, A, L
