def enumerate_counts(freqs, bins):
    rho = np.zeros(bins)
    def rec(i, e):
        if i == len(freqs): rho[e] += 1; return
        n = 0
        while e + n * freqs[i] < bins:
            rec(i + 1, e + n * freqs[i]); n += 1
    rec(0, 0); return rho
