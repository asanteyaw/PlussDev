def collocation_levels(I, V0, N, M=96):
    n = 2 * M + 1; phi = 2 * np.pi * np.arange(n) / n
    # spectral second-derivative matrix on the periodic grid via the DFT
    k = np.fft.fftfreq(n, 1.0 / n); D2 = np.real(np.fft.ifft(-(k ** 2)[:, None] * np.fft.fft(np.eye(n), axis=0), axis=0))
    H = -(hbar ** 2 / (2 * I)) * D2 + np.diag(0.5 * V0 * (1 - np.cos(N * phi)))
    return np.linalg.eigvalsh(0.5 * (H + H.T))
