import numpy as np
from h2o2_ref import *
temps=[1000.0,1500.0,2500.0]
base=dict(H2=2.0,H=1e-3,O=1e-3,O2=1.0,OH=5e-3,H2O=3.0,HO2=1e-3,H2O2=2e-4,AR=5.0,N2=1.0)
out=[]
def arr(name,a,shape):
    flat=",".join("%.17e"%v for v in np.ravel(a))
    return "inline const double %s[%s] = {%s};\n"%(name,shape,flat)
txt="// Generated by scratchpad gen_ref.py from an independent NumPy implementation (CGS/cal units)\n// of the same equations; do not edit.\n#pragma once\nnamespace kinetics_reference {\n"
txt+=arr("temps",temps,"3")
C_si=np.array([base[n] for n in names])
txt+=arr("conc_si",C_si,"10")
wd=[];kc=[];kf=[]
for T in temps:
    C_cgs=C_si*1e-6
    w,_,_=wdot(T,C_cgs); wd.append(w*1e6)
    nuS=nu.sum(1)
    kc.append(Kc(T)*(1e6)**nuS)        # concentration-units conversion mol/cm3 -> mol/m3
    # forward rate constants in SI: order from forward stoich (+1 for third-body M)
    k=kfs(T,C_cgs); 
    order=nu_r.sum(1)   # effective k (incl. [M] for three-body, falloff) has the reactant order
    kf.append(k*(1e-6)**(order-1))
txt+=arr("wdot_si",wd,"3*10")+arr("kc_si",kc,"3*%d"%NR)+arr("kf_si",kf,"3*%d"%NR)
# reactor references
refs={}
for T0 in (1000.0,1100.0,1200.0):
    y0=initial(T0)
    sol=solve_ivp(rhs,[0,5e-3],y0,method='Radau',rtol=1e-10,atol=1e-22,dense_output=True)
    t=np.linspace(0,5e-3,200001); Tt=sol.sol(t)[0]; ig=t[np.argmax(np.gradient(Tt,t))]
    st=sol.sol(5e-3)
    refs[T0]=(ig,st)
txt+=arr("ignition_s",[refs[T][0] for T in (1000.0,1100.0,1200.0)],"3")
txt+=arr("final_T",[refs[T][1][0] for T in (1000.0,1100.0,1200.0)],"3")
txt+=arr("final_conc_1100_si",refs[1100.0][1][1:]*1e6,"10")
txt+="}\n"
open("kinetics_reference.h","w").write(txt)
print("written",len(txt))
print("kf SI sample reaction 11 (H+O2<=>O+OH) T=1500:",kf[1][10])
