fid = fopen('../test/estimation_reference.h','w');
fprintf(fid,'// Generated by NatSci/common/verification/gen_estimation_ref.m (MATLAB nlinfit / nlparci); do not edit.\n#pragma once\n#include <vector>\nnamespace estimation_reference {\n');
function wr(fid,name,v)
    fprintf(fid,'inline const std::vector<double> %s = {',name); fprintf(fid,'%.17g,',v(:)); fprintf(fid,'};\n');
end
opts = statset('nlinfit');
wr(fid,'matlab_tolx',opts.TolX); wr(fid,'matlab_tolfun',opts.TolFun);
dstep = opts.DerivStep; if isempty(dstep), dstep = eps^(1/3); end
wr(fid,'matlab_derivstep',dstep);
% P1 Michaelis-Menten
x = linspace(0.1,10,25)'; y = 2.5*x./(0.8+x) + 0.05*sin(7*x);
m1 = @(b,x) b(1)*x./(b(2)+x);
[b,r,J] = nlinfit(x,y,m1,[1 1]); ci = nlparci(b,r,'jacobian',J);
wr(fid,'p1_x',x); wr(fid,'p1_y',y); wr(fid,'p1_b0',[1 1]); wr(fid,'p1_beta',b); wr(fid,'p1_sse',sum(r.^2)); wr(fid,'p1_ci',ci'); wr(fid,'p1_J',J');
% P2 offset exponential decay
t = (0:0.5:9)'; yd = 3*exp(-0.4*t) + 0.5 + 0.03*cos(5*t);
m2 = @(b,t) b(1)*exp(-b(2)*t)+b(3);
[b,r,J] = nlinfit(t,yd,m2,[1 1 0]); ci = nlparci(b,r,'jacobian',J);
wr(fid,'p2_x',t); wr(fid,'p2_y',yd); wr(fid,'p2_b0',[1 1 0]); wr(fid,'p2_beta',b); wr(fid,'p2_sse',sum(r.^2)); wr(fid,'p2_ci',ci');
% P3 Hill
xh = logspace(-1,1.2,22)'; yh = 2*xh.^2.2./(1.5^2.2+xh.^2.2) + 0.04*sin(11*xh);
m3 = @(b,x) b(1)*x.^b(3)./(b(2).^b(3)+x.^b(3));
[b,r,J] = nlinfit(xh,yh,m3,[1.5 1 1.5]); ci = nlparci(b,r,'jacobian',J,'alpha',0.1);
wr(fid,'p3_x',xh); wr(fid,'p3_y',yh); wr(fid,'p3_b0',[1.5 1 1.5]); wr(fid,'p3_beta',b); wr(fid,'p3_sse',sum(r.^2)); wr(fid,'p3_ci90',ci');
% critical values used by nlparci
wr(fid,'tinv_975_10',tinv(0.975,10)); wr(fid,'tinv_95_19',tinv(0.95,19)); wr(fid,'chi2inv_95_1',chi2inv(0.95,1)); wr(fid,'chi2inv_95_3',chi2inv(0.95,3));
