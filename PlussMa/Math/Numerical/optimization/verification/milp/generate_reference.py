#!/usr/bin/env python3
"""Generate test/milp_reference.h for milp_test.cpp.
Oracles: scipy.optimize.milp (HiGHS, presolve off, mip_rel_gap = 0) and, for tiny binary problems, exhaustive enumeration.
usage: generate_reference.py <out.h>
"""
import sys, itertools, numpy as np
from scipy.optimize import milp, LinearConstraint, Bounds
INF = np.inf
rng = np.random.default_rng(20261015)
probs = []
def add(kind, c, Ai, bi, Ae, be, lb, ub, im): probs.append((kind, c, Ai, bi, Ae, be, lb, ub, im))
for t in range(10):
    n = int(rng.integers(6, 20)); k = int(rng.integers(1, 4)); w = rng.integers(1, 30, (k, n)).astype(float); v = rng.integers(1, 40, n).astype(float)
    add('knapsack', -v, w, np.floor(w.sum(1) * rng.uniform(.3, .6)), np.zeros((0, n)), np.zeros(0), np.zeros(n), np.ones(n), np.ones(n))
for t in range(8):
    n = int(rng.integers(4, 11)); x0 = rng.integers(0, 6, n).astype(float); Ai = rng.integers(-3, 6, (3, n)).astype(float); Ae = rng.integers(-3, 6, (1, n)).astype(float)
    add('integer', rng.integers(-5, 6, n).astype(float), Ai, Ai @ x0 + rng.integers(0, 4, 3), Ae, Ae @ x0, np.zeros(n), np.full(n, 8.0), np.ones(n))
for t in range(8):
    n = int(rng.integers(6, 14)); x0 = rng.uniform(0, 4, n); x0[:n // 2] = np.round(x0[:n // 2]); Ai = rng.normal(size=(4, n)); im = np.zeros(n); im[:n // 2] = 1
    add('mixed', rng.normal(size=n), Ai, Ai @ x0 + rng.uniform(0, 1, 4), np.zeros((0, n)), np.zeros(0), np.zeros(n), np.full(n, 6.0), im)
for t in range(6):
    n = int(rng.integers(8, 18)); m = int(rng.integers(6, 12)); A = (rng.random((m, n)) < .3).astype(float)
    for i in range(m):
        if A[i].sum() == 0: A[i, rng.integers(0, n)] = 1
    add('setcover', rng.integers(1, 10, n).astype(float), -A, -np.ones(m), np.zeros((0, n)), np.zeros(0), np.zeros(n), np.ones(n), np.ones(n))
for t in range(4):
    k = int(rng.integers(3, 6)); cost = rng.integers(1, 20, (k, k)).astype(float); n = k * k; Ae = np.zeros((2 * k, n))
    for i in range(k): Ae[i, i * k:(i + 1) * k] = 1; Ae[k + i, i::k] = 1
    add('assignment', cost.ravel(), np.zeros((0, n)), np.zeros(0), Ae, np.ones(2 * k), np.zeros(n), np.ones(n), np.ones(n))
for t in range(4):   # parity: LP relaxation feasible, integer problem infeasible
    n = int(rng.integers(3, 7)); a = 2 * rng.integers(1, 4, n).astype(float)
    add('parity', rng.normal(size=n), np.zeros((0, n)), np.zeros(0), a[None, :], np.array([a.sum() / 2 + 1.0]), np.zeros(n), np.full(n, 5.0), np.ones(n))
for t in range(3):   # LP-relaxation infeasible
    n = int(rng.integers(3, 7)); a = rng.normal(size=n)
    add('lp_infeasible', rng.normal(size=n), np.vstack([a, -a]), np.array([1.0, -3.0]), np.zeros((0, n)), np.zeros(0), np.zeros(n), np.full(n, 3.0), np.ones(n))
for t in range(3):   # unbounded continuous direction, no constraint rows (bound-only LP relaxation)
    n = int(rng.integers(3, 7)); im = np.zeros(n); im[0] = 1; c = np.zeros(n); c[-1] = -1; ub = np.full(n, INF); ub[0] = 4
    add('unbounded', c, np.zeros((0, n)), np.zeros(0), np.zeros((0, n)), np.zeros(0), np.zeros(n), ub, im)
for t in range(6):   # tiny binary (also brute-forced)
    n = int(rng.integers(5, 12)); Ai = rng.integers(-5, 8, (3, n)).astype(float); x0 = rng.integers(0, 2, n).astype(float)
    add('tiny_binary', rng.integers(-9, 10, n).astype(float), Ai, Ai @ x0 + rng.integers(0, 3, 3), np.zeros((0, n)), np.zeros(0), np.zeros(n), np.ones(n), np.ones(n))
def fmt(a): return ",".join("INF" if v == INF else "-INF" if v == -INF else repr(float(v)) for v in np.ravel(a))
def reference(c, Ai, bi, Ae, be, lb, ub, im, kind):
    cons = []
    if Ai.shape[0]: cons.append(LinearConstraint(Ai, -INF, bi))
    if Ae.shape[0]: cons.append(LinearConstraint(Ae, be, be))
    r = milp(c, constraints=cons, integrality=im, bounds=Bounds(lb, ub), options={'presolve': False, 'mip_rel_gap': 0.0, 'time_limit': 60})
    st = {0: 0, 2: 1, 3: 2}.get(r.status, 9)
    if kind == 'unbounded': st = 2   # HiGHS may label a bound-only unbounded relaxation infeasible
    obj = r.fun if st == 0 else float('nan')
    if kind == 'tiny_binary':
        best = INF
        for bits in itertools.product([0, 1], repeat=len(c)):
            x = np.array(bits, float)
            if Ai.shape[0] and np.any(Ai @ x > bi + 1e-9): continue
            best = min(best, c @ x)
        assert abs(best - obj) < 1e-6 * (1 + abs(best)), "HiGHS disagrees with brute force"
    return st, obj
with open(sys.argv[1], 'w') as f:
    f.write("// Generated by verification/milp/generate_reference.py (SciPy/HiGHS milp + brute force); do not edit.\n#pragma once\n#include <cmath>\n#include <vector>\n#define INF INFINITY\nnamespace milp_reference {\n")
    f.write("struct Case { const char *kind; int n, mi, me; std::vector<double> ai, ae, c, bi, be, lb, ub, integer; int status; double objective; };\n")
    f.write("inline const std::vector<Case> &cases() {\n  static const std::vector<Case> v = {\n")
    for kind, c, Ai, bi, Ae, be, lb, ub, im in probs:
        st, obj = reference(c, Ai, bi, Ae, be, lb, ub, im, kind)
        f.write('    {"%s", %d, %d, %d, {%s}, {%s}, {%s}, {%s}, {%s}, {%s}, {%s}, {%s}, %d, %s},\n' % (kind, len(c), Ai.shape[0], Ae.shape[0], fmt(Ai), fmt(Ae), fmt(c), fmt(bi), fmt(be), fmt(lb), fmt(ub), fmt(im), st, "NAN" if st else repr(float(obj))))
    f.write("  };\n  return v;\n}\n} // namespace milp_reference\n")
print("cases:", len(probs))
